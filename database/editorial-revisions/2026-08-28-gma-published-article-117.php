<h2>Gate 5: residu, hygiene, dan mutu</h2>

<p>Maximum residue limits bergantung pada active ingredient, commodity, dan market. Program residu perlu dimulai dari daftar pestisida yang diizinkan, pre-harvest interval, application record, sampling plan, metode laboratorium, serta action limit. Sertifikat analisis hanya bernilai bila sample mewakili lot dan metode diterima oleh buyer atau regulator.</p>

<p><a href="https://www.fao.org/fao-who-codexalimentarius/codex-texts/all-standards/en/" target="_blank" rel="noopener noreferrer">Codex Alimentarius</a> menyediakan General Principles of Food Hygiene, Code of Hygienic Practice for Fresh Fruits and Vegetables, serta Code of Practice for Packaging and Transport of Fresh Fruit and Vegetables. Gunakan sebagai referensi sistem, lalu sesuaikan dengan hukum tujuan dan kontrak.</p>

<p>Kontrol packhouse mencakup kebersihan air, food-contact surface, worker hygiene, pest control, chemical handling, foreign matter, damaged produce, temperature, cleaning verification, serta segregasi lot. Jangan menunggu hasil akhir untuk mengetahui bahwa lot tidak sesuai; tetapkan hold-and-release pada titik kritis.</p>

<h2>Gate 6: desain cold chain per komoditas</h2>

<p>Cold chain bukan sekadar mengatur reefer pada satu angka. Produk harus dipanen pada maturity yang tepat, terlindung dari panas lapangan, dipre-cool dengan metode yang sesuai, dikemas agar aliran udara bekerja, dan dimonitor selama perjalanan. Set point yang salah dapat mempercepat kerusakan atau menyebabkan chilling injury.</p>

<ul>
<li>Tentukan pulp temperature target sebelum loading, bukan hanya ambient temperature.</li>
<li>Validasi airflow, ventilation, humidity, ethylene sensitivity, dan compatibility antarproduk.</li>
<li>Pastikan kemasan tidak menutup ventilasi dan pallet pattern tidak menghambat sirkulasi.</li>
<li>Gunakan calibrated data logger pada posisi yang mewakili risiko, dengan serial number tercatat.</li>
<li>Tetapkan alarm threshold, penerima alarm, response time, dan escalation path.</li>
<li>Rekonsiliasi waktu panen, pre-cooling, stuffing, gate-in, loading, transit, dan availability.</li>
</ul>

