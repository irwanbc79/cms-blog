<h2>Gate 3: tindakan karantina dan phytosanitary</h2>

<p>Badan Karantina Indonesia menyediakan akses registrasi dan permohonan tindakan karantina melalui portal resminya. <a href="https://jdih.karantinaindonesia.go.id/storage/common/dokumen/Perba14tahun2024.pdf" target="_blank" rel="noopener noreferrer">Peraturan Badan Karantina Indonesia Nomor 14 Tahun 2024</a> mengatur tindakan karantina dan pengawasan terintegrasi. Untuk tumbuhan ekspor, sertifikat kesehatan tumbuhan diterbitkan setelah media pembawa dikenai tindakan karantina dan memenuhi persyaratan yang relevan.</p>

<p><a href="https://www.ippc.int/en/publications/609/" target="_blank" rel="noopener noreferrer">ISPM 12 dari International Plant Protection Convention</a> memberi pedoman penyiapan dan penerbitan phytosanitary certificate untuk ekspor serta re-ekspor. Bila negara menggunakan pertukaran elektronik, <a href="https://www.ippc.int/en/ephyto/" target="_blank" rel="noopener noreferrer">ePhyto</a> adalah bentuk elektronik sertifikat fitosanitari; kesiapan dan mekanisme pertukaran harus dikonfirmasi untuk pasangan negara aktual.</p>

<p>Eksportir tidak boleh menyusun additional declaration sendiri berdasarkan contoh shipment lama. Teks harus mengikuti persyaratan negara tujuan dan dapat didukung oleh hasil pemeriksaan, treatment, test, atau status area produksi yang benar.</p>

