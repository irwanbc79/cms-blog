<h2>Red flags yang harus menghentikan proses</h2>

<ul>
<li>Buyer tidak dapat menunjukkan import condition atau permit untuk komoditas aktual.</li>
<li>Nama botani, varietas, asal, atau intended use berbeda antardokumen.</li>
<li>Kebun/packing house digunakan sebelum status registrasi atau approval yang dipersyaratkan diverifikasi.</li>
<li>Additional declaration disalin dari eksportir lain atau shipment lama.</li>
<li>Treatment dilakukan tanpa parameter, kalibrasi, operator, dan record yang memadai.</li>
<li>Certificate of analysis tidak dapat ditelusuri ke lot shipment.</li>
<li>Produk dimuat hangat lalu reefer diharapkan melakukan seluruh proses pre-cooling.</li>
<li>Tim menjanjikan penerbitan sertifikat, clearance, atau penerimaan tujuan sebelum pemeriksaan.</li>
<li>Perubahan bank account, consignee, atau shipping instruction tidak diverifikasi melalui kanal kedua.</li>
</ul>

<h2>Checklist go, hold, atau stop</h2>

<ol>
<li>Komoditas, nama botani, bentuk produk, dan intended use final.</li>
<li>HS serta lartas diperiksa pada tanggal shipment.</li>
<li>Import permit dan persyaratan NPPO/food authority tujuan tersedia.</li>
<li>Kebun, packhouse, treatment facility, dan laboratorium memenuhi requirement yang berlaku.</li>
<li>Pest, additional declaration, treatment, sampling, dan test plan ditutup.</li>
<li>MRL, hygiene, mutu, grade, size, dan label disetujui buyer.</li>
<li>Packing trial dan cold-chain protocol telah divalidasi.</li>
<li>Carrier menerima commodity, container, temperature, ventilation, dan routing.</li>
<li>Invoice, packing list, certificate, booking, dan data PEB direkonsiliasi.</li>
<li>Contingency untuk delay, excursion, rejection, dan claim memiliki owner.</li>
</ol>

<h2>Kesimpulan</h2>

<p>Ekspor hortikultura adalah sistem kendali mutu, biosecurity, dan waktu. Product-destination dossier menentukan requirement; traceability menghubungkan kebun ke carton; tindakan karantina mendukung phytosanitary certification; dan cold chain menjaga kondisi yang telah dibangun sejak panen. Tidak satu pun berdiri sendiri.</p>

<p>GMA World dapat membantu menyusun shipment matrix, document register, dan cold-chain checklist. Persyaratan fitosanitari, sertifikat, acceptance, biaya, serta jadwal final tetap harus dikonfirmasi menggunakan data aktual kepada buyer, carrier, laboratorium, Barantin, Bea Cukai, dan otoritas negara tujuan.</p>

