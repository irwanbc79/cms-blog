<h2>Simulasi memilih udara atau laut reefer</h2>

<p>Angka berikut hanya contoh cara menghitung dan bukan tarif atau tingkat kegagalan pasar. Misalkan nilai produk USD 12.000 dan perusahaan memasukkan biaya kehilangan mutu sebagai expected cost.</p>

<table>
<thead><tr><th>Asumsi internal</th><th>Udara</th><th>Laut reefer</th></tr></thead>
<tbody>
<tr><td>Freight dan handling terkonfirmasi</td><td>USD 4.500</td><td>USD 2.000</td></tr>
<tr><td>Monitoring/plug tambahan</td><td>USD 100</td><td>USD 300</td></tr>
<tr><td>Probabilitas loss berdasarkan histori perusahaan</td><td>5%</td><td>12%</td></tr>
<tr><td>Expected product loss</td><td>5% × 12.000 = USD 600</td><td>12% × 12.000 = USD 1.440</td></tr>
<tr><td>Total terukur</td><td>USD 5.200</td><td>USD 3.740</td></tr>
</tbody>
</table>

<p>Dalam contoh, laut masih lebih rendah USD 1.460. Keputusan dapat berubah jika shelf-life buffer, rejection exposure, missed connection, stockout, atau required delivery date berbeda. Ganti probabilitas dengan histori commodity-route-season milik perusahaan; jangan menyalin angka simulasi sebagai forecast.</p>

<h2>Contoh kontrol lot sebelum booking</h2>

<p>Shipment hipotetis berisi 4.000 kg buah segar dalam 400 carton. Packing list menyatakan 10 kg net per carton dan 40 carton per pallet sehingga terdapat 10 pallet. Sebelum booking final, tim merekonsiliasi:</p>

<ul>
<li>400 × 10 kg = 4.000 kg net;</li>
<li>gross weight menambahkan carton, liner, pallet, corner board, dan material pengaman;</li>
<li>setiap pallet memiliki mapping lot kebun serta packing date;</li>
<li>phytosanitary quantity tidak melebihi lot yang diperiksa;</li>
<li>label carton, invoice, packing list, booking, dan PEB memakai identitas produk yang konsisten;</li>
<li>container dan seal ditambahkan setelah stuffing, tidak ditebak sebelumnya.</li>
</ul>

<p>Bila satu pallet berasal dari lot yang belum released, shipment berstatus hold sampai disposition diberikan. Mengganti label untuk menyamarkan lot akan merusak traceability dan memperbesar exposure saat pemeriksaan atau recall.</p>

