<h2>Checklist 6 langkah prosedur operasional ekspor agribisnis ke ASEAN</h2>

<ol>
<li><strong>Registrasi Kebun &amp; Packing House di Otoritas Karantina (Barantin):</strong> Memastikan fasilitas pembersihan dan sortasi produk memiliki nomor registrasi resmi yang diakui negara mitra ASEAN.</li>
<li><strong>Pengujian Laboratorium Mutu &amp; Batas Residu Pestisida:</strong> Melakukan uji pra-ekspor pada laboratorium terakreditasi KAN untuk memastikan kandungan MRL di bawah ambang batas regulasi pangan negara tujuan.</li>
<li><strong>Pengajuan Permohonan Pemeriksaan Karantina (PPK Online Barantin):</strong> Petugas karantina melakukan sampling kargo untuk menerbitkan Sertifikat Fitosanitari (KT-1).</li>
<li><strong>Pengurusan Pemberitahuan Ekspor Barang (PEB) &amp; Penerbitan NPE:</strong> Melakukan submit dokumen kepabeanan BC 3.0 pada portal CEISA 4.0 DJBC.</li>
<li><strong>Penerbitan Surat Keterangan Asal Elektronik (e-SKA ATIGA Form D):</strong> Memproses e-Form D di instansi penerbit SKA (IPSKA Kemendag) agar data mengalir ke sistem bea cukai negara tujuan via ASW.</li>
<li><strong>Pengapalan Kargo Menggunakan Kontainer Reefer Terkalibrasi:</strong> Memastikan pra-pendinginan kontainer (pre-cooling) sesuai suhu komoditas sebelum muatan dimuat ke atas kapal kargo laut.</li>
</ol>

