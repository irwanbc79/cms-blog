<h2>Skema tarif preferensi ATIGA Form D &amp; integrasi ASEAN Single Window (ASW)</h2>

<p>Pemanfaatan skema ATIGA membebaskan importir negara tujuan dari bea masuk impor, meningkatkan daya saing harga komoditas Indonesia:</p>

<ul>
<li><strong>Kriteria Asal Barang (Rules of Origin / ROO):</strong> Komoditas agribisnis murni hasil panen Indonesia memenuhi kriteria <em>Wholly Obtained (WO)</em>, sedangkan produk pangan olahan wajib memiliki kandungan nilai regional (<em>Regional Value Content / RVC &ge; 40%</em>) atau perubahan klasifikasi pos tarif (<em>Change in Tariff Classification / CTC</em>).</li>
<li><strong>Penerbitan Surat Keterangan Asal Elektronik (e-Form D):</strong> Diajukan melalui sistem e-SKA Kementerian Perdagangan RI dan ditransmisikan secara elektronik secara langsung (<em>Host-to-Host</em>) melalui platform <em>ASEAN Single Window (ASW)</em> menuju sistem kepabeanan negara tujuan tanpa perlu pengiriman fisik dokumen hardcopy.</li>
<li><strong>Pemberitahuan Ekspor Barang (PEB BC 3.0):</strong> Deklarasi nilai FOB dan HS Code 8 digit yang akurat pada CEISA 4.0 DJBC guna memperoleh persetujuan Nota Pelayanan Ekspor (NPE).</li>
</ul>

<h2>Sertifikasi fitosanitari Barantin (PP 29/2023) &amp; standar mutu MRL</h2>

<p>Kepatuhan fitosanitari menjamin kargo agribisnis bebas dari organisme pengganggu tumbuhan karantina (OPTK):</p>

<ul>
<li><strong>Pemeriksaan Fisik &amp; Laboratorium Barantin:</strong> Pengambilan sampel kargo di kebun atau rumah pengemasan (<em>registered packing house</em>) untuk uji laboratorium residu pestisida, cemaran timbal (Pb), kadmium (Cd), dan mikotoksin (Aflatoksin).</li>
<li><strong>Penerbitan Phytosanitary Certificate (KT-1):</strong> Diterbitkan secara resmi oleh Badan Karantina Indonesia setelah komoditas dinyatakan memenuhi seluruh persyaratan sanitasi dan fitosanitari (SPS) negara tujuan ekspor.</li>
<li><strong>Perlakuan Pasca Panen &amp; Fumigasi ISPM 15:</strong> Fumigasi Phospine (PH3) dosis 2 g/m³ selama 120 jam untuk biji-bijian/kopi kering sesuai standar AFAS atau perlakuan pencucian disinfektan food-grade (Klorin/Ozon) untuk buah segar guna mematikan spora jamur pasca panen.</li>
<li><strong>Standar Good Agricultural Practices (IndoGAP / GlobalG.A.P.):</strong> Sertifikasi budidaya kebun pertanian yang menjamin jejak keterlacakan (traceability) dari bibit, penggunaan pupuk organik, hingga panen ramah lingkungan.</li>
<li><strong>Mutual Recognition Agreement (MRA) Sertifikasi Halal:</strong> Pengakuan timbal balik sertifikat halal Badan Penyelenggara Jaminan Produk Halal (BPJPH) dengan JAKIM Malaysia dan MUIS Singapura untuk memperlancar distribusi produk turunan agribisnis olahan.</li>
</ul>

<h2>Metode pembayaran ekspor agribisnis &amp; asuransi pengangkutan laut (ICC A)</h2>

<p>Manajemen risiko transaksi keuangan dan perlindungan fisik kargo pertanian selama pengapalan:</p>

<ul>
<li><strong>Metode Pembayaran Transaksi Agribisnis (L/C vs CAD vs TT Advance):</strong> Penggunaan <em>Irrevocable Letter of Credit (L/C at Sight)</em> atau kombinasi uang muka <em>Telegraphic Transfer (TT 30% Down Payment + 70% against Bill of Lading scan)</em> memberikan kepastian arus kas eksportir sebelum barang tiba di pelabuhan tujuan.</li>
<li><strong>Asuransi Pengangkutan Kargo Laut (Institute Cargo Clauses / ICC A):</strong> Penutupan asuransi kargo menyeluruh (All Risks) termasuk klausul khusus kerusakan mesin reefer (<em>Reefer Breakdown Clause</em> minimal 24 jam) guna melindungi eksportir dari risiko finansial pembusukan buah akibat kerusakan genset kapal.</li>
<li><strong>Klausul Force Majeure &amp; Demurrage Agreement:</strong> Penetapan toleransi waktu bongkar muat (free time demurrage/detention minimal 7–14 hari di pelabuhan tujuan) dalam kontrak jual beli (Sales Contract) untuk mengantisipasi antrean inspeksi karantina.</li>
</ul>

