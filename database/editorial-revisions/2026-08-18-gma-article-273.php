<h2>Checklist evaluasi supplier ready mix</h2>

<ul>
<li>Kesesuaian mix design dengan spesifikasi dan persetujuan engineer.</li>
<li>Sumber material, hasil uji, sistem penakaran, dan status kalibrasi plant.</li>
<li>Kapasitas plant, jarak ke proyek, rute, jam operasi, dan rencana trafik.</li>
<li>Jumlah serta kondisi armada, dispatch system, dan plant cadangan.</li>
<li>Isi delivery ticket, identitas batch, waktu batching, volume, dan traceability.</li>
<li>Prosedur bila slump, suhu, waktu, atau kondisi visual tidak sesuai.</li>
<li>Tanggung jawab sampling, laboratorium, hasil uji, dan penanganan dispute.</li>
<li>Syarat minimum order, waiting, pembatalan, sisa beton, dan pekerjaan malam.</li>
</ul>

<p>Jangan mengandalkan label “ready mix” sebagai bukti mutu. Minta data dan sepakati acceptance plan. Pengawas di lapangan harus memiliki wewenang untuk menahan penempatan ketika kondisi tidak sesuai prosedur proyek.</p>

<h2>Checklist kesiapan site mix</h2>

<ul>
<li>Mix design dan trial mix telah disetujui oleh pihak berwenang di proyek.</li>
<li>Penakaran menggunakan metode yang ditetapkan, dengan alat terkalibrasi.</li>
<li>Kadar air agregat diperiksa dan koreksi air campuran dikendalikan.</li>
<li>Material dipisahkan, terlindung dari kontaminasi, dan dapat ditelusuri.</li>
<li>Kapasitas mixer dan feeding memenuhi laju pengecoran yang direncanakan.</li>
<li>Ada alat cadangan, sumber daya, spare part, dan rencana saat breakdown.</li>
<li>Setiap batch dicatat: waktu, material, kuantitas, operator, dan lokasi penempatan.</li>
<li>Tim QC, alat uji, sampling, curing benda uji, dan laboratorium telah siap.</li>
</ul>

<p>Bila proyek tidak mampu menjalankan kontrol tersebut secara konsisten, selisih harga material tidak menggambarkan biaya sebenarnya. Keputusan yang jujur harus memasukkan kemampuan organisasi, bukan hanya kemampuan mesin.</p>

<h2>Rencana hari pengecoran</h2>

<p>Lakukan pre-pour meeting dengan engineer, pengawas, supplier, pelaksana, QC, safety, pump, dan logistik. Konfirmasi kesiapan bekisting dan perancah, tulangan dan embedded item, akses, pencahayaan, cuaca, tenaga, vibrator dan cadangan, jalur komunikasi, metode sampling, urutan penempatan, titik berhenti darurat, finishing, serta curing.</p>

<p>Untuk ready mix, susun slot kedatangan berdasarkan laju penempatan, bukan hanya kapasitas plant. Truk yang datang terlalu rapat menciptakan antrean dan risiko waktu; terlalu jarang mengganggu kontinuitas. Untuk site mix, uji satu siklus lengkap dan ukur output stabil sebelum mengecor elemen kritis.</p>

<p>Penambahan air di lapangan tidak boleh menjadi jalan pintas untuk workability. Setiap penyesuaian harus mengikuti spesifikasi, prosedur, dan otorisasi proyek serta dicatat. Hal yang sama berlaku untuk perubahan admixture, urutan campuran, atau waktu penggunaan.</p>

<h2>Contoh keputusan, bukan resep</h2>

<p><strong>Skenario A:</strong> volume besar, akses truk dan pump tersedia, kebutuhan laju tinggi, serta plant dengan kapasitas dan dokumentasi memadai berada dalam jangkauan. Ready mix layak masuk shortlist, tetapi rute, interval truk, contingency, dan acceptance plan tetap harus divalidasi.</p>

<p><strong>Skenario B:</strong> lokasi terpencil dengan akses truk terbatas, pasokan material dapat dikontrol, proyek memiliki batching yang memadai, tenaga QC, laboratorium, dan waktu produksi. Site mix dapat dievaluasi, namun keputusan tetap mengikuti desain serta persetujuan tenaga ahli.</p>

<p><strong>Skenario C:</strong> volume kecil tetapi elemen struktural padat tulangan dan akses sulit. Harga per m3 bukan faktor tunggal. Tim perlu mengevaluasi metode penempatan, workability, ukuran agregat, kapasitas alat, dan kemampuan menjaga mutu pada elemen tersebut.</p>

