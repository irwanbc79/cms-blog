<h2>Gate 1: pemanfaatan fasilitas Bea Masuk 0% ATIGA e-Form D</h2>

<p>Perjanjian perdagangan bebas intra-ASEAN (<a href="https://asean.org/our-communities/economic-community/asean-trade-in-goods-agreement-atiga/" target="_blank" rel="noopener noreferrer">ATIGA</a>) memberikan pembebasan tarif Bea Masuk (0%) untuk hampir seluruh komoditas agribisnis Indonesia:</p>

<ol>
<li><strong>Kriteria Asal Barang (Rules of Origin):</strong>
  <ul>
    <li><strong>Wholly Obtained (WO):</strong> Berlaku mutlak untuk komoditas hasil bumi mentah, buah segar, biji rempah, dan sayuran yang seluruhnya ditanam dan dipanen di wilayah teritorial Indonesia. Eksportir wajib membuktikan asal kebun atau surat pernyataan asal komoditas petani.</li>
    <li><strong>Regional Value Content (RVC &ge; 40%) atau CTH:</strong> Berlaku untuk produk agribisnis olahan (seperti minyak kelapa olahan, santan kemasan, briket arang, atau bumbu masak instan) di mana minimal 40% nilai tambah berasal dari negara anggota ASEAN atau terjadi perubahan pos tarif 4 digit.</li>
  </ul>
</li>
<li><strong>Transmisi Elektronik e-Form D (ASEAN Single Window):</strong> Eksportir mengajukan e-SKA Form D melalui portal e-SKA Kementerian Perdagangan RI. Setelah disetujui, data e-Form D ditransmisikan secara elektronik melalui gateway ASW ke sistem kepabeanan negara tujuan (misalnya Singapore Customs atau Royal Malaysian Customs Department), menghilangkan kewajiban pengiriman dokumen fisik asli via kurir.</li>
</ol>

<h2>Gate 2: sertifikasi karantina tumbuhan Barantin &amp; protokol SPS</h2>

<p>Setiap pengapalan agribisnis wajib memenuhi standar Sanitary and Phytosanitary (SPS) yang diselaraskan di tingkat regional ASEAN:</p>

<ul>
<li><strong>Pemeriksaan Fitosanitari &amp; Penerbitan KT-2:</strong> Petugas Badan Karantina Indonesia melakukan sampling fisik dan uji laboratorium di instalasi karantina pelabuhan muat untuk memastikan kargo bebas dari lalat buah (<em>Bactrocera spp.</em>), kutu putih (<em>Pseudococcidae</em>), kumbang penggerek, dan spora cendawan patogen.</li>
<li><strong>Kepatuhan ASEAN MRLs (Batas Maksimum Residu Pestisida):</strong> Komoditas buah dan sayuran segar wajib memenuhi ambang batas residu kimia yang ditetapkan oleh ASEAN Harmonized MRLs. Penggunaan pestisida terlarang atau konsentrasi di atas batas toleransi memicu penahanan kargo di pelabuhan bongkar.</li>
<li><strong>Sertifikasi Kemasan Pallet Kayu (ISPM 15):</strong> Seluruh pallet kayu wajib memiliki stempel perlakuan panas (<em>Heat Treatment - HT</em>) resmi IPPC untuk mencegah penyebaran hama penggerek kayu antar-negara ASEAN.</li>
</ul>

<h2>Gate 3: regulasi khusus negara tujuan utama</h2>

<p>Eksportir wajib menyelaraskan pengapalan dengan persyaratan spesifik otoritas tujuan:</p>

<ul>
<li><strong>Singapura — Singapore Food Agency (SFA):</strong> Eksportir buah dan sayuran segar wajib terdaftar di sistem SFA melalui importir berlisensi di Singapura. Setiap kemasan karton wajib mencantumkan label ketertelusuran (nama kebun, nomor registrasi packing house, tanggal panen, dan nomor lot).</li>
<li><strong>Malaysia — Department of Agriculture (DOA) &amp; MAFI:</strong> Importir di Malaysia wajib mengantongi <em>Import Permit (e-Permit)</em> yang diterbitkan DOA Malaysia sebelum kapal bertolak dari Indonesia. Untuk produk olahan pangan, sertifikasi halal BPJPH diakui penuh melalui MRA dengan JAKIM Malaysia.</li>
<li><strong>Thailand — Department of Agriculture (DOA Thailand):</strong> Mensyaratkan sertifikasi kebun Good Agricultural Practices (GAP) dan fasilitas packing house yang memenuhi standar Good Manufacturing Practices (GMP).</li>
<li><strong>Filipina — Bureau of Plant Industry (BPI):</strong> Mewajibkan importir memiliki dokumen Sanitary and Phytosanitary Import Clearance (SPSIC) yang masih berlaku sebelum tanggal pengapalan kargo.</li>
</ul>

<h2>Gate 4: tata laksana kepabeanan ekspor (PMK 155/PMK.04/2022)</h2>

<p>Prosedur pabean ekspor agribisnis ke ASEAN diselesaikan melalui sistem CEISA 4.0 Ekspor:</p>

<ol>
<li><strong>Transmisi Pemberitahuan Ekspor Barang (PEB BC 3.0):</strong> Eksportir atau PPJK menginput data invoice, packing list, nomor Phytosanitary Certificate, dan nomor e-Form D ke sistem pabean.</li>
<li><strong>Penerbitan Nota Pelayanan Ekspor (NPE):</strong> Untuk eksportir dengan profil risiko baik dan komoditas non-lartas ketat, sistem otomatis menerbitkan NPE (Jalur Hijau) sehingga kontainer dapat langsung masuk ke dermaga pelabuhan (CY Gate-In).</li>
<li><strong>Penanganan Pemuatan Kapal Cepat (Short-Sea Cut-Off):</strong> Mengingat jadwal feeder intra-ASEAN sangat padat dan ketat, proses *stuffing* kontainer dan penyelesaian dokumen pabean wajib selesai minimal 12–24 jam sebelum waktu penutupan gerbang pelabuhan (CY Closing Time).</li>
</ol>

