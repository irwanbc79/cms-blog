<h2>Checklist 6 langkah audit ekspor agribisnis ke ASEAN</h2>

<ol>
<li><strong>Validasi Dokumen Import Permit / SFA Traceability:</strong> Pastikan importir telah mengantongi izin impor (DOA/BPI) dan kode registrasi kebun tercantum pada label kemasan karton.</li>
<li><strong>Inspeksi Karantina Barantin di Packing House:</strong> Lakukan pemeriksaan fisik sampling dan perlakuan sanitasi sebelum buah dimasukkan ke dalam kontainer reefer.</li>
<li><strong>Pra-Pendinginan Kontainer (Pre-Cooling Protocol):</strong> Pastikan suhu kontainer reefer telah mencapai set-point yang ditentukan (+10°C untuk manggis, +4°C untuk sayuran) sebelum proses *stuffing* dimulai.</li>
<li><strong>Transmisi e-Form D di Portal e-SKA:</strong> Kirimkan deklarasi e-Form D segera setelah B/L terbit agar terintegrasi di gateway ASEAN Single Window sebelum kapal sandar.</li>
<li><strong>Transmisi PEB BC 3.0 di CEISA 4.0:</strong> Deklarasikan pos tarif 8 digit dan nomor dokumen pelengkap ekspor secara presisi untuk penerbitan NPE otomatis.</li>
<li><strong>Monitoring Cold Chain Data Logger:</strong> Unduh grafik data logger suhu saat kontainer dibuka di pelabuhan tujuan sebagai bukti kepatuhan rantai dingin bagi pihak buyer.</li>
</ol>

