<h2>Mekanisme formula harga acuan bursa SGX SICOM &amp; penyesuaian diferensial</h2>

<p>Dalam perdagangan karet alam internasional, harga tidak ditetapkan secara angka mati (<em>fixed price</em>) melainkan mengacu pada formula resmi bursa komoditas:</p>

<ul>
<li><strong>Formula Floating Price:</strong> <code>Harga Ekspor (US Cents/kg) = [Rata-Rata SGX SICOM TSR20 Bulan Pengapalan] + [Diferensial Pabrik]</code>.</li>
<li><strong>Penentuan Nilai Diferensial:</strong> Pabrik remah karet dengan sertifikasi ISO 9001 dan reputasi pasokan stabil ke pabrik ban tier-1 (seperti Bridgestone, Michelin, atau Goodyear) berhak menuntut diferensial positif (premi +1,5 hingga +3,0 US Cents/kg). Sebaliknya, eksportir baru tanpa track record biasanya menerima diferensial netral atau diskon kecil.</li>
<li><strong>Klausul Penetapan Nilai Tukar (Currency Hedging):</strong> Transaksi komoditas karet wajib berdenominasi Dolar Amerika Serikat (USD). Eksportir wajib memanfaatkan fasilitas <em>forward contract</em> perbankan untuk mengunci kurs rupiah terhadap USD guna menjaga margin keuntungan produksi.</li>
</ul>

<h2>Strategi pemilihan Incoterms 2020: Mengapa FOB lebih aman daripada CIF?</h2>

<p>Pemilihan terminologi pengapalan internasional menentukan alokasi biaya dan perpindahan risiko kerusakan kargo:</p>

<ul>
<li><strong>FOB (Free on Board):</strong> Eksportir bertanggung jawab atas biaya transportasi lokal (trucking), pengujian mutu laboratorium, fumigasi ISPM 15, jasa PPJK, dan THC pelabuhan muat hingga barang dimuat ke kapal. Setelah kargo melewati pagar kapal (on board), seluruh risiko freight laut dan transit ditanggung oleh buyer. Sangat ideal untuk kargo komoditas curah dan kontainer karet.</li>
<li><strong>CIF (Cost, Insurance, and Freight):</strong> Eksportir wajib membayar freight kapal ke negara tujuan dan menutup asuransi kargo laut. Dalam situasi krisis jalur pelayaran (seperti lonjakan biaya rute Laut Merah atau kelangkaan kontainer kosong), eksportir dapat mengalami kerugian besar jika freight rate melonjak drastis setelah kontrak ditandatangani.</li>
</ul>

<h2>Manajemen klaim mutu pasca pengapalan &amp; pembiayaan ekspor LPEI</h2>

<p>Penyelesaian perselisihan spesifikasi teknis dan fasilitas pembiayaan perdagangan ekspor:</p>

<ul>
<li><strong>Klausul Joint Survey Independent:</strong> Apabila pembeli di pelabuhan tujuan mengajukan klaim mutu (misalnya dugaan kelebihan kadar abu atau penurunan elastisitas), kontrak wajib mensyaratkan inspeksi ulang bersama oleh surveyor independen bertaraf internasional (seperti SGS atau Inspectorate) dengan biaya ditanggung oleh pihak yang terbukti keliru.</li>
<li><strong>Fasilitas Pembiayaan Ekspor Lembaga Pembiayaan Ekspor Indonesia (LPEI / Indonesia Eximbank):</strong> Eksportir dapat memanfaatkan fasilitas Kredit Modal Kerja Ekspor (KMKE) dan Asuransi Piutang Dagang (Trade Credit Insurance) untuk mengantisipasi wanprestasi pembeli luar negeri dan memperkuat arus kas pengadaan getah karet petani.</li>
<li><strong>Integrasi Dokumen Pabean PEB BC 3.0 &amp; e-SKA Form E:</strong> Menyerahkan salinan dokumen kepabeanan resmi sesegera mungkin agar proses pencairan dana L/C di bank devisa tidak mengalami diskrepansi administrasi.</li>
<li><strong>Ketentuan Dokumen Force Majeure:</strong> Mencantumkan klausul keadaan kahar yang diakui secara internasional (seperti embargo pelabuhan, perang, atau bencana alam cuaca ekstrem) untuk membebaskan eksportir dari denda keterlambatan pengapalan.</li>
</ul>

