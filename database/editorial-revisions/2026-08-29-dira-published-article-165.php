<h2>Checklist 5 tahapan negosiasi kontrak ekspor karet bagi pelaku usaha</h2>

<ol>
<li><strong>Verifikasi Kredibilitas Finansial Pembeli:</strong> Melakukan pemeriksaan latar belakang buyer melalui laporan kredit perbankan (Bank Reference Report) atau platform asuransi ekspor ASEI/LPEI.</li>
<li><strong>Penyusunan Lembar Penawaran Formal (Firm Offer Sheet):</strong> Menyusun penawaran tertulis yang merinci spesifikasi mutu SIR 20, formula harga SICOM, kuantitas bulanan, pelabuhan muat, masa berlaku penawaran, dan opsi Incoterms FOB.</li>
<li><strong>Negosiasi Batas Toleransi Mutu &amp; Sampling:</strong> Memastikan kontrak memuat klausul bahwa sertifikat mutu laboratorium independen (seperti Sucofindo atau SGS) di pelabuhan muat bersifat mengikat secara final (final at loading port).</li>
<li><strong>Review Dokumen Draft L/C Bersama Bank Devisa:</strong> Memeriksa seluruh syarat dokumen pada draft L/C sebelum dibuka oleh buyer untuk memastikan tidak ada klausul yang mustahil dipenuhi (non-compliance clauses).</li>
<li><strong>Finalisasi Penandatanganan Sales Contract:</strong> Membubuhkan tanda tangan direksi berwenang dan meterai hukum pada dokumen kontrak dagang resmi.</li>
</ol>

