<h2>4 model klasifikasi fasilitas warehousing industri</h2>

<ol>
<li><strong>Dedicated Raw Material Hub (Gudang Bahan Baku Pabrik):</strong> Fasilitas penyimpanan yang berlokasi berdampingan dengan kawasan pabrik manufaktur/smelter untuk menjamin kontinuitas pasokan lini perakitan 24 jam dengan metode <em>Just-in-Time (JIT)</em>.</li>
<li><strong>Multi-User Industrial Logistics Center:</strong> Fasilitas pergudangan bersama modern di kawasan industri terpadu (Kawasan Industri MM2100, KIIC Karawang, Jababeka, KIM Medan, JIIPE Gresik) yang melayani konsolidasi kargo banyak perusahaan manufaktur.</li>
<li><strong>Heavy Equipment &amp; Project Cargo Open Yard:</strong> Lapangan terbuka berfondasi padat berkerikil/aspal heavy-duty dengan pengamanan pagar perimeter dan CCTV untuk menimbun alat berat pertambangan, pipa minyak bumi, trafo gardu listrik, dan struktur beton precast.</li>
<li><strong>Hazardous Material &amp; Chemical Storage (Gudang Khusus B3):</strong> Gudang berpembatas tahan api khusus yang dilengkapi tanggul penahan tumpahan cairan kimia (<em>containment bund wall minimal 110% kapasitas tangki</em>), ventilasi tahan ledakan (<em>explosion-proof exhaust</em>), dan shower dekontaminasi darurat.</li>
</ol>

<h2>Rekayasa ventilasi, charging station forklift &amp; tata ruang K3</h2>

<p>Fasilitas gudang industri berstandar modern mengadopsi prinsip efisiensi energi dan keselamatan kerja operasional:</p>

<ul>
<li><strong>Sistem Ventilasi Alami &amp; Sirkulasi Udara (Louvre &amp; Turbine Ventilator):</strong> Pemasangan louvre dinding perimeter dan ventilator atap otomatis menjamin laju pergantian udara (<em>Air Changes per Hour / ACH</em>) minimal 4–6 kali per jam guna mengeluarkan panas akumulasi mesin forklift dan uap kimia industri.</li>
<li><strong>Pencahayaan Alami &amp; Lampu High-Bay LED:</strong> Panel atap tembus cahaya skylight polycarbonate mencakup <strong>8% s.d. 12% dari total luas atap</strong> memberikan penerangan 200–300 Lux pada siang hari, didukung lampu LED High-Bay hemat energi berstandar 150 Lux di lorong simpan dan 300 Lux di area staging.</li>
<li><strong>Stasiun Pengisian Baterai Forklift (Battery Charging Bay):</strong> Ruang khusus pengisian baterai forklift elektrik yang terisolasi, dilengkapi kipas pembuang gas hidrogen otomatis, detektor gas, dan bak pencuci mata darurat (eyewash station).</li>
<li><strong>Drainase Pemisah Minyak &amp; Standar Palet ISPM 15:</strong> Saluran pembuangan air pelataran dilengkapi bak penangkap oli (oil trap interceptor) untuk mencegah pencemaran lingkungan kawasan industri, serta area penyimpanan kayu kemasan berstandar sertifikasi fumigasi ISPM 15 Badan Karantina Indonesia.</li>
<li><strong>Marka Jalur Lalu Lintas Lantai Epoxy (Permenaker 8/2020):</strong> Pembagian zona visual yang tegas menggunakan cat epoxy tahan abrasi: jalur utama forklift selebar 3,5 meter (garis kuning tebal), jalur pejalan kaki pedestrian 1,0 meter (garis hijau), dan zona dilarang berhenti di depan panel listrik/hydrant (garis merah silang).</li>
<li><strong>Konektivitas Multimoda (Dry Port &amp; Koridor Tol Pelabuhan):</strong> Lokasi gudang industri strategis yang terhubung langsung dengan akses jalan tol bebas hambatan dan terminal peti kemas dry port memangkas waktu tunggu distribusi antarmoda.</li>
</ul>

<h2>Kepatuhan legalitas: Tanda Daftar Gudang (TDG) &amp; Izin Lingkungan</h2>

<p>Pengoperasian gudang distribusi industri wajib memenuhi legalitas formal Republik Indonesia:</p>

<ul>
<li><strong>Kewajiban Tanda Daftar Gudang (TDG):</strong> Berdasarkan Permendag 25/2021, seluruh fasilitas gudang tertutup maupun terbuka dengan luas minimal 100 m² wajib mengantongi dokumen TDG resmi melalui sistem Perizinan Berusaha Berbasis Risiko OSS RBA.</li>
<li><strong>Persetujuan Bangunan Gedung (PBG) &amp; Sertifikat Laik Fungsi (SLF):</strong> Memastikan struktur baja gedung telah melalui uji kelayakan teknik konstruksi dan keselamatan beban gempa dari Dinas PUPR setempat.</li>
<li><strong>Izin Pengelolaan Bahan Berbahaya dan Beracun (AMDAL / UKL-UPL):</strong> Fasilitas yang menyimpan bahan kimia industri wajib memiliki dokumen pengelolaan lingkungan hidup dan SOP tanggap darurat tumpahan (Spill Response Protocol).</li>
</ul>

