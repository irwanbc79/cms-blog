<h2>Checklist 5 langkah audit fisik &amp; kepatuhan vendor pergudangan industri</h2>

<ol>
<li><strong>Verifikasi Dokumen TDG dan Kesesuaian Zonasi Kawasan:</strong> Pastikan lahan pergudangan berada di dalam peruntukan Kawasan Industri atau Zona Pergudangan resmi tata ruang daerah (RTRW).</li>
<li><strong>Inspeksi Fisik Ketebalan Lantai dan Tanda Keretakan:</strong> Periksa apakah lantai bebas dari lendutan (deflection) dan retak struktural akibat beban titik berat.</li>
<li><strong>Uji Kelayakan Radius Putar Armada Berat:</strong> Simulasikan akses truk kontainer 40ft dari gerbang masuk tol terdekat hingga posisi mundur di dermaga bongkar.</li>
<li><strong>Pemeriksaan Fasilitas K3 dan Izin Operasi Alat (SIO/SILO):</strong> Pastikan operator overhead crane dan forklift reach truck memiliki lisensi K3 resmi Kementerian Ketenagakerjaan.</li>
<li><strong>Evaluasi Asuransi Properti &amp; Tanggung Gugat Pihak Ketiga:</strong> Pastikan gedung dilindungi polis asuransi komprehensif <em>Property All Risks (PAR)</em> dan <em>Warehouseman Liability</em>.</li>
</ol>

