<h2>Pre-shipment gate</h2>

<p>Status <em>go</em> diberikan hanya setelah buyer spec final, lot lulus release, certificate requirement dipenuhi, HS/lartas selesai, commercial documents direkonsiliasi, booking cocok, dan owner menandatangani checklist. Gunakan <em>hold</em> bila masih ada hasil uji, draft certificate, payment security, atau document correction. Gunakan <em>stop</em> bila barang tidak memenuhi spec atau transaksi tidak dapat dipenuhi secara sah.</p>

<p>Jalankan pre-stuffing inspection: container condition, odor, moisture, cleanliness, bag/pallet condition, label, lot, quantity, weight, seal, desiccant bila sesuai, dan foto. Catat siapa hadir serta waktu. Setelah stuffing, perubahan data harus melewati exception approval.</p>

<h2>Cost and exception matrix</h2>

<p>Hitung harga bahan, processing, testing, treatment, packaging, inland transport, terminal, customs service, karantina, certificate, freight, insurance, finance, commission, dan buffer claim. Buat skenario normal, re-test, rework, treatment tambahan, roll-over kapal, storage, document amendment, dan buyer rejection.</p>

<p>Margin di spreadsheet bukan hasil akhir sampai specification, yield, exchange rate, freight, payment cost, dan claim exposure dikunci. Setiap asumsi memiliki sumber, tanggal, owner, dan status aktual atau estimasi.</p>

<h2>Review setelah shipment</h2>

<p>Bandingkan rencana dengan hasil aktual: quantity, mutu, hasil uji, treatment, dokumen, waktu, biaya, discrepancy, claim, dan payment. Perbarui supplier scorecard, product master, buyer profile, contract clause, dan checklist. Jangan memakai certificate atau COA lot lama untuk shipment baru.</p>

