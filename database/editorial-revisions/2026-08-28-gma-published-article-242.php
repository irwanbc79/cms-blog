<h2>Apa yang dikerjakan agen kapal?</h2>

<p>PM 59 Tahun 2021 membagi kepentingan kapal menjadi operasional dan komersial. Dalam lingkup operasional, tugas dapat mencakup pelaporan rencana serta realisasi kedatangan dan keberangkatan, penyerahan dokumen kepada penyelenggara pelabuhan dan instansi terkait, pengurusan jasa kepelabuhanan, koordinasi perusahaan bongkar muat, pengurusan kebutuhan kapal, penyampaian informasi kepada principal, dan aktivitas lain yang disepakati.</p>

<p>Lingkup komersial dapat mencakup pencarian muatan dan pemesanan ruang muat atas nama principal, tetapi tidak boleh dianggap otomatis melekat pada setiap appointment. Siapa yang boleh menjalankan kepentingan komersial, menandatangani bill of lading, mengurus freight, atau menunjuk vendor harus sesuai izin, kemitraan, surat penunjukan, dan batas kewenangan yang berlaku.</p>

<p>Agen bukan Syahbandar, Bea Cukai, Imigrasi, Karantina, pengelola terminal, surveyor, atau pihak klasifikasi. Agen mengoordinasikan kesiapan dan menyampaikan data, sedangkan keputusan pemeriksaan, persetujuan, pelayanan, keselamatan, serta clearance tetap berada pada pihak yang berwenang.</p>

