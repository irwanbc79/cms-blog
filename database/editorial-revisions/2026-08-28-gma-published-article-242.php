<h2>Alur port call yang dapat diaudit</h2>

<h3>1. Intake dan conflict check</h3>

<p>Validasi identitas principal, pihak yang memberi instruksi, beneficial ownership sesuai prosedur perusahaan, data kapal, port rotation, cargo interest, serta potensi konflik dengan charterer atau agen lain. Tetapkan nomor port call unik. Satu kapal dapat memiliki beberapa pihak komersial, tetapi data master dan rantai instruksi harus tetap tunggal.</p>

<h3>2. Pre-arrival planning</h3>

<p>Buat timeline mundur dari ETA berdasarkan batas waktu aktual setiap instansi dan terminal. Kunci data kapal, last port, next port, crew list, kegiatan bongkar atau muat, dangerous goods bila ada, draft, kebutuhan tug/pilot, berth window, bunker, freshwater, provision, garbage, repair, crew change, dan kebutuhan khusus lainnya. Bila data berubah, catat versi, waktu, pengirim, penerima, serta dampaknya.</p>

<h3>3. Pelaporan dan koordinasi layanan</h3>

<p>Sampaikan data melalui kanal yang ditetapkan pemerintah dan pelabuhan. Pastikan isi antardokumen konsisten: nama kapal, IMO number, voyage, ETA/ETD, pelabuhan asal dan tujuan, manifest, jumlah kru, serta kegiatan kapal. Status “submitted” berbeda dari “accepted” atau “approved”; dashboard operasi harus membedakannya.</p>

<h3>4. Arrival, clearance in, dan operasi</h3>

<p>Pantau perubahan ETA, pilot boarding, anchorage, berth, pemeriksaan instansi, kegiatan cargo, kebutuhan kapal, dan kejadian keselamatan. Agen mencatat statement of facts dari sumber yang disepakati dan mengeskalasi deviasi material kepada principal. Keputusan master terkait keselamatan kapal tidak boleh digantikan oleh tekanan jadwal komersial.</p>

<h3>5. Clearance out dan departure</h3>

<p>Sebelum keberangkatan, rekonsiliasi penyelesaian kegiatan, dokumen kapal, crew atau passenger data, manifest, layanan pelabuhan, tagihan kritis, serta persyaratan instansi. Keberangkatan hanya dilaporkan setelah bukti dan status dari pihak berwenang tersedia; jangan mengubah “sedang diproses” menjadi “clear” untuk mengejar KPI.</p>

<h3>6. Post-departure close-out</h3>

<p>Kirim departure report, statement of facts, dokumen akhir, daftar outstanding, dan estimasi final disbursement account. Tutup port call setelah seluruh invoice diverifikasi, uang muka direkonsiliasi, selisih dijelaskan, refund atau tambahan dana diselesaikan, dan arsip disimpan sesuai kebijakan retensi.</p>

