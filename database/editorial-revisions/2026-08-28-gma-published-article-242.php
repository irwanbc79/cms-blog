<p>Waktu sandar atau turnaround time penting, tetapi tidak seluruhnya dikendalikan agen. KPI harus memisahkan waktu akibat dokumen, terminal, cuaca, kapal, muatan, vendor, dan keputusan otoritas agar evaluasi tidak mendorong penyembunyian keterlambatan.</p>

<h2>Red flags yang harus menghentikan proses</h2>

<ul>
<li>Appointment dikirim oleh pihak yang kewenangannya tidak dapat diverifikasi.</li>
<li>Nama kapal, IMO number, bendera, voyage, atau port rotation berbeda antardokumen.</li>
<li>Instruksi untuk menyatakan status telah disetujui sebelum ada bukti dari pihak berwenang.</li>
<li>Permintaan pembayaran ke rekening baru hanya melalui pesan instan.</li>
<li>Vendor bekerja tanpa quotation atau approval, lalu meminta invoice dibayar segera.</li>
<li>Data muatan berbahaya, crew, last port, atau kegiatan kapal tidak lengkap tetapi diminta tetap disubmit.</li>
<li>Sub agen menerima instruksi langsung yang bertentangan dengan agen umum atau authority matrix.</li>
<li>Dokumen lama disalin ke voyage baru tanpa pemeriksaan masa berlaku dan data kapal.</li>
</ul>

<h2>Checklist penutupan port call</h2>

<ol>
<li>Appointment dan scope tersimpan dalam berkas port call.</li>
<li>Seluruh submission memiliki bukti waktu, versi, pengirim, penerima, dan status.</li>
<li>Arrival, berth, cargo, unberth, dan departure milestones telah direkonsiliasi.</li>
<li>Statement of facts dikonfirmasi dari sumber yang disepakati.</li>
<li>Dokumen akhir kapal, crew, cargo, dan layanan telah diserahkan sesuai scope.</li>
<li>Semua vendor invoice memiliki bukti layanan dan approval.</li>
<li>Selisih proforma dan final DA dijelaskan per item.</li>
<li>Refund atau additional funding memiliki perhitungan dan jalur persetujuan.</li>
<li>Outstanding issue mempunyai owner, deadline, serta bukti penyelesaian.</li>
<li>Arsip disimpan dengan hak akses dan masa retensi yang ditetapkan.</li>
</ol>

<h2>Kesimpulan</h2>

<p>Keagenan kapal asing yang kuat dibangun dari mandat yang valid, data voyage tunggal, pembagian kewenangan tertulis, pelaporan yang dapat ditelusuri, dan kontrol biaya per transaksi. Agen memberi nilai bukan dengan menjanjikan clearance atau jadwal, tetapi dengan membuat setiap dependensi terlihat, setiap perubahan tercatat, dan setiap keputusan mempunyai pemilik.</p>

