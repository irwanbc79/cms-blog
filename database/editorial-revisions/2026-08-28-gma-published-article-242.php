<p>A berarti accountable, R responsible, C consulted, dan I informed. Matriks aktual harus mengikuti kontrak. Jika dua pihak sama-sama merasa berwenang menyetujui vendor atau biaya, hentikan order non-kritis sampai authority matrix diperjelas.</p>

<h2>Kontrol disbursement account</h2>

<p>Biaya port call rawan membesar karena quotation terlambat, perubahan kegiatan, overtime, kurs, tambahan tug, shifting, storage, atau layanan tanpa purchase approval. Gunakan proforma disbursement account dengan asumsi eksplisit: ETA, durasi, GT/LOA/draft, cargo quantity, berth, tarif, kurs, pajak, serta item yang dikecualikan.</p>

<ul>
<li>Verifikasi rekening vendor melalui kanal kedua sebelum pembayaran pertama atau perubahan rekening.</li>
<li>Terapkan pemeriksaan empat mata untuk vendor baru, uang muka, refund, dan perubahan beneficiary.</li>
<li>Hubungkan setiap invoice ke quotation, persetujuan, work order, dan bukti layanan.</li>
<li>Tandai estimated cost, committed cost, invoiced cost, paid cost, dan disputed cost secara terpisah.</li>
<li>Jangan memecah invoice atau mengubah deskripsi untuk melewati limit persetujuan.</li>
<li>Jelaskan variance proforma versus final per item, bukan hanya total akhirnya.</li>
</ul>

