<h2>6 tahapan rekayasa tata letak metode Systematic Layout Planning (SLP)</h2>

<ol>
<li><strong>Tahap 1: Pengumpulan Data P-Q-R-S-T (Product, Quantity, Routing, Supporting, Time):</strong> Menganalisis variasi produk yang diproduksi, volume produksi tahunan, urutan rute mesin, kebutuhan ruang pendukung, dan target waktu siklus (takt time).</li>
<li><strong>Tahap 2: Analisis Aliran Material (Flow of Materials Analysis):</strong> Menyusun <em>From-To Chart (Travel Chart)</em> untuk menghitung total tonase dan frekuensi perpindahan material antar-stasiun kerja per hari.</li>
<li><strong>Tahap 3: Diagram Hubungan Aktivitas (Activity Relationship Chart / ARC):</strong> Menilai derajat kedekatan kualitatif antar-departemen (A: Mutlak Dekat, E: Sangat Penting, I: Penting, O: Biasa, U: Tidak Penting, X: Tidak Boleh Berdekatan karena faktor bahaya/debu/bising).</li>
<li><strong>Tahap 4: Diagram Hubungan Ruang (Space Relationship Diagram):</strong> Menggabungkan matriks kedekatan ARC dengan kebutuhan luas lantai riil mesin, ruang gerak operator, dan area penyimpanan material WIP.</li>
<li><strong>Tahap 5: Pengembangan Alternatif Tata Letak (Block Layout Alternatives):</strong> Merancang 2 s.d. 3 opsi denah layout blok dengan mempertimbangkan batasan struktural kolom gedung dan pintu loading dock.</li>
<li><strong>Tahap 6: Evaluasi Multi-Kriteria &amp; Pemilihan Layout Terbaik:</strong> Melakukan scoring kuantitatif berdasarkan total momen perpindahan (Material Handling Distance), efisiensi biaya konstruksi, dan kemudahan ekspansi kapasitas masa depan.</li>
</ol>

<h2>Matriks zonasi fasilitas: Produksi, Logistik, dan Utilitas Pabrik</h2>

<p>Pemisahan zona fasilitas pabrik yang disiplin menjamin kepatuhan K3 dan kenyamanan lingkungan kerja:</p>

<ul>
<li><strong>Zona 1: Area Penerimaan &amp; Gudang Bahan Baku (Inbound Raw Material):</strong> Terhubung langsung dengan dermaga bongkar muat kontainer, dilengkapi sistem rak selektif dan area inspeksi kendali mutu (Incoming QC).</li>
<li><strong>Zona 2: Area Inti Proses Produksi (Core Production / Assembly Floor):</strong> Area bebas debu dengan lantai epoxy anti-statis, pencahayaan berstandar minimal <strong>300 s.d. 500 Lux</strong>, dan penataan stasiun kerja ergonomis sesuai kaidah antropometri pekerja Indonesia.</li>
<li><strong>Zona 3: Ruang Utilitas &amp; Pembangkit Energi (Isolasi Akustik &amp; Termal):</strong> Ruang genset cadangan, kompresor udara bertekanan tinggi, gardu trafo PLN, dan boiler uap wajib ditempatkan terpisah di perimeter luar pabrik dengan peredam suara khusus guna membatasi kebisingan di bawah <strong>Nilai Ambang Batas 85 dBA (Permenaker 5/2018)</strong>.</li>
<li><strong>Zona 4: Area Quality Control &amp; Laboratorium Pengujian:</strong> Ruang ber-AC dengan kontrol suhu dan kelembaban presisi untuk kalibrasi alat ukur dan uji laboratorium produk.</li>
<li><strong>Zona 5: Gudang Produk Jadi &amp; Dermaga Pengiriman (Outbound Finished Goods):</strong> Area penyimpanan akhir yang terisolasi dari debu produksi, terhubung langsung ke pintu pengeluaran kargo menuju armada truk distribusi.</li>
</ul>

<h2>Ergonomi stasiun kerja &amp; manajemen visual 5S industri manufaktur</h2>

<p>Penerapan kaidah ergonomi dan manajemen visual 5S di lantai pabrik meningkatkan produktivitas serta menurunkan tingkat kelelahan fisik operator:</p>

<ul>
<li><strong>Ketinggian Meja Kerja Ergonomis:</strong> Standar tinggi bidang kerja disesuaikan dengan jenis aktivitas: 95–105 cm untuk perakitan ringan (posisi berdiri), 85–90 cm untuk perakitan manual presisi (posisi duduk), dan 70–80 cm untuk pekerjaan manual beban berat.</li>
<li><strong>Zona Jangkauan Primer &amp; Sekunder (Reach Envelope):</strong> Seluruh perkakas kerja, tombol kontrol darurat, dan komponen perakitan wajib berada di dalam radius jangkauan primer 35–45 cm tanpa mengharuskan operator membungkuk atau memutar pinggang.</li>
<li><strong>Papan Bayangan Perkakas (Shadow Board 5S):</strong> Penempatan alat kerja perkakas menggunakan siluet warna visual untuk memastikan setiap kunci, tang, dan obeng kembali ke tempat semula setelah dipakai.</li>
<li><strong>Andon Board &amp; Sistem Visual Factory:</strong> Lampu menara sinyal Andon 3 warna di setiap lini untuk memantau status operasional secara langsung: hijau (beroperasi normal), kuning (kebutuhan pasokan material), dan merah (terjadi abnormalitas/line stop).</li>
</ul>

