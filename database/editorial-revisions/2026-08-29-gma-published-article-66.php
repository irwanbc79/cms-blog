<h2>Checklist 5 langkah audit perancangan tata letak fasilitas manufaktur</h2>

<ol>
<li><strong>Audit Kesesuaian Jalur Forklift vs Pejalan Kaki:</strong> Pastikan lorong utama selebar minimal 3,5 meter memiliki pembatas fisik (guardrail) atau marka lantai hijau pedestrian yang tegas.</li>
<li><strong>Verifikasi Radius Putar dan Clearance Antar-Mesin:</strong> Sediakan ruang bebas minimal 1,2 meter di sekeliling mesin untuk akses teknisi pemeliharaan (maintenance access) dan panel darurat.</li>
<li><strong>Pemeriksaan Pintu Evakuasi &amp; Akses Tanggap Darurat:</strong> Pastikan jarak tempuh terjauh dari titik kerja mana pun menuju pintu darurat kebakaran tidak melebihi 30 meter.</li>
<li><strong>Pengujian Tingkat Kebisingan dan Pencahayaan:</strong> Gunakan sound level meter dan lux meter untuk memastikan seluruh area kerja memenuhi standar NAB Permenaker 5/2018.</li>
<li><strong>Simulasi Fleksibilitas Ekspansi Masa Depan (Scalability):</strong> Pastikan desain blok modul pabrik memungkinkan penambahan lini produksi baru tanpa membongkar struktur utilitas utama.</li>
</ol>

