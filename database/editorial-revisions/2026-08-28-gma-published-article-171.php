<h2>Gate 1: identifikasi barang sebelum memilih HS</h2>

<p>HS code tidak dapat ditentukan dari nama pemasaran. Siapkan technical product dossier berisi material atau komposisi, fungsi, proses, bentuk, ukuran, merek/model, kondisi baru/bekas, foto, katalog, dan data keselamatan bila relevan. Untuk set atau barang campuran, uraikan setiap komponen material.</p>

<p>Classification memo internal harus mencatat kandidat HS, dasar nomenklatur dan catatan yang digunakan, alasan kandidat lain tidak dipilih, serta pihak peninjau. Jangan menyalin HS dari invoice pemasok, marketplace, atau shipment perusahaan lain tanpa memeriksa kesamaan barang.</p>

<h2>Gate 2: periksa lartas dan larangan berdasarkan tanggal</h2>

<p>Gunakan <a href="https://intr.insw.go.id/" target="_blank" rel="noopener noreferrer">Indonesia National Trade Repository pada INSW</a> untuk menelusuri HS, larangan/pembatasan, peraturan, tarif, dan rules of origin. Simpan snapshot hasil pencarian dengan tanggal rencana ekspor, HS, uraian, negara tujuan, serta tautan peraturan sumber.</p>

<p>Jika hasil menunjukkan kewajiban eksportir terdaftar, persetujuan ekspor, laporan surveyor, dokumen legalitas, rekomendasi, sertifikat kesehatan, atau persyaratan teknis lain, buat permit register. Kolomnya minimum memuat penerbit, nomor, produk/HS, quantity, port, masa berlaku, saldo, syarat laporan, dan owner.</p>

<p>Status “tidak ditemukan lartas” pada satu pencarian tidak menghapus kewajiban dari aturan sektoral atau negara tujuan. Lakukan second review untuk produk berisiko seperti mineral, kehutanan, limbah/skrap, barang berbahaya, budaya, satwa/tumbuhan, pangan, obat, atau barang strategis.</p>

<h2>Gate 3: kunci transaksi dan data pengangkutan</h2>

<p>Sebelum membuat PEB, rekonsiliasi seller-exporter, buyer-consignee, purchase order, Incoterm, currency, nilai, payment condition, origin, destination, port of loading, port of discharge, mode, carrier, vessel/flight, voyage, booking, container, package, dan target departure.</p>

<p>Perubahan consignee, destination, quantity, atau carrier setelah dokumen disiapkan harus masuk change log. Tentukan siapa yang berwenang menyetujui, dokumen apa yang harus direvisi, apakah PEB perlu dibetulkan, dan apakah izin/lartas masih sesuai.</p>

