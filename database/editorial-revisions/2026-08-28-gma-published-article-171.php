<h2>Red flags sebelum mengajukan PEB</h2>

<ul>
<li>Judul berita diperlakukan sebagai aturan tanpa membuka dokumen hukum.</li>
<li>HS dipilih dari nama komersial tanpa technical dossier.</li>
<li>Snapshot INSW tidak memiliki tanggal atau HS lengkap.</li>
<li>Permit tidak cocok dengan quantity, port, masa berlaku, atau eksportir.</li>
<li>Invoice, packing list, booking, dan fisik barang memiliki uraian atau berat berbeda.</li>
<li>Data shipment lama disalin tanpa menghapus container, seal, voyage, dan consignee.</li>
<li>NPE disampaikan kepada buyer sebagai bukti kapal telah berangkat.</li>
<li>Perubahan rekening, consignee, destination, atau HS hanya disetujui melalui pesan instan.</li>
<li>Tim diminta menjanjikan respons sistem, pemeriksaan, pemuatan, atau penerimaan tujuan.</li>
</ul>

<h2>Checklist sebelum submission</h2>

<ol>
<li>Identitas eksportir dan kewenangan pengaju tervalidasi.</li>
<li>Technical product dossier serta classification memo selesai.</li>
<li>HS dan lartas diperiksa pada INSW untuk tanggal rencana ekspor.</li>
<li>Permit register menunjukkan semua persyaratan valid dan memiliki saldo.</li>
<li>Buyer, consignee, origin, destination, Incoterm, dan nilai final.</li>
<li>Invoice, packing list, booking, quantity, unit, net, gross, dan VGM konsisten.</li>
<li>PEB direview dengan kontrol empat mata.</li>
<li>Owner untuk NPP, NPPD, PPB, dan exception sudah ditetapkan.</li>
<li>Gate-in, loading, departure, serta reconciliation dipantau terpisah.</li>
<li>Dokumen final masuk arsip dengan retention dan access control.</li>
</ol>

<h2>Kesimpulan</h2>

<p>Prosedur ekspor yang kuat tidak bergantung pada slogan “aturan terbaru”. Ia bergantung pada identifikasi barang, HS yang dapat dijelaskan, lartas bertanggal, izin yang sesuai, data PEB yang konsisten, pengelolaan setiap respons, serta bukti pemuatan dan keberangkatan.</p>

