<p>Jika pallet, dunnage, atau securing material ditambahkan, gross weight dan VGM harus memakai hasil final yang benar. Invoice, packing list, booking, shipping instruction, PEB, serta permit tidak boleh mempertahankan angka sebelum packing final bila angka tersebut sudah berubah.</p>

<h2>Pembetulan, pembatalan, dan no-silent-change</h2>

<p>PMK 155/2022 menyediakan kerangka pembetulan dan pembatalan pemberitahuan dengan kondisi serta batas waktu tertentu. Tim tidak boleh mengedit file internal setelah submission lalu menganggap data resmi ikut berubah. Setiap correction case memerlukan:</p>

<ul>
<li>nomor PEB dan versi data;</li>
<li>field lama dan field baru;</li>
<li>alasan serta bukti sumber;</li>
<li>dampak terhadap izin, bea keluar, invoice, packing, booking, dan manifest;</li>
<li>approval pihak berwenang;</li>
<li>respons sistem dan tanggal penyelesaian.</li>
</ul>

<p>Untuk pembatalan ekspor, jangan berhenti pada pembatalan booking carrier. Kewajiban pelaporan kepada Bea Cukai dan instansi penerbit izin harus diperiksa. Halaman Bea Cukai juga mencantumkan konsekuensi apabila pembatalan tidak dilaporkan atau terlambat dilaporkan.</p>

<h2>Arsip dan audit trail</h2>

<p>Ringkasan resmi PMK 155/2022 pada JDIH Kemenkeu mencantumkan kewajiban penyimpanan dokumen ekspor selama 10 tahun. Document retention register sebaiknya memuat kategori, nomor, shipment, lokasi penyimpanan, pemilik, hak akses, tanggal mulai, tanggal akhir, dan legal hold.</p>

<p>Simpan original electronic response, bukan hanya screenshot. Hubungkan PEB, NPE, invoice, packing list, izin, payment, booking, BL/AWB, terminal event, proof of departure, pembetulan, dan rekonsiliasi melalui shipment ID yang sama.</p>

