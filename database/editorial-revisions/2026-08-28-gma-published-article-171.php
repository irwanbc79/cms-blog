<h2>Memahami status dan respons proses ekspor</h2>

<p>Halaman resmi Bea Cukai menjelaskan bahwa eksportir menyampaikan PEB, kemudian dilakukan penelitian dokumen. Pemeriksaan fisik dapat dilakukan secara selektif berdasarkan manajemen risiko. Respons berbeda harus diperlakukan sebagai state yang berbeda, bukan disederhanakan menjadi “sudah masuk Bea Cukai”.</p>

