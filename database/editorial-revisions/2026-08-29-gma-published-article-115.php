<h2>Ketahanan seismik gempa (SNI 1726:2019) &amp; standar angin</h2>

<p>Perancangan struktur gedung industri wajib memitigasi potensi risiko bencana alam tektonik di wilayah Indonesia:</p>

<ul>
<li><strong>Analisis Spektrum Respons Percepatan Wilayah:</strong> Menghitung parameter percepatan gempa permukaan (Ss dan S1) sesuai peta bahaya gempa Kementerian PUPR untuk menentukan gaya geser dasar seismik (Base Shear Force).</li>
<li><strong>Sistem Rangka Pemikul Momen Khusus (SRPMK / SMF):</strong> Sambungan balok-kolom baja dirancang daktail menggunakan baut mutu tinggi (<em>High-Strength Bolt Grade 8.8 / ASTM A325</em>) yang mampu menyerap energi gempa tanpa mengalami keruntuhan getas tiba-tiba.</li>
<li><strong>Sistem Ikatan Angin &amp; Purlin Bracing (Portal Bracing):</strong> Pemasangan kabel rod diagonal dan batang pengaku pipa baja (strut tube) pada atap dan dinding perimeter guna menahan tekanan angin kencang hingga 120 km/jam serta mendistribusikan beban lateral secara merata.</li>
<li><strong>Proteksi Korosi Pelapis Baja (Epoxy Primer &amp; Hot-Dip Galvanized):</strong> Perlindungan anti-karat minimal 100–150 mikron pada elemen baja struktural untuk menjamin umur pakai struktur minimal 30–50 tahun di zona industri agresif.</li>
</ul>

<h2>Rekayasa lantai heavy-duty slab &amp; pengolahan air limbah (IPAL)</h2>

<p>Fondasi lantai operasional dan infrastruktur pengolahan lingkungan merupakan pilar vital integritas fasilitas pabrik:</p>

<ul>
<li><strong>Lantai Beton Beban Berat (Heavy-Duty Slab on Grade):</strong> Pelat lantai beton bertulang tebal 20–25 cm dengan mutu beton K-350 / fc' 30 MPa, diperkuat tulangan wiremesh ulir ganda M10 atau serat baja (steel fiber rebarless system), mampu menahan beban statis mesin hingga 8 Ton/m² dan lalu lintas forklift 5 ton tanpa mengalami retak lendutan.</li>
<li><strong>Instalasi Pengolahan Air Limbah (IPAL / WWTP Pabrik):</strong> Sistem pengolahan air limbah industri terintegrasi (fisik, kimiawi, dan biologis) yang memenuhi baku mutu air buangan Kementerian LHK sebelum dialirkan ke saluran drainase kawasan industri.</li>
<li><strong>Peredaman Getaran Mesin (Vibration Isolation Pad):</strong> Fondasi terpisah (isolated machine foundation) dengan bantalan karet elastomerik khusus untuk mesin press stamping dan genset guna mencegah perambatan getaran ke struktur utama gedung.</li>
<li><strong>Sistem Pembumian Penangkal Petir (Grounding System):</strong> Pemasangan elektroda tembaga dengan resistansi tanah di bawah 2 Ohm untuk melindungi instalasi instrumen otomatisasi PLC dari bahaya lonjakan petir.</li>
</ul>

<h2>Standar Bangunan Gedung Hijau (BGH) Permen PUPR 21/2021</h2>

<p>Fasilitas manufaktur modern mengadopsi standar keberlanjutan lingkungan guna menekan emisi karbon dan memangkas biaya utilitas operasional:</p>

<ul>
<li><strong>Insulasi Termal Selubung Bangunan (OTTV &lt; 35 W/m²):</strong> Penggunaan material atap <em>Sandwich Panel Polyisocyanurate (PIR)</em> atau lapisan <em>Glasswool Double-Layer dengan Foil Aluminium</em> mampu memantulkan panas radiasi matahari, menjaga suhu interior tetap sejuk (27°C–29°C), dan mengurangi beban pendingin udara hingga 30%.</li>
<li><strong>Integrasi Rangka Atap Solar PV Rooftop:</strong> Perancangan gording atap (purlin Z-section) dengan cadangan beban mati tambahan <strong>15 s.d. 20 kg/m²</strong> untuk mengakomodasi instalasi panel surya fotovoltaik (Solar Cell) on-grid.</li>
<li><strong>Pencahayaan Alami (Skylight Polycarbonate):</strong> Luas panel transparan 10% dari luas atap memberikan penerangan alami 300 Lux pada jam operasional 08.00–16.00 WIB tanpa listrik.</li>
<li><strong>Sistem Pemanenan Air Hujan (Rainwater Harvesting Tank):</strong> Menampung limpasan air hujan dari atap pabrik berkapasitas ribuan meter persegi untuk kebutuhan air cooling tower industri, hydrant pemadam, dan penyiraman lansekap hijau pabrik.</li>
</ul>

