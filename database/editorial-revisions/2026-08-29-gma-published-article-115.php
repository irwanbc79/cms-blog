<h2>Checklist 5 tahapan perizinan &amp; pengendalian mutu konstruksi pabrik</h2>

<ol>
<li><strong>Penyusunan Perencanaan Teknis (DED &amp; Analisis Struktur SAP2000/ETABS):</strong> Menghasilkan gambar kerja arsitektur, struktur, mekanikal elektrikal (MEP), serta perhitungan beban gempa yang ditandatangani Insinyur Profesional Berlisensi (SKA/STRA).</li>
<li><strong>Pengurusan Persetujuan Bangunan Gedung (PBG OSS PUPR):</strong> Mengajukan sidang teknis Tim Profesi Ahli (TPA) Dinas PUPR hingga Surat Bukti Kepemilikan PBG diterbitkan resmi.</li>
<li><strong>Pengendalian Mutu Fabrikasi &amp; Non-Destructive Testing (NDT):</strong> Melakukan uji radiografi (X-ray) dan pengujian ultrasonik (UT) pada sambungan las balok utama PEB di workshop fabrikator.</li>
<li><strong>Manajemen K3 Konstruksi (SMKK Permen PUPR 10/2021):</strong> Penerapan helm, rompi, body harness ganda untuk pekerja di ketinggian, jaring pengaman (safety net), dan prosedur pengangkatan beban crane (Lifting Plan).</li>
<li><strong>Uji Fungsi &amp; Penerbitan Sertifikat Laik Fungsi (SLF):</strong> Melakukan uji beban lantai (slab load test), uji commissioning sistem hidran kebakaran, genset darurat, dan grounding petir sebelum mengajukan SLF definitif ke pemerintah daerah.</li>
</ol>

