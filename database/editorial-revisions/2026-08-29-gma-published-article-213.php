<h2>Gate 1: registrasi fasilitas pangan SFDA dan kepatuhan standar Halal</h2>

<p>Untuk pasar Arab Saudi dan negara GCC, kepatuhan keamanan pangan dan sertifikasi halal menjadi prasyarat masuk mutlak:</p>

<ol>
<li><strong>Registrasi Fasilitas Pangan SFDA (Ghidha Portal):</strong> Pabrik pengolahan pangan dan agribisnis Indonesia yang mengekspor ke Arab Saudi wajib terdaftar secara resmi di portal Saudi Food and Drug Authority (SFDA). Eksportir wajib mengunggah sertifikat legalitas, HACCP, ISO 22000, dan denah alur proses sanitasi pabrik.</li>
<li><strong>Sertifikasi Halal Terakreditasi (BPJPH &amp; Halal MRA):</strong> Sertifikat Halal yang diterbitkan oleh Badan Penyelenggara Jaminan Produk Halal (BPJPH) Republik Indonesia telah memiliki kesepakatan saling pengakuan (<em>Mutual Recognition Arrangement / MRA</em>) dengan otoritas halal Arab Saudi (SFDA) dan Uni Emirat Arab (MoIAT).</li>
<li><strong>Standar Komposisi Bebas Bahan Kritis:</strong> Produk pangan olahan tidak boleh mengandung alkohol (etanol), gelatin hewani non-halal, ekstrak turunan babi (porcine), atau pewarna sintetis terlarang yang tercantum dalam standar GSO 2500.</li>
</ol>

<h2>Gate 2: standar pelabelan dwibahasa GSO 9/2013</h2>

<p>Otoritas pabean dan karantina di seluruh negara GCC (UEA, Saudi, Qatar, Kuwait, Oman, Bahrain) menerapkan inspeksi label yang sangat ketat sesuai standar <a href="https://www.gso.org.sa" target="_blank" rel="noopener noreferrer">GSO 9/2013 (Labelling of Prepackaged Foodstuffs)</a>:</p>

<ul>
<li><strong>Bahasa Wajib:</strong> Seluruh informasi pada kemasan wajib dicetak dalam <strong>Bahasa Arab dan Bahasa Inggris</strong> secara berdampingan. Penggunaan stiker terjemahan bahasa Arab (over-stickering) hanya diizinkan dengan persetujuan khusus otoritas tujuan dan harus ditempel permanen tanpa mudah lepas.</li>
<li><strong>Informasi Wajib pada Label:</strong>
  <ol>
    <li>Nama spesifik produk komoditas agribisnis;</li>
    <li>Daftar lengkap komposisi bahan (ingredients) diurutkan berdasarkan berat;</li>
    <li>Berat bersih (Net Weight) dalam satuan metrik (g / kg);</li>
    <li>Tanggal produksi (<em>Production Date</em>) dan tanggal kedaluwarsa (<em>Expiry Date</em>) dicetak jelas dengan format baku <strong>DD/MM/YYYY</strong>;</li>
    <li>Negara asal (*Country of Origin: Made in Indonesia*);</li>
    <li>Petunjuk penyimpanan khusus (misalnya: *"Store in a cool, dry place"*);</li>
    <li>Nama dan alamat lengkap produsen di Indonesia serta nama/alamat importir di negara GCC;</li>
    <li>Logo sertifikasi halal yang diakui.</li>
  </ol>
</li>
</ul>

<h2>Gate 3: sertifikasi karantina tumbuhan Barantin &amp; perlakuan ISPM 15</h2>

<p>Setiap pengapalan komoditas agribisnis segar maupun kering wajib melalui karantina ekspor:</p>

<ul>
<li><strong>Pemeriksaan Laboratorium &amp; Penerbitan KT-2:</strong> Petugas Badan Karantina Indonesia melakukan sampling fisik dan pengujian mikrobiologi di instalasi karantina berizin untuk memastikan kargo bebas dari serangga hidup, jamur berbahaya, dan nematoda karantina.</li>
<li><strong>Standar Kemasan Pallet Kayu (ISPM 15):</strong> Jika komoditas dikemas di atas pallet kayu (wooden pallets), seluruh pallet wajib telah melalui perlakuan panas (<em>Heat Treatment / HT</em>) dan dibubuhi cap resmi IPPC bersertifikasi untuk mencegah penolakan karantina di pelabuhan Timur Tengah.</li>
</ul>

<h2>Gate 4: pemanfaatan fasilitas preferensi tarif IUAE-CEPA</h2>

<p>Untuk pengapalan ke Uni Emirat Arab (UEA), eksportir dapat menikmati fasilitas pembebasan Bea Masuk 0% melalui perjanjian <a href="https://ditjenpki.kemendag.go.id" target="_blank" rel="noopener noreferrer">Indonesia-United Arab Emirates Comprehensive Economic Partnership Agreement (IUAE-CEPA)</a>:</p>

<ul>
<li><strong>Surat Keterangan Asal (e-SKA Form IUAE-CEPA):</strong> Diterbitkan secara elektronik melalui portal e-SKA Kementerian Perdagangan RI dengan memenuhi aturan asal barang (Rules of Origin) komoditas pertanian Indonesia.</li>
<li><strong>Keuntungan Tarif:</strong> Menghapus tarif Bea Masuk normal (5%) menjadi 0% di seluruh pelabuhan Uni Emirat Arab (seperti Jebel Ali Dubai, Khalifa Port Abu Dhabi, dan Sharjah).</li>
<li><strong>Pengapalan ke Negara GCC Lain:</strong> Untuk pengapalan ke Arab Saudi, Qatar, atau Kuwait, gunakan SKA Non-Preferensi (Form B) atau dokumen legalisasi perdagangan yang disyaratkan kamar dagang bilateral (KADIN Indonesia–Middle East).</li>
</ul>

