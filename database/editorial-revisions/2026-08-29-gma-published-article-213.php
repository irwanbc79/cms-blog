<h2>Checklist 6 langkah audit ekspor agribisnis ke Timur Tengah</h2>

<ol>
<li><strong>Verifikasi Registrasi SFDA / MoIAT:</strong> Pastikan nama pabrik dan produk telah terdaftar aktif pada portal regulator pangan negara tujuan.</li>
<li><strong>Audit Desain Label Kemasan Sesuai GSO:</strong> Pastikan teks dwibahasa Arab-Inggris, tanggal format DD/MM/YYYY, dan logo halal tercetak jelas tanpa kesalahan transliterasi.</li>
<li><strong>Pengujian Laboratorium Bebas Cemaran:</strong> Lakukan uji lab independen untuk parameter aflatoksin, kadar air (&lt;12%), dan residu pestisida sebelum pengemasan.</li>
<li><strong>Sertifikasi Barantin &amp; Pallet ISPM 15:</strong> Selesaikan inspeksi fitosanitari dan pastikan seluruh pallet kayu memiliki cap stempel panas resmi.</li>
<li><strong>Penerbitan e-SKA Form IUAE-CEPA / Form B:</strong> Ajukan SKA segera setelah Bill of Lading terbit untuk memastikan dokumen tiba sebelum kapal bersandar di pelabuhan Teluk.</li>
<li><strong>Monitoring Rantai Dingin (Untuk Produk Segar):</strong> Jika menggunakan Reefer Container, pasang data logger suhu independen di dalam kontainer untuk memantau stabilitas suhu sepanjang pelayaran.</li>
</ol>

