<h2>Checklist 5 langkah audit kesiapan ekspor kemiri bagi pelaku usaha</h2>

<ol>
<li><strong>Verifikasi Kadar Air &amp; FFA Lot Produksi:</strong> Memastikan hasil uji oven menunjukkan kadar air di bawah 4% dan asam lemak bebas di bawah 1% sebelum pengemasan.</li>
<li><strong>Uji Bebas Aflatoksin Laboratorium Terakreditasi:</strong> Mengantongi sertifikat Certificate of Analysis (CoA) kadar aflatoksin total di bawah 10 ppb dari laboratorium KAN.</li>
<li><strong>Pemberitahuan Ekspor Barang (PEB BC 3.0):</strong> Mendaftarkan dokumen PEB ke CEISA 4.0 DJBC untuk penerbitan Nota Pelayanan Ekspor (NPE).</li>
<li><strong>Sertifikasi Fitosanitari &amp; Fumigasi Barantin:</strong> Memastikan fumigasi selesai dan sertifikat KT-1 terbit sebelum kontainer dimuat ke kapal.</li>
<li><strong>Penyusunan Shipping Documents untuk Buyer:</strong> Menyerahkan set dokumen asli (B/L, Commercial Invoice, Packing List, CoA, KT-1, dan SKA Form B/Form AK) kepada pembeli di negara tujuan.</li>
</ol>

<h2>Kesimpulan</h2>

<p>Keberhasilan <strong>ekspor kemiri</strong> ke pasar internasional ditentukan oleh konsistensi pengawalan standar mutu fisik SNI 01-3172-1992, pengendalian kadar air rendah di bawah 4%, mitigasi cemaran aflatoksin melalui pengemasan vakum modern, sertifikasi karantina Barantin yang kredibel, serta kepatuhan deklarasi kepabeanan PEB BC 3.0 yang presisi.</p>

<p>PT Dira Anugerah Mandiri (Dira) menyediakan layanan terintegrasi ekspor komoditas rempah dan minyak nabati: Pengusaha Pengurusan Jasa Kepabeanan (PPJK) resmi DJBC, pengurusan sertifikat karantina tumbuhan Barantin (KT-1), jasa fumigasi standar ISPM 15, penerbitan Surat Keterangan Asal (SKA/COO), serta reservasi ruang muat kontainer kargo laut internasional. Seluruh operasional dijalankan secara legal, profesional, dan taat regulasi Republik Indonesia.</p>

