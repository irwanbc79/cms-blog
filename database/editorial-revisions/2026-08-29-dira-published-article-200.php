<h2>Prosedur pengeringan, sortasi, dan pencegahan oksidasi lemak</h2>

<p>Untuk mempertahankan mutu fisik dan warna putih gading alami kemiri kupas selama pengiriman laut jarak jauh:</p>

<ul>
<li><strong>Prosedur Pemecahan Tempurung Bertahap:</strong> Biji kemiri gelondongan direbus atau diangin-anginkan sebelum dipecahkan secara mekanis atau manual menggunakan pisau pemecah presisi agar biji tidak remuk.</li>
<li><strong>Pengeringan Terkontrol (Dehydration Chamber):</strong> Menggunakan ruang pengering oven suhu 40°C–50°C selama 12–18 jam hingga kadar air turun di bawah 4%. Hindari penjemuran langsung di atas aspal jalanan untuk mencegah kontaminasi debu dan bakteri.</li>
<li><strong>Sortasi Warna &amp; Ukuran (Optical Sorting):</strong> Memisahkan biji putih super dari biji bintik kuning atau keriput guna memenuhi grade premium pasar kosmetik Timur Tengah.</li>
<li><strong>Sistem Pengemasan Vakum (Vacuum Pack Barrier):</strong> Kemiri kupas dikemas dalam kantong vakum polietilena food-grade 10 kg atau 25 kg berlapisan anti-oksigen (EVOH) yang melindungi komoditas dari kelembaban udara luar.</li>
</ul>

<h2>Persyaratan fitosanitari Badan Karantina Indonesia (Barantin)</h2>

<p>Kepatuhan sertifikasi karantina tumbuhan wajib diselesaikan sebelum kontainer masuk kawasan pabean:</p>

<ul>
<li><strong>Pengajuan Permohonan Pemeriksaan Karantina (PPK Online):</strong> Eksportir mengajukan data komoditas melalui sistem otomasi Barantin minimal 3 hari sebelum rencana pemuatan kargo.</li>
<li><strong>Pemeriksaan Fisik &amp; Sampling Laboratorium:</strong> Petugas fungsional karantina mengambil sampel biji kemiri untuk menguji keberadaan serangga hidup, kumbang gudang (<em>Tribolium castaneum</em>), dan cendawan berbahaya.</li>
<li><strong>Perlakuan Fumigasi Standar AFAS (Phospine PH3):</strong> Kargo kemiri wajib difumigasi menggunakan gas fosfin dengan dosis 2–3 gram/m³ selama 120 jam pemaparan, dibuktikan dengan <em>Fumigation Certificate</em> resmi.</li>
<li><strong>Penerbitan Phytosanitary Certificate (KT-1):</strong> Terbit setelah kargo dinyatakan sehat dan bebas OPTK karantina guna memenuhi ketentuan Sanitary and Phytosanitary (SPS) WTO.</li>
</ul>

<h2>Peluang hilirisasi: Ekspor minyak kemiri murni (Cold-Pressed Candlenut Oil)</h2>

<p>Selain biji kemiri mentah, produk olahan turunan kemiri memiliki margin profitabilitas yang sangat tinggi di pasar internasional:</p>

<ul>
<li><strong>Minyak Kemiri Ekstraksi Dingin (Cold-Pressed Oil):</strong> Diekstraksi tanpa pemanasan tinggi untuk menjaga kandungan asam lemak esensial (asam linoleat dan asam oleat), vitamin E alami, dan antioksidan yang sangat diminati oleh industri perawatan rambut dan kosmetik di Uni Eropa dan Amerika Serikat.</li>
<li><strong>Klasifikasi Pos Tarif Minyak Kemiri:</strong> Didaftarkan pada pos tarif HS Code 1515.90.90 (Minyak nabati lainnya dan fraksinya) dengan kemasan jeriken food-grade atau drum baja berlapis epoxy 200 liter.</li>
<li><strong>Sertifikasi Halal BPJPH &amp; HACCP:</strong> Produk minyak kemiri olahan yang ditujukan untuk pasar Timur Tengah wajib melampirkan Sertifikat Halal dari Badan Penyelenggara Jaminan Produk Halal (BPJPH) dan sertifikasi sistem manajemen keamanan pangan HACCP / ISO 22000.</li>
<li><strong>Penataan Muatan Kontainer &amp; Desiccant Dry Bag:</strong> Pemasangan kantong silika gel desiccant gantung seberat 1–2 kg per sudut dinding kontainer untuk menyerap kelembaban udara tropis dan mencegah terbentuknya kondensasi (<em>container sweat</em>) yang dapat merusak label karton kemasan.</li>
<li><strong>Fasilitas Tarif Preferensi SKA Elektronik:</strong> Pemanfaatan Surat Keterangan Asal (e-SKA Form D untuk ASEAN, Form AK untuk Korea Selatan, atau Form B untuk Timur Tengah) yang diterbitkan melalui portal resmi Kementerian Perdagangan RI untuk memberikan pembebasan bea masuk bagi importir.</li>
</ul>

