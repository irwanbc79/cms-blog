<h2>Gate 1: pemenuhan SNI Wajib dan Pertimbangan Teknis Kemenperin</h2>

<p>Untuk melindungi standar keselamatan bangunan dan industri domestik, Kementerian Perindustrian Republik Indonesia memberlakukan standardisasi ketat untuk komoditas material konstruksi:</p>

<ol>
<li><strong>Sertifikat Produk Penggunaan Tanda SNI (SPPT SNI):</strong> Pabrik pembuat di China harus telah diaudit sistem mutunya oleh Lembaga Sertifikasi Produk (LSPro) yang terakreditasi Komite Akreditasi Nasional (KAN), dan produk harus memiliki nomor SPPT SNI yang masih aktif.</li>
<li><strong>Penandaan Label SNI (Marking):</strong> Setiap batang baja, dus keramik, atau kemasan semen wajib memiliki tanda SNI yang di-emboss atau dicetak permanen sesuai regulasi teknis. Barang yang tiba tanpa label SNI sah tidak dapat diloloskan uji kesesuaian di pelabuhan bongkar.</li>
<li><strong>Pertimbangan Teknis (Pertek):</strong> Dokumen rekomendasi kuota dan verifikasi kapasitas yang diterbitkan oleh Kemenperin melalui portal Sistem Informasi Industri Nasional (SIINas) sebagai prasyarat penerbitan Persetujuan Impor (PI) di Kementerian Perdagangan RI.</li>
</ol>

<h2>Gate 2: pemanfaatan fasilitas preferensi tarif Form E ACFTA / RCEP</h2>

<p>Material konstruksi impor dari China dapat menikmati pembebasan atau penurunan Bea Masuk hingga 0% melalui skema <em>ASEAN-China Free Trade Area (ACFTA)</em> atau <em>Regional Comprehensive Economic Partnership (RCEP)</em>:</p>

<ul>
<li><strong>Surat Keterangan Asal (SKA / Form E):</strong> Diterbitkan oleh Otoritas Bea Cukai China (China Customs / CCPIT) dengan mencantumkan kriteria asal barang (<em>Origin Criteria</em>, misalnya CTC atau RVC minimal 40%).</li>
<li><strong>Aturan Pengapalan Langsung (Direct Consignment):</strong> Kontainer kargo harus dikapalkan langsung dari pelabuhan China ke pelabuhan Indonesia. Jika terjadi transit di negara ketiga (misalnya alih kapal di Singapura atau Hong Kong), importir wajib memiliki <em>Through Bill of Lading</em> atau dokumen <em>Non-Manipulation Certificate</em> dari otoritas kepabeanan transit.</li>
<li><strong>Deklarasi Form E pada Dokumen PIB:</strong> Nomor referensi dan tanggal Form E wajib dideklarasikan secara tepat pada kolom fasilitas dokumen Pemberitahuan Impor Barang (BC 2.0) saat transmisi sistem CEISA.</li>
</ul>

<h2>Gate 3: penetapan nilai pabean (PMK 144/PMK.04/2022)</h2>

<p>Berdasarkan <a href="https://jdih.kemenkeu.go.id" target="_blank" rel="noopener noreferrer">PMK 144/PMK.04/2022</a> tentang Nilai Pabean untuk Penghitungan Bea Masuk, Pejabat Bea Cukai menguji apakah nilai transaksi yang dideklarasikan pada invoice merupakan harga yang sebenarnya dibayar atau seharusnya dibayar:</p>

<ul>
<li><strong>Metode I (Nilai Transaksi Barang Impor):</strong> Nilai faktur komersial yang didukung bukti bayar perbankan (Telegraphic Transfer / L/C swift MT700), bukti pemesanan (PO/Sales Contract), dan pembukuan importir.</li>
<li><strong>Biaya Penambah Nilai Pabean:</strong> Biaya pengangkutan (freight) hingga pelabuhan tujuan, premi asuransi pengangkutan laut (marine cargo insurance), dan biaya pengemasan/handling wajib ditambahkan ke dalam Nilai Pabean jika belum termasuk dalam harga faktur (basis CIF).</li>
<li><strong>Risiko Penetapan Notul (Nota Pembetulan):</strong> Jika nilai transaksi ditolak karena bukti perbankan tidak memadai atau dicurigai terjadi *undervaluation*, Pejabat Bea Cukai berwenang menetapkan nilai pabean berdasarkan Metode II s.d. VI (data harga pembanding/database pabean), yang mengakibatkan denda administrasi pabean dan lonjakan tagihan pajak.</li>
</ul>

<h2>Tata laksana kepabeanan impor untuk dipakai (PMK 190/PMK.04/2022)</h2>

<p>Sesuai dengan <a href="https://jdih.kemenkeu.go.id/dok/190-pmk-04-2022/files" target="_blank" rel="noopener noreferrer">PMK 190/PMK.04/2022</a>, alur pengeluaran barang impor dari Tempat Penimbunan Sementara (TPS) pelabuhan mencakup:</p>

<ol>
<li><strong>Inward Manifest (BC 1.1):</strong> Pengangkut mentransmisikan data manifest kedatangan kapal dan nomor pos BC 1.1 ke sistem DJBC.</li>
<li><strong>Pembayaran Pajak Dalam Rangka Impor (PDRI):</strong> Importir/PPJK menghitung dan menyetorkan Bea Masuk, PPN, dan PPh Pasal 22 melalui sistem Billing Perbendaharaan Kemenkeu (MPN G3).</li>
<li><strong>Transmisi PIB (BC 2.0):</strong> Dokumen PIB disubmit melalui portal CEISA 4.0 dengan melampirkan Invoice, Packing List, B/L, Polis Asuransi, Dokumen Lartas (PI/LS), dan Form E.</li>
<li><strong>Penetapan Jalur Kepabeanan:</strong>
  <ul>
    <li><strong>Jalur Hijau:</strong> Terbit Surat Persetujuan Pengeluaran Barang (SPPB) secara otomatis tanpa pemeriksaan fisik kargo.</li>
    <li><strong>Jalur Kuning:</strong> Dilakukan pemeriksaan dokumen pendukung oleh Pejabat Pemeriksa Dokumen sebelum SPPB terbit.</li>
    <li><strong>Jalur Merah:</strong> Dilakukan pemeriksaan fisik kargo (uji sampling/periksa peti kemas di TPS) dan verifikasi dokumen sebelum SPPB terbit.</li>
  </ul>
</li>
</ol>

