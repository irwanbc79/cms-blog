<h2>Checklist 6 langkah mitigasi risiko impor material proyek</h2>

<ol>
<li><strong>Verifikasi HS Code &amp; Status Lartas Sebelum Booking:</strong> Pastikan pos tarif 8 digit tidak memiliki kewajiban PI/LS yang belum diselesaikan importir.</li>
<li><strong>Pre-Shipment Inspection (LS) Tepat Waktu:</strong> Jadwalkan inspeksi surveyor di pabrik China sebelum kontainer di-seal dan diangkut ke pelabuhan muat.</li>
<li><strong>Pemeriksaan Draft Dokumen Pengapalan:</strong> Rekonsiliasi data Shipper, Consignee, Deskripsi Barang, Gross Weight, Volume, dan HS Code antara Proforma Invoice, Packing List, B/L, dan Form E.</li>
<li><strong>Kunci Klausul Incoterms &amp; Asuransi Maritim:</strong> Gunakan terms FOB atau CFR dengan asuransi kargo menyeluruh (<em>Institute Cargo Clauses A</em>) untuk melindungi risiko kerusakan material di laut.</li>
<li><strong>Kelola Free Time Demurrage/Detention Pelabuhan:</strong> Negosiasikan fasilitas extended free time (minimal 14-21 hari) dengan carrier untuk mengantisipasi proses pengeluaran jalur merah atau verifikasi SPPB.</li>
<li><strong>Gunakan PPJK &amp; Freight Forwarder Tersertifikasi:</strong> Pastikan mitra logistik memiliki integrasi sistem CEISA 4.0 dan rekam jejak kepatuhan kepabeanan yang tinggi.</li>
</ol>

