<h2>5 jenis Izin Kerja Khusus (Permit to Work / PTW)</h2>

<p>Pekerjaan berkategori kritis wajib mengantongi persetujuan tertulis PTW dari Ahli K3 Konstruksi sebelum dieksekusi:</p>

<ul>
<li><strong>1. Working at Height Permit (Pekerjaan di Ketinggian &gt;1,8 Meter):</strong> Pemeriksaan fisik scaffolding oleh Scaffolder bersertifikasi (pemasangan Green Scaff-Tag), uji kelayakan lifeline tambatan, dan verifikasi full body harness pekerja.</li>
<li><strong>2. Hot Work Permit (Pekerjaan Panas / Pengelasan / Pemotongan Logam):</strong> Pemeriksaan area bebas bahan mudah terbakar radius 10 meter, penyiapan Alat Pemadam Api Ringan (APAR) siap pakai, dan penugasan petugas pengawas api (<em>Fire Watcher</em>).</li>
<li><strong>3. Confined Space Permit (Pekerjaan Ruang Terbatas / Galian Dalam):</strong> Pengujian kadar gas beracun ($H_2S, CO$) dan kecukupan oksigen ($O_2$ 19,5–23,5%) menggunakan gas detector terkalibrasi serta pemasangan blower ventilasi udara paksa.</li>
<li><strong>4. Lifting Operation Permit (Pengangkatan Beban Alat Berat):</strong> Verifikasi rencana pengangkatan (<em>Lifting Plan</em>), perhitungan kapasitas beban (Load Chart), uji kelayakan sling baja/shackle, dan sertifikat Surat Izin Laik Operasi (SILO) crane.</li>
<li><strong>5. Excavation Permit (Pekerjaan Penggalian Tanah &gt;1,5 Meter):</strong> Pemasangan dinding turap penahan tanah (<em>shoring / trench box</em>) untuk mencegah bahaya longsor dan pengecekan utilitas kabel pipa bawah tanah.</li>
</ul>

<h2>Sertifikasi kelayakan alat berat dan keselamatan kelistrikan proyek</h2>

<p>Kementerian Ketenagakerjaan mewajibkan pemeriksaan berkala alat berat dan instalasi kelistrikan konstruksi:</p>

<ul>
<li><strong>Surat Izin Layak Operasi (SILO) &amp; SIO:</strong> Tower Crane, Mobile Crane, Passenger Hoist, Excavator, dan Kompresor Udara wajib memiliki SILO aktif dari Disnaker/Kemnaker. Operator dan Rigger wajib memegang lisensi SIO resmi Kemnaker kelas yang sesuai dengan kapasitas beban alat berat.</li>
<li><strong>Proteksi Kelistrikan Lapangan (ELCB &amp; LOTO):</strong> Seluruh panel distribusi listrik sementara di lapangan wajib dilengkapi pemutus arus bocor tanah (<em>Earth Leakage Circuit Breaker / ELCB 30mA</em>) dan menerapkan prosedur penguncian daya (<em>Lockout / Tagout - LOTO</em>) saat pemeliharaan mesin.</li>
<li><strong>Organisasi P2K3 Proyek:</strong> Proyek dengan tenaga kerja lebih dari 100 orang wajib membentuk Panitia Pembina Keselamatan dan Kesehatan Kerja (P2K3) yang terdaftar di Disnaker setempat dan melaporkan kinerja K3 secara triwulanan.</li>
<li><strong>Pengukuran Metrik Keselamatan (LTIFR):</strong> Proyek memantau <em>Lost Time Injury Frequency Rate</em> (LTIFR) per 1.000.000 jam kerja orang untuk mengevaluasi efektivitas program nihil kecelakaan kerja (<em>Zero Accident</em>).</li>
</ul>

