<h2>Pondasi regulasi SMKK Permen PUPR No. 10 Tahun 2021</h2>

<p>Kementerian PUPR mewajibkan setiap badan usaha jasa konstruksi (kontraktor dan konsultan pengawas) menyusun dan menerapkan Dokumen <strong>Rencana Keselamatan Konstruksi (RKK)</strong> yang memuat:</p>

<ol>
<li><strong>Kepemimpinan dan Partisipasi Pekerja dalam Keselamatan Konstruksi:</strong> Komitmen tertulis direksi, pembentukan Unit Keselamatan Konstruksi (UKK) yang dipimpin oleh Ahli K3 Konstruksi bersertifikat BNSP/Kemnaker.</li>
<li><strong>Alokasi Biaya Penerapan SMKK dalam RAB:</strong> Biaya SMKK wajib dicantumkan dalam daftar kuantitas dan harga (Bill of Quantities / BOQ) sebagai mata pembayaran tersendiri (berkisar antara 1,5% hingga 2,5% dari total nilai proyek) dan dilarang dinegosiasikan atau dihapus dalam kontrak kerja.</li>
<li><strong>Evaluasi Tingkat Risiko Keselamatan Konstruksi:</strong>
  <ul>
    <li><em>Risiko Besar:</em> Nilai kontrak &gt;Rp100 Miliar, mempekerjakan &gt;100 orang, atau menggunakan teknologi tinggi/alat angkat berat berisiko fatalitas tinggi. Wajib diawasi oleh Ahli Utama K3 Konstruksi.</li>
    <li><em>Risiko Sedang:</em> Nilai kontrak Rp20 Miliar s.d. Rp100 Miliar. Diawasi oleh Ahli Madya K3 Konstruksi.</li>
    <li><em>Risiko Kecil:</em> Nilai kontrak &lt;Rp20 Miliar. Diawasi oleh Ahli Muda K3 Konstruksi / Petugas K3 Konstruksi.</li>
  </ul>
</li>
</ol>

