<h2>Checklist 5 langkah audit keselamatan kerja proyek</h2>

<ol>
<li><strong>Verifikasi Dokumen RKK &amp; Pengesahan Pengawas:</strong> Pastikan dokumen RKK telah disetujui oleh Direksi Teknis Pengguna Jasa sebelum peletakan batu pertama proyek.</li>
<li><strong>Inspeksi Harian Alat Berat dan Tagging Scaffolding:</strong> Lakukan pemeriksaan checklist harian crane sebelum beroperasi dan pastikan scaffolding bertanda <em>Green Tag</em> aktif.</li>
<li><strong>Pelaksanaan Safety Induction 100% Pekerja:</strong> Larang pekerja, subkontraktor, dan tamu memasuki area kerja aktif tanpa mengikuti induksi keselamatan dan mengenakan APD standar.</li>
<li><strong>Audit Penerbitan Permit to Work (PTW):</strong> Periksa apakah seluruh pekerjaan pengelasan dan ketinggian memiliki lembar izin kerja aktif yang ditandatangani supervisor HSE.</li>
<li><strong>Simulasi Tanggap Darurat Kebakaran &amp; Evakuasi (Drill):</strong> Laksanakan simulasi tanggap darurat minimal satu kali selama durasi siklus proyek berlangsung.</li>
</ol>

