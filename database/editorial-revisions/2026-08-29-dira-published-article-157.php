<h2>Ketentuan pemetaan geolokasi poligon kebun sawit (EUDR Traceability)</h2>

<p>Kepatuhan regulasi EUDR menuntut keterlacakan rantai pasok hingga ke tingkat petak kebun:</p>

<ul>
<li><strong>Petak Kebun Skala Kecil (&lt; 4 Hektare):</strong> Wajib mencantumkan titik koordinat GPS pusat kebun (Latitude dan Longitude) dengan presisi minimal 6 angka di belakang koma, dilengkapi dokumen legalitas Surat Tanda Daftar Budidaya (STD-B) dari dinas perkebunan daerah.</li>
<li><strong>Perkebunan Skala Menengah &amp; Korporasi (&ge; 4 Hektare):</strong> Wajib mengunggah data poligon batas perimeter kebun dalam format GeoJSON atau Shapefile (.shp) yang memetakan seluruh batas terluar hamparan tanaman sawit sesuai izin Hak Guna Usaha (HGU).</li>
<li><strong>Analisis Citra Satelit Bebas Deforestasi:</strong> Menggunakan citra satelit resolusi tinggi (Copernicus Sentinel atau Landsat) untuk memverifikasi bahwa petak kebun tidak mengalami pembukaan kanopi hutan perawan setelah tanggal batas 31 Desember 2020.</li>
<li><strong>Sistem Registrasi TRACES NT Komisi Eropa:</strong> Importir di Uni Eropa wajib memasukkan nomor referensi pernyataan uji tuntas (DDS) ke sistem kepabeanan Uni Eropa sebelum kapal diizinkan sandar dan membongkar muatan.</li>
</ul>

<h2>Moda pengapalan logistik &amp; kontrak dagang FOSFA International</h2>

<p>Pemilihan armada logistik kargo sawit disesuaikan dengan volume, jenis fraksinasi produk, dan standar kontrak maritim:</p>

<ul>
<li><strong>Kapal Tanker Kimia Curah (Chemical Product Tanker):</strong> Pilihan paling ekonomis untuk pengiriman CPO mentah dan RBD Olein skala besar (5.000 s.d. 35.000 Metrik Ton). Tangki kargo wajib dilapisi material stainless steel atau marine epoxy coating dengan sistem pemanas uap (heating coil) untuk menjaga temperatur minyak 45°C–55°C agar tidak membeku selama pelayaran melintasi Samudra Atlantik.</li>
<li><strong>Flexibag dalam Peti Kemas Dry Van 20ft:</strong> Wadah fleksibel berkapasitas 21.000 s.d. 24.000 Liter (20–22 Ton) yang dipasang di dalam kontainer 20ft standar. Sangat cocok untuk pengiriman minyak sawit olahan bernilai tinggi, specialty fats, dan shortening bagi pembeli industri skala menengah di Eropa.</li>
<li><strong>Standar Kontrak FOSFA International (FOSFA 53 / 54):</strong> Kontrak perdagangan minyak nabati laut yang mengatur toleransi deviasi muatan, prosedur pengambilan sampel tangki kapal (sampling on board), dan klausul penyelesaian sengketa klaim mutu asam lemak bebas (FFA).</li>
<li><strong>Pemeriksaan Kebersihan Tangki (Tank Cleanliness Inspection):</strong> Surveyor independen wajib menerbitkan Cleanliness Certificate untuk memastikan tangki kapal bebas dari kontaminasi muatan kargo sebelumnya (seperti minyak mineral atau bahan kimia beracun).</li>
</ul>

