<h2>Checklist 6 tahapan siklus pengadaan jasa pergudangan</h2>

<ol>
<li><strong>Tahap 1: Penyusunan Dokumen Kebutuhan (RFI / RFP Logistik):</strong> Merinci profil kargo (SKU, dimensi, berat, temperatur simpan), proyeksi throughput bulanan, dan kebutuhan integrasi IT.</li>
<li><strong>Tahap 2: Evaluasi Proposal &amp; Scoring Vendor:</strong> Menilai penawaran vendor menggunakan matriks pembobotan vendor scorecard 100 poin.</li>
<li><strong>Tahap 3: Audit Fisik Lapangan (Site Visit Inspection):</strong> Menguji secara langsung kondisi lantai, kelayakan dock leveler, kerapian lorong rak, fungsi CCTV, dan kesiapan APAR/sprinkler.</li>
<li><strong>Tahap 4: Uji Konektivitas Sistem IT (Proof of Concept API):</strong> Melakukan simulasi pengiriman data pesanan dummy antara ERP klien dengan WMS vendor untuk memastikan integritas data.</li>
<li><strong>Tahap 5: Finalisasi Kontrak WSA &amp; Service Level Agreement:</strong> Mengunci tarif, indikator kinerja KPI, batasan tanggung gugat, dan mekanisme klaim dalam kontrak hukum yang sah.</li>
<li><strong>Tahap 6: Eksekusi Inbound Awal &amp; Go-Live Monitoring:</strong> Pelaksanaan inbound bertahap dengan pendampingan tim pengawas harian selama masa stabilisasi 30 hari pertama.</li>
</ol>

