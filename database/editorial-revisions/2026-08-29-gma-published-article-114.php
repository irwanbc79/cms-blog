<h2>Standar Service Level Agreement (SLA) baku pergudangan kelas dunia</h2>

<p>Kontrak kerja sama jasa warehousing wajib mengikat penyedia layanan dengan indikator kinerja terukur (KPI):</p>

<ul>
<li><strong>Inbound Dock-to-Stock Time:</strong> Maksimal <strong>&le; 4 jam kerja</strong> sejak truk kontainer selesai dibongkar hingga seluruh barang tersimpan di lokasi rak bin dan terdata aktif di WMS.</li>
<li><strong>Order Picking &amp; Packing Accuracy:</strong> Target minimal <strong>&ge; 99,85%</strong> (Toleransi salah ambil barang / salah kemas maksimal 0,15%).</li>
<li><strong>On-Time Order Dispatch:</strong> Target minimal <strong>&ge; 99,50%</strong> untuk pesanan yang masuk sebelum batas waktu cut-off harian.</li>
<li><strong>Inventory Record Accuracy (IRA):</strong> Tingkat kesesuaian fisik terhadap sistem minimal <strong>&ge; 99,70%</strong> melalui program rutin cycle count harian.</li>
<li><strong>Batas Toleransi Kerusakan / Kehilangan (Shrinkage Allowance):</strong> Dibatasi maksimal <strong>&le; 0,10% dari total nilai perputaran barang</strong>, dengan kelebihan selisih wajib diganti rugi 100% oleh vendor.</li>
<li><strong>Waktu Tanggap Investigasi Klaim (Discrepancy Resolution):</strong> Penyelesaian laporan selisih atau kerusakan maksimal dalam waktu <strong>1x24 jam kerja</strong> didukung rekaman CCTV dan log data WMS.</li>
</ul>

<h2>Struktur biaya komersial, keamanan siber WMS &amp; tata kelola QBR</h2>

<p>Transparansi skema penagihan, perlindungan data digital, dan pengawasan performa rutin menjamin kerja sama jangka panjang yang saling menguntungkan:</p>

<ul>
<li><strong>Biaya Penyimpanan (Storage Fee):</strong> Dihitung berdasarkan volume kubikasi riil (per CBM / bulan) atau per posisi palet per hari (per Pallet-Position / Day), memberikan fleksibilitas biaya variabel yang mengikuti fluktuasi stok musiman.</li>
<li><strong>Biaya Penanganan (Handling In / Handling Out Fee):</strong> Tarif per palet atau per karton untuk aktivitas bongkar muat fisik dan pemindahan kargo dari dermaga menuju rak penyimpanan.</li>
<li><strong>Layanan Bernilai Tambah (Value-Added Services / VAS):</strong> Tarif per item untuk aktivitas khusus seperti pelabelan barcode harga, penyusunan paket bundling promosi (shrink-wrapping), dan penggantian karton master.</li>
<li><strong>Keamanan Siber &amp; Disaster Recovery WMS (ISO 27001):</strong> Server WMS vendor wajib mengimplementasikan enkripsi data TLS 1.3, autentikasi multi-faktor (MFA), pencadangan data otomatis harian di lokasi sekunder (offsite cloud backup), dan target pemulihan data (RPO &lt; 1 jam) bila terjadi gangguan server.</li>
<li><strong>Standar Pengelolaan Limbah Palet &amp; Daur Ulang:</strong> Vendor wajib memiliki SOP pemilahan sampah kardus pembungkus, pemeliharaan palet kayu berstandar ISPM 15, dan pembuangan limbah ramah lingkungan.</li>
<li><strong>Forum Evaluasi Triwulanan (QBR Meeting):</strong> Pertemuan berkala antara manajemen klien dan vendor untuk mereview pemenuhan target KPI SLA, audit laporan shrinkage, dan perencanaan kapasitas kargo menghadapi musim puncak (peak season).</li>
</ul>

<h2>Klausul kritis dalam kontrak Warehouse Service Agreement (WSA)</h2>

<ol>
<li><strong>Klausul Batasan Tanggung Jawab &amp; Asuransi (Liability &amp; Cargo Insurance):</strong> Memisahkan secara tegas antara <em>Warehouseman Legal Liability</em> (tanggung jawab vendor atas kelalaian staf) dengan kewajiban pemilik kargo memiliki polis asuransi <em>Marine Cargo / Property All Risks</em>.</li>
<li><strong>Klausul Hak Audit Fisik Bebas (Right to Audit):</strong> Klien berhak melakukan inspeksi fasilitas mendadak (spot check) dan audit stock opname berkala tanpa dapat ditolak oleh pengelola gudang.</li>
<li><strong>Klausul Keamanan Data &amp; Kerahasiaan (Data Confidentiality):</strong> Menjamin data volume penjualan, daftar pelanggan akhir, dan harga pokok barang klien tidak dibocorkan kepada pihak ketiga atau kompetitor industri.</li>
<li><strong>Klausul Penalti Kegagalan SLA (Service Level Penalties):</strong> Pemotongan tagihan jasa pergudangan bulanan (service credit) sebesar 5% s.d. 15% jika vendor gagal memenuhi target SLA yang disepakati selama 2 bulan berturut-turut.</li>
</ol>

