<h2>Gate 1: Pertimbangan Teknis Kemenperin &amp; Persetujuan Impor Kemendag</h2>

<p>Tahapan perizinan wajib diselesaikan secara runut sebelum pesanan diproduksi dan dimuat di negara asal:</p>

<ol>
<li><strong>Pertimbangan Teknis (Pertek SIINas):</strong> Pabrik pemegang API-P mengajukan permohonan Pertek melalui portal Sistem Informasi Industri Nasional (SIINas) Kemenperin. Tim verifikator menguji kapasitas produksi terpasang, data realisasi penyerapan bahan baku lokal, dan rencana produksi tahun berjalan.</li>
<li><strong>Penerbitan Persetujuan Impor (PI TPT):</strong> Berdasarkan Pertek Kemenperin yang telah disetujui, Kementerian Perdagangan menerbitkan dokumen PI TPT yang mencantumkan alokasi kuota volume (dalam satuan meter, kilogram, atau yard), spesifikasi teknis pos tarif 8 digit, dan pelabuhan tujuan bongkar.</li>
<li><strong>Verifikasi Pra-Pengapalan (Laporan Surveyor / LS):</strong> Eksportir di negara asal (seperti China, India, Taiwan, Korea) wajib menghubungi surveyor independen yang ditunjuk (misalnya Sucofindo / Surveyor Indonesia / CCIC) untuk melakukan pemeriksaan fisik kargo (uji jenis kain, gramasi, lebar kain, dan nomor roll) sebelum kontainer ditutup dan disegel.</li>
</ol>

