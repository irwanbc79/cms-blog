<h2>Gate 3: Bea Masuk Tindakan Pengamanan (BMTP) dan preferensi Form E</h2>

<p>Importir bahan baku tekstil wajib memperhitungkan komponen tarif ganda:</p>

<ul>
<li><strong>Bea Masuk MFN vs. Preferensi Form E ACFTA:</strong> Tarif dasar Bea Masuk MFN untuk kain tenun/rajut berkisar antara 5% hingga 15%. Pemanfaatan Surat Keterangan Asal (SKA) Form E ACFTA atau Form RCEP yang sah dari negara asal dapat menurunkan Bea Masuk dasar menjadi <strong>0%</strong>.</li>
<li><strong>Pungutan BMTP / BMAD (Trade Remedy Duties):</strong> Pengenaan BMTP bersifat tambahan di atas tarif dasar (misalnya tarif spesifik Rp1.500 – Rp10.000 per meter kain). Periksa apakah pos tarif yang Anda impor termasuk dalam daftar lampiran PMK Pengenaan BMTP yang sedang berlaku.</li>
<li><strong>Ketentuan Pengapalan Langsung:</strong> Form E hanya berlaku jika kargo dikapalkan langsung tanpa transit di negara ketiga, atau dilengkapi <em>Through Bill of Lading</em> dan <em>Non-Manipulation Certificate</em> jika terjadi transshipment di pelabuhan transit.</li>
</ul>

<h2>Gate 4: pengawasan fisik surveyor dan integritas IT Inventory</h2>

<p>Titik kritis operasional yang sering memicu sanksi pabean berpusat pada dua pilar pengawasan:</p>

<ol>
<li><strong>Ketepatan Data Laporan Surveyor (LS):</strong> Surveyor di negara asal memeriksa kesesuaian fisik meliputi: komposisi serat (fiber content), jenis anyaman/rajutan, gramasi (GSM - grams per square meter), lebar kain, dan pelabelan roll. Jika hasil verifikasi fisik saat kargo tiba di pelabuhan Indonesia berbeda dari data LS, dokumen PIB akan dibatalkan dan kargo berisiko terkena sanksi administratif.</li>
<li><strong>Rekonsiliasi IT Inventory Kawasan Berikat:</strong> Berdasarkan ketentuan DJBC, sistem pencatatan bahan baku pada pabrik Kawasan Berikat wajib terhubung secara real-time (*CCTV &amp; IT Inventory*) yang merekam alur: barang masuk (BC 2.7/BC 2.0), barang dalam proses produksi (WIP), bahan baku sisa (scrap/waste), hingga pengeluaran barang jadi ekspor (BC 3.0 / PEB).</li>
</ol>

