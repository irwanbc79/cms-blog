<h2>Checklist 6 langkah audit impor bahan baku tekstil</h2>

<ol>
<li><strong>Validasi Kuota PI TPT &amp; Pos Tarif:</strong> Pastikan saldo kuota volume meter/kg pada Persetujuan Impor masih mencukupi sebelum menerbitkan Purchase Order (PO).</li>
<li><strong>Pemeriksaan Fisik Pra-Pengapalan oleh Surveyor (LS):</strong> Koordinasikan inspeksi surveyor di pabrik supplier China sebelum kontainer berangkat ke pelabuhan muat.</li>
<li><strong>Pemeriksaan Draft Dokumen Impor:</strong> Sinkronkan deskripsi kain, komposisi serat, nomor roll, berat netto/bruto antara Invoice, Packing List, B/L, LS, dan Form E.</li>
<li><strong>Verifikasi Keabsahan SKA Form E ACFTA:</strong> Pastikan barcode/QR e-Form E terverifikasi di portal kepabeanan dan memenuhi kriteria asal barang (CTH/RVC).</li>
<li><strong>Transmisi PIB BC 2.0 di CEISA 4.0:</strong> Deklarasikan nomor PI, LS, dan Form E pada kolom dokumen fasilitas pabean untuk mencegah gugurnya fasilitas tarif preferensi.</li>
<li><strong>Pengelolaan IT Inventory Kepabeanan:</strong> Untuk fasilitas KB/KITE, lakukan pencatatan penerimaan bahan baku secara real-time pada sistem IT Inventory yang terhubung dengan DJBC.</li>
</ol>

