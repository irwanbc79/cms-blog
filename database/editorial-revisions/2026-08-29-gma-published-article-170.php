<h2>Parameter mutu fisik green bean standar SCA</h2>

<p>Sebelum dikemas ke dalam kontainer ekspor, laboratorium mutu eksportir wajib memvalidasi parameter fisik green coffee sesuai standar <a href="https://sca.coffee" target="_blank" rel="noopener noreferrer">SCA Green Coffee Standards</a>:</p>

<ul>
<li><strong>Kadar Air (Moisture Content):</strong> Wajib berada pada rentang <strong>10,0% hingga 12,0%</strong> (rentang target ideal pengapalan laut: 10,5% – 11,5%). Kadar air di atas 12,5% berisiko tinggi memicu jamur, sedangkan di bawah 9,5% menyebabkan biji kehilangan densitas dan karakter rasa.</li>
<li><strong>Aktivitas Air (Water Activity / aw):</strong> Nilai aktivitas air wajib di bawah <strong>0,60 aw</strong> pada suhu 25°C. Parameter ini merupakan batas aman mikrobiologis untuk mencegah spora jamur <em>Aspergillus</em> dan <em>Penicillium</em> memproduksi racun <em>Ochratoxin A (OTA)</em> selama perjalanan laut 20–40 hari.</li>
<li><strong>Defect Count (Toleransi Cacat Biji):</strong> Kategori Specialty Grade tidak mengizinkan adanya cacat primer (<em>primary defects</em> seperti full black, full sour, dried cherry, fungus damage) dan maksimal 5 poin cacat sekunder per 350 gram sampel.</li>
<li><strong>Ukuran Biji (Screen Size):</strong> Keseragaman ukuran biji (misalnya Screen 16–18 untuk Arabika premium) guna memastikan profil pemanggangan yang merata di negara tujuan.</li>
</ul>

<h2>Gate 1: mitigasi kondensasi dan kemasan hermetis</h2>

<p>Tantangan terbesar pengapalan kopi via laut adalah siklus kondensasi (<em>condensation cycle</em>). Ketika kapal berlayar dari pelabuhan tropis (suhu 30°C–34°C, kelembapan 85%) menuju perairan dingin (suhu 5°C–10°C), udara hangat di dalam kontainer akan mencapai titik embun (<em>dew point</em>), menyebabkan uap air mengembun di langit-langit baja kontainer dan menetes membasahi karung kargo (<em>cargo rain</em>).</p>

<p>Protokol proteksi kontainer wajib mencakup:</p>

<ol>
<li><strong>Kemasan Berlapis Gas Barrier (Hermetic Bags):</strong> Kopi biji dimasukkan ke dalam kantong plastik hermetis berpenghalang oksigen dan uap air tinggi (seperti GrainPro atau Ecotact) sebelum dimasukkan ke karung goni (<em>jute bag 60 kg</em>). Untuk lot mikro (<em>micro-lot</em> bernilai tinggi), gunakan kemasan <em>vacuum pack 30 kg</em> di dalam kotak karton berlapis ganda.</li>
<li><strong>Pemasangan Container Desiccant Berkadar Tinggi:</strong> Gantungkan 4 hingga 8 unit desiccant berbasis kalsium klorida (CaCl2) berdaya serap uap air minimal 200–300% dari berat desiccant di dinding bagian dalam kontainer.</li>
<li><strong>Kraft Paper Lining / Thermal Blanket:</strong> Lapisi seluruh dinding, lantai, dan atap kontainer dengan kertas kraft tebal atau <em>container thermal insulation liner</em> untuk meredam fluktuasi suhu ekstrem.</li>
<li><strong>Instruksi Pemuatan Kapal (Stowage Request):</strong> Berikan instruksi tertulis kepada carrier/forwarder agar kontainer kopi dialokasikan pada posisi <em>Under Deck / Away from Heat Sources</em> (tidak diletakkan di dek teratas yang terpapar sinar matahari langsung atau berdekatan dengan ruang mesin kapal).</li>
</ol>

<h2>Gate 2: sertifikasi karantina Barantin dan fumigasi aman</h2>

<p>Penerbitan <em>Phytosanitary Certificate</em> oleh Badan Karantina Indonesia dilakukan melalui tahapan pemeriksaan fisik dan laboratorium:</p>

<ul>
<li><strong>Uji Sampling &amp; Analisis Laboratorium:</strong> Petugas karantina mengambil sampel representatif dari Tempat Penyimpanan Kopi Terdaftar untuk uji serangga hidup, nematoda, dan cendawan.</li>
<li><strong>Protokol Fumigasi yang Aman untuk Kopi Spesialti:</strong> Jika negara tujuan mensyaratkan fumigasi wajib, gunakan perlakuan gas Fosfin (<em>Phosphine / PH3</em>) dengan dosis terkontrol atau perlakuan gas Karbondioksida (<em>CO2 Modified Atmosphere</em>). Hindari penggunaan Metil Bromida (CH3Br) dosis tinggi tanpa aerasi sempurna karena dapat meninggalkan residu kimia dan merusak skor rasa kopi.</li>
</ul>

<h2>Kepatuhan regulasi pasar internasional: EUDR dan US FDA</h2>

<p>Eksportir kopi Indonesia wajib menyelaraskan pengapalan dengan regulasi yurisdiksi importir:</p>

<ul>
<li><strong>Uni Eropa — EU Deforestation Regulation (EUDR):</strong> Mulai berlaku untuk importir kopi di Uni Eropa, mewajibkan pernyataan uji tuntas (<em>Due Diligence Statement</em>) yang menyertakan data geolokasi polygon GPS kebun kopi asal untuk membuktikan bahwa kopi dipanen dari lahan yang tidak mengalami deforestasi setelah 31 Desember 2020.</li>
<li><strong>Amerika Serikat — US FDA FSMA &amp; Bioterrorism Act:</strong> Fasilitas gudang eksportir wajib terdaftar di sistem FDA (*Food Facility Registration*) dan forwarder wajib mengirimkan *Prior Notice of Imported Food* sebelum kargo tiba di pelabuhan AS.</li>
<li><strong>Batas Maksimum Mikotoksin Ochratoxin A (OTA):</strong> Uni Eropa memberlakukan batas maksimum kandungan OTA pada green coffee sebesar 3,0 &mu;g/kg (ppb). Sertifikat analisis laboratorium independen (COA) dari Sucofindo atau laboratorium terakreditasi KAN disyaratkan untuk meloloskan kargo.</li>
</ul>

