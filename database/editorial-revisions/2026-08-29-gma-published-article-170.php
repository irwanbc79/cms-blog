<h2>Checklist 6 langkah audit ekspor kopi spesialti</h2>

<ol>
<li><strong>Validasi Uji Laboratorium Mutu:</strong> Pastikan kadar air (10,5%–11,5%), aktivitas air (&lt;0,60 aw), dan laporan cupping score telah ditandatangani Q-Grader bersertifikat.</li>
<li><strong>Verifikasi Dokumen Perizinan (SPEK &amp; ICO):</strong> Pastikan kuota SPEK masih berlaku dan data Form Kopi ICO sesuai dengan data invoice serta B/L.</li>
<li><strong>Inspeksi Fisik Kontainer Kosong (Container Survey):</strong> Periksa apakah lantai kontainer kering (bebas bau, paku menonjol, atau bekas minyak) dan tes kekedapan cahaya (<em>light-leak test</em>).</li>
<li><strong>Instalasi Sistem Proteksi Kelembapan:</strong> Pastikan seluruh karung telah terbungkus hermetis, desiccant terpasang merata, dan kertas pelapis menutupi seluruh dinding baja.</li>
<li><strong>Transmisi PEB dan Verifikasi NPE:</strong> Submit PEB BC 3.0 tepat waktu sebelum jadwal *closing time* cy gate-in pelabuhan untuk menghindari biaya penumpukan.</li>
<li><strong>Monitoring Jalur Kapal dan Notifikasi Dokumen:</strong> Kirimkan salinan dokumen (Non-Negotiable B/L, Phytosanitary, ICO, COA) ke buyer untuk persiapan pre-clearance di negara tujuan.</li>
</ol>

