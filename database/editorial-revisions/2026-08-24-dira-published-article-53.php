<p>Bandingkan minimal tiga skenario: base, quality downgrade, dan shipment delay. Premium diakui setelah buyer menyetujui sample, lot memenuhi release, serta price formula tertulis. Cerita origin mendukung pemasaran, tetapi tidak menggantikan mutu dan bukti.</p>

<h2>Dokumen dan shipment gate</h2>

<p>Setelah produk dan buyer jelas, tentukan HS serta ketentuan melalui <a href="https://www.insw.go.id/" target="_blank" rel="noopener noreferrer">Portal INSW</a>. Biji kakao dapat dikenakan Bea Keluar menurut harga referensi dan periode yang berlaku. Siapkan PEB berdasarkan invoice, packing list, serta dokumen wajib lain. PPJK dapat membantu berdasarkan kuasa, tetapi eksportir tetap perlu memeriksa data.</p>

<p>Periksa kebutuhan karantina, certificate, treatment, SKA, atau dokumen asal sesuai produk dan tujuan. Fumigation certificate tidak otomatis wajib untuk setiap shipment, dan asuransi tidak selalu menjadi kewajiban seller; keduanya mengikuti regulasi, buyer requirement, moda, dan Incoterm.</p>

<p>Jalankan pilot lot sebelum skala besar. Kirim pre-shipment sample yang benar-benar diambil dari lot, minta approval tertulis, lalu kunci retain sample. Shipment berstatus <strong>go</strong> hanya jika traceability lengkap, process record lolos, moisture stabil, physical dan sensory sesuai, laboratory result diterima, kontrak efektif, payment security jelas, serta dokumen direkonsiliasi. Gunakan <strong>hold</strong> untuk deviasi yang masih dapat diperbaiki dan <strong>stop</strong> untuk lot yang tidak dapat ditelusuri atau tidak aman.</p>

<h2>Review setelah buyer menerima barang</h2>

<p>Rekonsiliasi plan versus actual: input, yield, waktu proses, moisture, defect, flavor, hasil laboratorium, biaya, transit, arrival condition, claim, dan payment. Hubungkan feedback buyer ke batch record. Ubah SOP hanya melalui version control dan validasi; jangan mengubah proses berdasarkan satu komentar tanpa melihat data lot.</p>

<p>Dira dapat membantu membuat product dossier, batch record, mass-balance, sampling checklist, buyer-spec matrix, cost sheet, dan shipment document reconciliation. Dira tidak menjamin premium, buyer acceptance, hasil laboratorium, pelayanan kepabeanan, atau penerbitan certificate karena keputusan tersebut bergantung pada bukti dan pihak berwenang.</p>

