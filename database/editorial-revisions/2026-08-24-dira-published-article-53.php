<h2>Gate 3: drying adalah bagian dari mutu</h2>

<p>Setelah fermentasi, pengeringan harus menurunkan kelembapan secara terkendali dan merata. ICCO menyebut sekitar 7,5% sebagai moisture yang sesuai untuk penyimpanan kakao dalam kondisi tropis, sedangkan kontrak buyer dan SNI perlu diperiksa untuk batas serta metode aktual. Target angka tanpa metode ukur dan sampling yang benar dapat menyesatkan.</p>

<p>Catat tanggal, drying bed atau dryer ID, ketebalan hamparan, turning, perlindungan dari hujan, sumber panas, waktu, moisture trend, dan quantity. Hindari kontak dengan tanah, bahan bakar, asap, bahan kimia, hewan, atau komoditas berbau kuat. Pengeringan terlalu cepat atau terlalu panas dapat mengubah karakter, sedangkan pengeringan lambat dan lembap meningkatkan risiko jamur.</p>

<p>Setelah kering, stabilkan lot sebelum packing final sesuai SOP fasilitas. Ukur dari beberapa titik dan bag, bukan satu genggam dari permukaan. Alat moisture perlu diverifikasi atau dikalibrasi, dan hasil abnormal harus dikonfirmasi sebelum lot dilepas.</p>

<h2>Gate 4: sampling, cut test, dan sensory harus mewakili lot</h2>

<p>COA yang terlihat lengkap tidak berguna bila sampelnya tidak mewakili lot. Buat sampling plan berdasarkan jumlah bag, ukuran lot, risiko, dan kontrak. Catat siapa mengambil sampel, tanggal, lokasi, increment, composite sample, pembagian sample, seal, retain sample, dan chain of custody.</p>

<p>Gunakan tiga lapis evaluasi:</p>

<ol>
<li><strong>Physical:</strong> moisture, bean count atau weight, foreign matter, broken, flat, mould, insect damage, germinated, dan defect lain sesuai spec.</li>
<li><strong>Cut test:</strong> distribusi warna dan kondisi internal dengan metode serta jumlah biji yang disepakati.</li>
<li><strong>Sensory:</strong> roast dan preparation protocol yang konsisten untuk menilai cocoa flavor, acidity, bitterness, astringency, flavor notes, serta off-flavor seperti smoky, mouldy, earthy, atau hammy.</li>
</ol>

<p>Nilai cut test tidak selalu memprediksi seluruh flavor. Karena itu, keputusan premium sebaiknya tidak hanya memakai persentase fermentasi. Hubungkan process record dengan physical result dan sensory outcome, lalu perbarui SOP berdasarkan bukti batch.</p>

<h2>Gate 5: laboratory plan mengikuti risiko dan tujuan</h2>

<p>Parameter laboratorium tidak boleh disalin dari komoditas atau negara lain. Susun daftar berdasarkan bentuk produk, intended use, origin risk, buyer, dan negara tujuan. Untuk pasar pangan, buyer dapat meminta pengujian logam berat, residu pestisida, mikotoksin, mikrobiologi, atau kontaminan lain. Tetapkan satuan, metode, detection limit, acceptance limit, accreditation scope, dan disposition.</p>

<p>Untuk produk yang menuju Uni Eropa, Regulation (EU) 2023/915 menetapkan batas kontaminan menurut kategori produk pangan tertentu. Batas kadmium untuk cokelat atau cocoa powder bukan otomatis batas universal raw beans. Processor dan importir perlu menurunkan raw-material specification dari produk akhir dan prosesnya; eksportir memastikan lot diuji sesuai spec yang disetujui.</p>

<h2>Gate 6: penyimpanan dan packing mempertahankan mutu</h2>

<p>Gudang harus bersih, kering, berventilasi sesuai kebutuhan, bebas hama, dan terpisah dari bahan berbau. Gunakan pallet atau sistem yang mencegah kontak langsung dengan lantai dan dinding. Terapkan lot zoning, stock rotation, humidity monitoring, pest control, inspection, serta akses terbatas.</p>

<p>Material karung, liner, net weight, marking, bag number, label, dan pallet mengikuti kontrak. Liner dapat membantu pada kondisi tertentu tetapi juga dapat menahan kelembapan jika produk belum stabil. Keputusan kemasan harus mempertimbangkan moisture, rute, transit time, ventilasi kontainer, desiccant, dan buyer handling.</p>

<p>Sebelum stuffing, periksa kondisi kontainer: bersih, kering, bebas bau, tidak bocor, lantai layak, tidak ada residu, dan nomor serta seal dicatat. Foto harus menunjukkan lot, bag, loading pattern, container condition, dan seal tanpa membuka data sensitif yang tidak diperlukan.</p>

<h2>Gate 7: hitung yield dan premium secara defensif</h2>

<p>Harga premium bukan asumsi anggaran. Buat mass-balance dari input sampai saleable output: pod atau wet beans, hasil sortasi, fermented wet beans, dried beans, grading loss, sample, reject, dan quantity yang dapat ditagihkan. HPP per kilogram memakai quantity saleable, bukan quantity awal.</p>

