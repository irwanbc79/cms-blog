<h2>Gate 1: bangun traceability sebelum fermentasi</h2>

<p>Traceability dimulai saat penerimaan buah atau wet beans, bukan saat karung siap dikirim. Berikan ID pada supplier, kebun atau kelompok kebun, tanggal panen, tanggal penerimaan, quantity, kondisi bahan, dan batch fermentasi. Jangan mencampur bahan dari hari, kematangan, atau pemasok berbeda tanpa aturan dan catatan yang jelas.</p>

<p>Minimum batch record mencakup:</p>

<ul>
<li>batch ID, supplier ID, origin, tanggal dan waktu penerimaan;</li>
<li>quantity masuk, kondisi pod atau wet beans, serta hasil sortasi awal;</li>
<li>jenis wadah, kapasitas aktual, waktu mulai, turning atau aeration event, dan waktu selesai;</li>
<li>observasi suhu atau indikator proses sesuai SOP fasilitas;</li>
<li>cuaca atau kondisi lingkungan yang memengaruhi proses;</li>
<li>quantity keluar fermentasi, quantity setelah drying, loss, dan penyebab deviasi;</li>
<li>ID lot kering, bag number, lokasi penyimpanan, dan shipment allocation.</li>
</ul>

<p>Jika targetnya Uni Eropa, data batch perlu dihubungkan dengan dataset asal dan geolokasi yang dibutuhkan untuk EUDR. Lihat panduan <a href="/blog/cara-ekspor-kakao-ke-eropa-panduan-umkm-2025">ekspor kakao ke Uni Eropa dan shipment gate EUDR</a>. Dataset tidak boleh dibentuk belakangan dari ingatan pemasok setelah buyer meminta bukti.</p>

<h2>Gate 2: validasi SOP fermentasi per kondisi nyata</h2>

<p>ICCO menjelaskan bahwa pengembangan flavor dimulai di kebun melalui fermentasi yang benar dan dilanjutkan saat roasting oleh processor. ICCO juga menggambarkan fermentasi berlangsung pada rentang proses tertentu, tetapi angka referensi tidak boleh dipakai sebagai resep universal. Varietas, kematangan, jumlah pulp, massa batch, wadah, drainage, turning, suhu, dan cuaca memengaruhi hasil.</p>

<p>Buat SOP awal, lalu validasi dengan batch kecil yang terukur. Tetapkan rentang input, urutan kerja, checkpoint, siapa yang boleh melakukan perubahan, dan kriteria penghentian. Jangan memperpanjang proses hanya untuk mengejar angka “fully fermented” bila hasil sensory memburuk. Buyer membeli hasil, bukan lamanya fermentasi.</p>

