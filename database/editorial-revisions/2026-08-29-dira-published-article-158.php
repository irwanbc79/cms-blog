<h2>Checklist 5 tahapan prosedur operasional ekspor karet ke China</h2>

<ol>
<li><strong>Pengujian Mutu Laboratorium Terakreditasi (SNI SIR 20):</strong> Mengambil sampel dari setiap lot produksi untuk pengujian kadar kotoran, abu, dan nilai PRI guna menerbitkan Certificate of Quality.</li>
<li><strong>Pemberitahuan Ekspor Barang (PEB BC 3.0):</strong> Menginput data pengapalan pada sistem CEISA 4.0 DJBC untuk penerbitan Nota Pelayanan Ekspor (NPE).</li>
<li><strong>Pengurusan Surat Keterangan Asal Elektronik (e-SKA ACFTA Form E):</strong> Mengajukan e-Form E pada portal e-SKA Kemendag untuk transmisi data kepabeanan ke China Customs.</li>
<li><strong>Perlakuan Fumigasi Palet Kayu (ISPM 15):</strong> Memastikan seluruh palet kayu kemasan karet telah difumigasi Phospine/Metil Bromida dan dibubuhi stempel resmi ISPM 15.</li>
<li><strong>Penyusunan Shipping Dossier Lengkap ke Pembeli:</strong> Mengirimkan set dokumen asli (B/L, Commercial Invoice, Packing List, CoA, Form E, dan Fumigation Certificate) kepada pembeli di China sebelum kapal sandar.</li>
</ol>

