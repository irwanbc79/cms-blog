<h2>Rumus perhitungan bea masuk dan pajak impor di pelabuhan China</h2>

<p>Kalkulasi total pungutan impor di pelabuhan tujuan China dihitung berdasarkan nilai pabean CIF (<em>Cost, Insurance, and Freight</em>):</p>

<ol>
<li><strong>Nilai Pabean CIF (Customs Value):</strong> Nilai FOB Pelabuhan Indonesia + Asuransi Pengangkutan Laut (Insurance) + Biaya Freight Kapal ke China.</li>
<li><strong>Perhitungan Bea Masuk (Customs Import Duty):</strong>
<ul>
<li><strong>Jika Tanpa Form E (Tarif MFN):</strong> <code>Bea Masuk = Nilai CIF x 20%</code> (atau bobot volume x 1.500 RMB).</li>
<li><strong>Jika Menggunakan Form E ACFTA / RCEP:</strong> <code>Bea Masuk = Nilai CIF x 0% = Rp 0</code>.</li>
</ul>
</li>
<li><strong>Perhitungan Pajak Pertambahan Nilai Impor (Import VAT 13%):</strong>
<code>Dasar Pengenaan Pajak (DPP VAT) = Nilai CIF + Bea Masuk</code>
<code>Pajak VAT Impor = DPP VAT x 13%</code></li>
<li><strong>Total Pungutan Impor di China:</strong> <code>Total Pungutan = Bea Masuk + Pajak VAT Impor</code>.</li>
</ol>

<h2>Standar mutu teknis karet SIR 20 (SNI 1903:2017) &amp; uji laboratorium</h2>

<p>Kepabeanan GACC dan pembeli industri ban di China mensyaratkan parameter mutu ketat sebelum kargo diterima di gudang:</p>

<ul>
<li><strong>Kadar Kotoran (Dirt Content):</strong> Maksimal 0,16% berat, diuji dengan metode saringan 44 mikron untuk menjamin kebersihan kompon ban.</li>
<li><strong>Kadar Abu (Ash Content):</strong> Maksimal 0,80%, mengindikasikan tingkat kemurnian polimer getah karet tanpa kontaminasi tanah liat.</li>
<li><strong>Kadar Zat Menguap (Volatile Matter):</strong> Maksimal 0,80% untuk mencegah timbulnya gelembung udara (porositas) saat proses vulkanisasi karet.</li>
<li><strong>Plastisitas Awal (Wallace Plasticity / Po):</strong> Nilai minimal 30 untuk menjamin elastisitas dan ketahanan mekanis produk karet jadi.</li>
<li><strong>Plasticity Retention Index (PRI):</strong> Nilai minimal 50, menunjukkan ketahanan karet alam terhadap degradasi termal akibat oksidasi panas.</li>
</ul>

<h2>Persyaratan perizinan ekspor ET Karet, bursa komoditas, dan kemasan palet</h2>

<p>Kepatuhan administrasi domestik dan standar logistik kargo karet alam ekspor:</p>

<ul>
<li><strong>Eksportir Terdaftar Karet Olahan (ET Karet Kemendag):</strong> Pelaku usaha wajib mengantongi izin ET Karet dan Tanda Sah Mutu (TSM) dari Balai Pengujian dan Sertifikasi Mutu Barang (BPSMB) Kementerian Perdagangan RI.</li>
<li><strong>Hedging Harga Acuan Bursa Komoditas (SGX SICOM TSR20 &amp; SHFE):</strong> Penetapan harga kontrak ekspor umumnya mengacu pada harga rata-rata bulanan bursa berjangka <em>Singapore Exchange (SGX SICOM TSR20)</em> atau <em>Shanghai Futures Exchange (SHFE)</em> dengan penyesuaian premi/diskon kualitas mutu pabrik remah (crumb rubber factory).</li>
<li><strong>Standardisasi Kemasan Palet Kayu ISPM 15 / Metal Pallet Box:</strong> Karet blok seberat 35 kg per bongkahan dibungkus plastik polietilena low-density (LDPE) dengan titik leleh &lt; 109°C, kemudian ditata rapi dalam boks palet kayu berkapasitas 1,26 Ton (36 balok) atau kontainer palet besi anti-karat untuk memudahkan penanganan forklift di pabrik ban China.</li>
</ul>

<h2>Metode pembayaran ekspor L/C &amp; asuransi maritim kargo laut</h2>

<p>Manajemen risiko transaksi keuangan dan pengangkutan kargo kontainer karet alam jalur laut:</p>

<ul>
<li><strong>Pembayaran Letter of Credit (L/C at Sight):</strong> Penggunaan L/C yang diterbitkan bank komersial terkemuka di China (seperti Bank of China atau ICBC) dan dikonfirmasi oleh bank devisa nasional Indonesia menjamin pembayaran eksportir segera setelah dokumen pengapalan diserahkan.</li>
<li><strong>Asuransi Pengangkutan Laut (Institute Cargo Clauses / ICC B):</strong> Penutupan polis asuransi kargo laut dengan perluasan klausul <em>Water Ingress &amp; Mold Contamination Clause</em> untuk melindungi nilai kargo dari kerusakan akibat rembesan air laut di dalam kontainer selama pelayaran.</li>
<li><strong>Penetapan Klausul Demurrage &amp; Free Time Pelabuhan China:</strong> Negosiasi free time peti kemas minimal 14 hari di pelabuhan Qingdao/Shanghai untuk mengantisipasi proses inspeksi pabean GACC.</li>
</ul>

