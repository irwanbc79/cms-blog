<h2>Checklist 5 langkah manajemen docking kapal bagi Ship Owner</h2>

<ol>
<li><strong>Penyusunan Repair List Komprehensif (H-60 Hari):</strong> Buat daftar rincian pekerjaan reparasi lambung, mesin, dan kelistrikan yang jelas bersama Chief Engineer dan Master sebelum mengirim tender ke galangan kapal.</li>
<li><strong>Pemesanan Suku Cadang Kritis (Long Lead Items):</strong> Pastikan suku cadang poros propeller, katup laut, pelat baja berstandar kelas, dan cat marine telah tiba di galangan sebelum kapal naik dok.</li>
<li><strong>Penerbitan Gas Free Certificate (Khusus Kapal Tanker):</strong> Pastikan tangki bahan bakar dan ruang muat telah dibersihkan (tank cleaning) dan bebas gas mudah terbakar dengan sertifikat resmi dari Chemist berwenang sebelum pekerjaan panas (<em>hot work / welding</em>) dimulai.</li>
<li><strong>Pengawasan Harian Bersama Surveyor Kelas:</strong> Dampingi Surveyor BKI dan Marine Inspector Ditjen Hubla pada setiap uji tekan (pressure test), uji tak-merusak (NDT welding check), dan pengukuran ketebalan UTG.</li>
<li><strong>Pelaksanaan Undocking &amp; Sea Trial:</strong> Lakukan pemeriksaan kebocoran katup lambung saat air mulai masuk ke dalam dok sebelum pintu dok dibuka penuh, dilanjutkan uji coba pelayaran (Sea Trial) untuk memastikan seluruh parameter permesinan beroperasi normal.</li>
</ol>

