<h2>4 tipe fasilitas galangan kapal (Shipyard Facilities)</h2>

<p>Pemilihan tipe galangan disesuaikan dengan dimensi kapal (Length Overall / LOA, Breadth, Draft), bobot mati (Deadweight Tonnage / DWT), dan ketersediaan fasilitas:</p>

<ol>
<li><strong>Graving Dock (Drydock Kolam Gali):</strong> Kolam beton permanen di tepi laut yang dilengkapi pintu ponton kedap air. Kapal masuk saat air pasang, pintu ditutup, lalu air dipompa keluar hingga dasar dok kering sempurna. Tipe dok paling stabil untuk kapal berukuran besar (kargo &gt;10.000 DWT).</li>
<li><strong>Floating Dock (Dok Apung):</strong> Struktur baja terapung berongga berbentuk huruf U. Dok ditenggelamkan dengan mengisi air ke dalam tangki balas, kapal masuk ke atas bantalan balok ganjal (keel blocks), kemudian tangki balas dipompa kosong hingga dok dan kapal terangkat di atas permukaan laut.</li>
<li><strong>Slipway (Lintasan Rel Tarik):</strong> Landasan miring dengan rel baja yang menjorok ke perairan. Kapal diletakkan di atas kereta penopang (cradle) lalu ditarik ke daratan menggunakan mesin derek kawat baja (winch). Umum digunakan untuk kapal tunda, tongkang, dan kapal feeder &lt;5.000 DWT.</li>
<li><strong>Airbag Docking System:</strong> Metode peluncuran dan penarikan kapal menggunakan balon karet pneumatik bertekanan tinggi di atas bantalan beton pantai landai, sangat efisien untuk kapal tongkang dan kapal motor tradisional.</li>
</ol>

<h2>Tahapan teknis eksekusi repair list di atas dok</h2>

<p>Selama kapal berada di atas dok ganjal, serangkaian pekerjaan mekanik dan struktural dilaksanakan secara simultan:</p>

<h3>1. Pembersihan Lambung &amp; Sandblasting (Surface Preparation)</h3>
<ul>
<li>Pencucian semprot air bertekanan tinggi (<em>High Pressure Water Washing 300–500 bar</em>) untuk merontokkan lumpur, teritip (<em>barnacles</em>), lumut, dan garam laut.</li>
<li>Pembersihan karat dan sisa cat lama menggunakan metode <em>Grit Blasting</em> hingga mencapai standar kebersihan permukaan <strong>ISO 8501-1 Sa 2.5 (Near-White Metal)</strong> sebelum aplikasi cat primer.</li>
</ul>

<h3>2. Uji Ketebalan Pelat Lambung (Ultrasonic Thickness Gauging / UTG)</h3>
<ul>
<li>Pengukuran ketebalan pelat baja lambung bawah air (<em>keel plate, bottom plating, sheer strake</em>) oleh surveyor UTG bersertifikasi BKI.</li>
<li>Jika pengurangan ketebalan pelat akibat korosi melebihi batas toleransi klasifikasi (umumnya &gt;20% dari ketebalan nominal desain), dilakukan peremajaan pemotongan dan penyambungan pelat baja baru (<em>plate renewal / replating</em>).</li>
</ul>

<h3>3. Perawatan Sistem Propulsi, Kemudi, dan Katup Laut</h3>
<ul>
<li><strong>Propeller &amp; Shaft Survey:</strong> Pemolesan daun baling-baling (propeller polishing) untuk menghilangkan kavitasi, pengukuran kelonggaran bantalan poros baling-baling (<em>stern tube bearing clearance</em>), dan penggantian segel oli (<em>Simplex seal renewal</em>).</li>
<li><strong>Rudder Overhaul:</strong> Pengukuran kelonggaran pasak kemudi (<em>rudder pintle &amp; bush clearance</em>) serta pengujian penurunan daun kemudi (<em>rudder drop test</em>).</li>
<li><strong>Sea Chest &amp; Overboard Valves:</strong> Pembongkaran, skir/lapping katup laut, penggantian paking gasket, dan pembersihan kisi-kisi penyaring air laut untuk pendingin mesin.</li>
</ul>

<h3>4. Sistem Proteksi Katodik &amp; Aplikasi Cat Anti-Fouling</h3>
<ul>
<li>Pemasangan anoda korban seng/aluminium (<em>Zinc/Aluminium Sacrificial Anodes</em>) baru di area lambung bawah air, kotak sea chest, dan daun kemudi untuk mencegah korosi galvanik.</li>
<li>Aplikasi sistem pengecatan marine coating multi-layer: <em>Epoxy Anti-Corrosive Primer, Tie-Coat,</em> dan lapisan akhir <strong>Anti-Fouling Paint (bebas TBT sesuai IMO AFS Convention)</strong> atau <em>Silicone Foul-Release Coating</em>.</li>
</ul>

