<h2>Checklist 5 langkah mitigasi audit kepatuhan kepabeanan</h2>

<ol>
<li><strong>Lakukan Rekonsiliasi Mingguan IT Inventory vs Fisik:</strong> Pastikan tidak ada selisih saldo kuantitas antara fisik rak dengan catatan modul BC 1.6 / BC 2.8.</li>
<li><strong>Pantau Masa Kedaluwarsa Penimbunan 1 Tahun:</strong> Ajukan permohonan perpanjangan waktu penimbunan ke Kepala KPPBC minimal 30 hari sebelum batas waktu 1 tahun berakhir.</li>
<li><strong>Validasi Integritas Segel Pabean Elektronik (E-Seal):</strong> Periksa nomor segel kontainer saat tiba di pintu masuk gudang berikat dan catat dalam berita acara serah terima.</li>
<li><strong>Pemisahan Zona Kargo Berikat dan Non-Berikat:</strong> Berikan tanda pembatas fisik yang jelas dan marka lantai berwarna untuk memisahkan barang berstatus pabean dengan barang lokal bebas.</li>
<li><strong>Audit Kesiapan CCTV &amp; Backup Server:</strong> Uji fungsi streaming CCTV online ke server Bea Cukai dan pastikan sistem UPS daya cadangan berfungsi normal.</li>
</ol>

