<h2>Alur dokumen pabean operasional Gudang Berikat</h2>

<p>Seluruh pergerakan barang yang melintasi perimeter pabean gudang berikat wajib dilengkapi dokumen pemberitahuan pabean resmi DJBC:</p>

<ol>
<li><strong>Pemberitahuan Pabean BC 1.6 (Pemasukan dari Luar Daerah Pabean):</strong> Digunakan untuk mengangkut barang impor dari dermaga pelabuhan/bandara kedatangan langsung menuju fasilitas Gudang Berikat dengan jaminan penangguhan bea masuk.</li>
<li><strong>Pemberitahuan Pabean BC 2.7 (Mutasi Antar-Tempat Penimbunan Berikat):</strong> Digunakan untuk memindahkan bahan baku atau komponen dari Gudang Berikat ke fasilitas Kawasan Berikat (KB), Pusat Logistik Berikat (PLB), atau Gudang Berikat lainnya tanpa pembayaran bea masuk.</li>
<li><strong>Pemberitahuan Pabean BC 2.8 (Pengeluaran Barang Impor untuk Dipakai ke TLDDP):</strong> Dokumen penyelesaian kepabeanan saat barang impor dijual ke konsumen dalam negeri. Pada tahap ini, importir melunasi seluruh Bea Masuk dan PDRI melalui sistem billing elektronik sebelum Surat Persetujuan Pengeluaran Barang (SPPB) diterbitkan.</li>
<li><strong>Pemberitahuan Pabean BC 3.0 (Pengeluaran untuk Re-Ekspor):</strong> Digunakan saat kargo dikeluarkan dari Gudang Berikat menuju kapal pengangkut internasional untuk dikirim ke negara tujuan ketiga.</li>
<li><strong>Pemberitahuan Pabean BC 4.0 (Pemasukan Barang Asal Domestik):</strong> Digunakan untuk memasukkan barang lokal asal TLDDP (seperti bahan pembungkus atau karton) untuk keperluan pengepakan kargo di dalam gudang berikat.</li>
</ol>

<h2>Standar kepatuhan IT Inventory, jaminan pabean &amp; CCTV online (PER-02/BC/2019)</h2>

<p>Penyelenggara dan pengusaha gudang berikat wajib mematuhi standar teknologi informasi kepabeanan yang diawasi oleh Kantor Pelayanan Bea dan Cukai (KPPBC):</p>

<ul>
<li><strong>Prinsip Double-Entry Inventory Ledger:</strong> Sistem IT Inventory internal perusahaan wajib mencatat setiap mutasi fisik berdasarkan prinsip pembukuan berpasangan yang tidak dapat di-override secara manual tanpa jejak riwayat (audit trail log).</li>
<li><strong>Integrasi Laporan 4 Kategori Barang:</strong> Menyajikan laporan mutasi real-time untuk: (1) Laporan Pemasukan Barang per Dokumen Pabean, (2) Laporan Pengeluaran Barang per Dokumen Pabean, (3) Laporan Posisi Saldo Barang dalam Gudang (WIP/Storage), dan (4) Laporan Mutasi Penyesuaian/Kerusakan.</li>
<li><strong>Akses Daring Real-Time untuk DJBC:</strong> Memberikan hak akses baca (read-only view) kepada petugas seksi pengawasan pabean melalui dashboard web secara 24/7.</li>
<li><strong>Skema Jaminan Pabean (Customs Bond):</strong> Pengusaha wajib menyerahkan jaminan berupa Customs Bond, Garansi Bank, atau Corporate Guarantee senilai potensi Bea Masuk dan PDRI yang ditangguhkan.</li>
<li><strong>Pengeluaran Sementara untuk Perbaikan (Temporary Export/Repair):</strong> Barang modal atau peralatan yang mengalami kerusakan teknis dapat dikeluarkan sementara ke TLDDP atau luar negeri untuk diservis menggunakan izin pabean resmi dan jaminan penangguhan.</li>
<li><strong>Kamera Pengawas CCTV 24 Jam:</strong> Memasang kamera CCTV beresolusi tinggi di pintu masuk gerbang utama, area bongkar muat dock, lorong rak penyimpanan, dan area karantina, dengan rekaman video wajib disimpan minimal selama 30 (tiga puluh) hari kalender.</li>
<li><strong>Prosedur Perizinan OSS RBA Kemenkeu:</strong> Penetapan izin lokasi dan status Pengusaha Gudang Berikat (PGB) diterbitkan oleh Kantor Wilayah DJBC / KPU Bea dan Cukai setelah verifikasi kelayakan fisik perimeter pagar, layout zonasi, dan audit kepatuhan perpajakan (Tax Clearance).</li>
<li><strong>Penanganan Barang Cacat dan Limbah (Scrap &amp; Waste):</strong> Limbah kemasan sisa kegiatan sederhana wajib dimusnahkan di bawah pengawasan petugas Bea Cukai atau diselesaikan kewajiban pabeannya bila memiliki nilai ekonomis.</li>
</ul>

