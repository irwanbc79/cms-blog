<h2>Checklist 5 langkah inspeksi keselamatan rak (SEMA Standards)</h2>

<ol>
<li><strong>Pemeriksaan Kelurusan Tiang Tegak (Verticality Check):</strong> Pastikan defleksi tiang tegak akibat benturan tidak melebihi 3 mm per 1 meter bentang vertikal (Toleransi SEMA Green Hazard Limit).</li>
<li><strong>Verifikasi Kelengkapan Pin Pengunci Balok:</strong> Periksa seluruh sambungan balok dan ganti segera pin yang hilang atau bengkok menggunakan pin pengunci baja orisinal pabrikan.</li>
<li><strong>Inspeksi Retak Lantai dan Baut Angkur:</strong> Periksa apakah ada baut angkur yang kendor atau retakan lantai beton di sekitar pelat dasar tiang (baseplate).</li>
<li><strong>Audit Pelabelan Beban Maksimum SWL:</strong> Pastikan seluruh balok memiliki stiker penanda beban yang jelas dan operator tidak memuat palet yang melebihi batas tonase.</li>
<li><strong>Inspeksi Tahunan Ahli Struktur Independen (SARI):</strong> Lakukan audit kelayakan struktural menyeluruh setiap 12 bulan sekali oleh auditor kompeten berlisensi K3.</li>
</ol>

