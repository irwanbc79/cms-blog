<h2>Kesalahan yang harus dihentikan</h2>

<p>Pertama, jangan menawarkan “undername ekspor sawit” seolah nama perusahaan lain otomatis menyelesaikan Hak Ekspor dan Persetujuan Ekspor. Kedua, jangan menggunakan judul produk generik pada kontrak dan PEB. Ketiga, jangan memakai regulasi 2024 atau 2025 tanpa memeriksa status pencabutannya. Keempat, jangan menyamakan kepemilikan NIB dengan kewenangan mengekspor produk yang diatur.</p>

<p>Kelima, jangan menyalin perhitungan pungutan dari shipment berbeda. Keenam, jangan membuat invoice, packing list, Persetujuan Ekspor, dan PEB dari spreadsheet yang versinya tidak dikendalikan. Ketujuh, jangan menjanjikan jadwal muat sebelum peran eksportir, jalur BUMN, persyaratan produk, dan kontrak diselesaikan.</p>

<p>Dira dapat membantu menyiapkan product dossier, exporter-role matrix, document reconciliation, dan shipment readiness checklist. Keputusan perizinan, penelitian dokumen, pemeriksaan, serta pelayanan ekspor tetap berada pada instansi yang berwenang dan harus mengikuti data transaksi aktual.</p>

