<p>PPJK tidak menerbitkan Hak Ekspor atau Persetujuan Ekspor. <a href="https://meulaboh.beacukai.go.id/mandatory/ekspor.html" target="_blank" rel="noopener noreferrer">prosedur ekspor DJBC</a> menjelaskan bahwa pengurusan PEB dapat dilakukan sendiri oleh eksportir atau dikuasakan kepada PPJK. Kuasa administratif tersebut tidak memindahkan tanggung jawab atas kebenaran data, legalitas barang, hak komersial, atau pemenuhan ketentuan komoditas.</p>

<h2>Gate 3: bangun dossier Persetujuan Ekspor dan jalur BUMN</h2>

<p>Untuk produk yang berada dalam cakupan pengaturan, jangan berhenti pada NIB. <a href="https://oss.go.id/id/panduan" target="_blank" rel="noopener noreferrer">OSS</a> menjadi rujukan untuk identitas dan perizinan berusaha, sedangkan Persetujuan Ekspor serta mekanisme sektoral mengikuti ketentuan perdagangan dan sistem yang ditetapkan. Tim perlu membuat register yang mencatat nomor, pemegang, produk, volume, masa berlaku, saldo realisasi, syarat pelaporan, dan dokumen pendukung.</p>

<p>Jika transaksi berjalan melalui BUMN Ekspor, kontrak dan SOP perlu menjawab pertanyaan berikut:</p>

<ol>
<li>Siapa menjadi seller pada kontrak dan commercial invoice?</li>
<li>Siapa dicantumkan sebagai eksportir pada PEB?</li>
<li>Siapa menerima pembayaran dari buyer dan kapan pemasok dibayar?</li>
<li>Siapa menanggung kualitas, quantity, keterlambatan, demurrage, klaim, serta perubahan regulasi?</li>
<li>Data apa yang disampaikan ke BUMN Ekspor dan siapa yang menyetujui versi finalnya?</li>
<li>Bagaimana kontrak, invoice, packing list, transport document, perizinan, dan PEB direkonsiliasi?</li>
</ol>

<p>Jangan menandatangani kontrak jangka panjang hanya dengan asumsi struktur eksportir tetap sama. Tambahkan mekanisme <em>change in law</em>, kondisi pendahuluan, batas waktu pemenuhan dokumen, hak menunda shipment, serta cara mengalokasikan biaya bila jalur ekspor berubah.</p>

<h2>Gate 4: hitung pungutan dan cash-out per shipment</h2>

<p>Kelapa sawit, CPO, dan produk turunannya termasuk kelompok barang yang dapat dikenakan Bea Keluar. DJBC menjelaskan mekanisme self-assessment serta kebutuhan PEB berdasarkan invoice, packing list, dan dokumen lain yang diwajibkan. Karena tarif, Harga Patokan Ekspor, harga referensi, kurs, dan jenis produk dapat berubah, cost sheet harus memakai sumber serta periode yang sama dengan shipment.</p>

<p>Gunakan lembar perhitungan dengan kolom: pos tarif, uraian, quantity, satuan, harga ekspor, sumber HPE atau harga referensi, tarif, kurs, pungutan lain, tanggal berlaku, nomor keputusan, dan bukti persetujuan internal. Pisahkan estimasi dari angka final dan rekonsiliasi setelah dokumen pabean diterbitkan.</p>

<h3>Simulasi gate biaya</h3>

<p>Sebuah trader mempunyai kontrak pembelian produk sawit Rp8 miliar dan quotation buyer USD600.000. Margin belum dapat dihitung hanya dari selisih dua angka itu. Tim harus mengunci quantity saleable, spesifikasi, kurs, pajak, pungutan ekspor, biaya jalur BUMN, survey atau pengujian bila diwajibkan, inland transport, terminal, freight sesuai Incoterm, pembiayaan, serta cadangan exception.</p>

<p>Jika salah satu komponen regulasi atau kontrak belum jelas, quotation diberi status <em>conditional</em>. Ini bukan kelemahan penjualan; ini kontrol agar perusahaan tidak membuat komitmen yang struktur biayanya belum dapat dipertanggungjawabkan.</p>

<h2>Gate 5: rekonsiliasi dokumen sebelum PEB</h2>

<p>PEB bukan formulir yang berdiri sendiri. Data harus ditarik dari dossier produk dan dokumen komersial yang telah disetujui. Buat checklist rekonsiliasi berikut:</p>

<ul>
<li>eksportir, seller, buyer, consignee, dan penerima pembayaran;</li>
<li>nomor kontrak, invoice, dan Persetujuan Ekspor;</li>
<li>uraian barang, pos tarif, grade, lot, kemasan, net weight, dan gross weight;</li>
<li>quantity, nilai, currency, Incoterm, named port atau place;</li>
<li>asal barang, traceability, sertifikat mutu, dan dokumen teknis;</li>
<li>Bea Keluar atau pungutan yang relevan beserta dasar perhitungan;</li>
<li>booking, jadwal, container atau tank data, VGM bila relevan, dan transport document;</li>
<li>hasil pemeriksaan lartas serta dokumen pemenuhan persyaratan.</li>
</ul>

<p>Dalam alur DJBC, PEB dapat menerima respons penolakan bila data tidak lengkap atau tidak sesuai, respons persyaratan dokumen bila lartas belum dipenuhi, atau pemeriksaan fisik berdasarkan manajemen risiko. NPE diterbitkan setelah hasil penelitian memenuhi ketentuan yang berlaku. Karena itu, timeline penjualan tidak boleh menganggap NPE sebagai hasil otomatis.</p>

