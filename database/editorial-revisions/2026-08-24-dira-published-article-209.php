<h2>Gate 1: kunci produk sebelum membahas izin</h2>

<p>“Sawit” bukan uraian barang yang cukup. Crude palm oil, refined bleached deodorized palm oil, olein, used cooking oil, residu, bungkil, dan produk hilir memiliki karakter, pos tarif, kewajiban, dan dokumen yang dapat berbeda. Cocokkan nama dagang dengan komposisi, proses produksi, fungsi, bentuk fisik, grade, spesifikasi buyer, serta pos tarif pada lampiran aturan.</p>

<p>Buat <em>product dossier</em> minimum berisi:</p>

<ul>
<li>nama teknis dan nama komersial;</li>
<li>bahan, komposisi, serta proses produksi;</li>
<li>fungsi dan penggunaan produk;</li>
<li>bentuk fisik, kemasan, grade, dan parameter mutu;</li>
<li>calon pos tarif beserta dasar klasifikasinya;</li>
<li>hasil pemeriksaan ketentuan ekspor pada INSW;</li>
<li>dokumen asal, traceability, dan bukti rantai pasok.</li>
</ul>

<p>DJBC menjelaskan bahwa ketentuan larangan atau pembatasan yang diawasi dalam proses kepabeanan dapat diperiksa melalui <a href="https://www.insw.go.id/" target="_blank" rel="noopener noreferrer">Portal INSW</a>. Pemeriksaan tersebut harus dilakukan dengan data produk dan tanggal transaksi yang aktual. Hasil pencarian untuk satu pos tarif tidak boleh dipindahkan ke produk lain hanya karena sama-sama berasal dari kelapa sawit.</p>

