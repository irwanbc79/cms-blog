<h2>Klasifikasi HS Code sektor tekstil (Bab 50 s.d. 63)</h2>

<p>Penetapan pos tarif 8 digit pada dokumen PEB harus merujuk pada Buku Tarif Kepabeanan Indonesia (BTKI) di portal INSW:</p>

<ul>
<li><strong>Bab 50 – 55: Serat dan Benang Tekstil:</strong> Meliputi serat sutra, wol, kapas (Bab 52), serat nabati lain (rami/jute), dan serat filamen/stapel sintetik buatan (Bab 54 &amp; 55).</li>
<li><strong>Bab 56 – 60: Kain Khusus dan Kain Rajut/Tenun:</strong> Meliputi kain kempa (non-wovens), tali-temali, kain bordir, kain berlapis (coated fabrics), dan kain rajutan (knitted fabrics Bab 60).</li>
<li><strong>Bab 61: Pakaian Jadi Rajutan (Knitted Garments):</strong> Meliputi T-shirt (HS 6109), kemeja rajut, sweater, jaket rajut, kaos kaki, dan sarung tangan.</li>
<li><strong>Bab 62: Pakaian Jadi Non-Rajutan / Tenunan (Woven Garments):</strong> Meliputi kemeja pria/wanita katun (HS 6205), jas, celana panjang denim/katun (HS 6203 &amp; 6204), pakaian kerja industri, dan mantel.</li>
<li><strong>Bab 63: Barang Tekstil Jadi Lainnya:</strong> Meliputi selimut, sprei/linen tempat tidur (HS 6302), tirai, terpal, kantong kemasan, dan pakaian bekas.</li>
</ul>

<h2>Gate 1: aturan asal barang (Rules of Origin) pada penerbitan e-SKA</h2>

<p>Surat Keterangan Asal preferensi diterbitkan secara elektronik melalui portal e-SKA Kementerian Perdagangan RI. Untuk komoditas tekstil, kriteria asal barang (<em>Origin Criteria</em>) diatur secara ketat dalam perjanjian perdagangan bebas (FTA):</p>

<ol>
<li><strong>Change in Tariff Heading (CTH / CTC):</strong> Perubahan pos tarif 4 digit antara bahan baku impor (misalnya kain impor Bab 52) menjadi barang jadi yang diekspor (misalnya kemeja jadi Bab 62). Proses pemotongan dan penjahitan (<em>cutting &amp; sewing</em>) di Indonesia memenuhi transformasi substantif.</li>
<li><strong>Regional Value Content (RVC / Qualifying Value Content):</strong> Kandungan nilai lokal Indonesia dan negara mitra minimal mencapai ambang batas yang ditentukan (umumnya RVC &ge; 40%). Perhitungan didasarkan pada harga FOB dikurangi nilai bahan baku non-originating.</li>
<li><strong>Yarn Forward Rule (Aturan Benang):</strong> Pada skema perjanjian bilateral tertentu, seluruh proses mulai dari pemintalan benang, penenunan kain, hingga penjahitan garmen wajib dilakukan di wilayah negara anggota FTA untuk menikmati tarif Bea Masuk 0%.</li>
</ol>

<h2>Gate 2: kepatuhan regulasi lingkungan dan keselamatan pasar tujuan</h2>

<p>Pasar ekspor utama seperti Uni Eropa dan Amerika Serikat memberlakukan standar non-tarif yang sangat ketat terhadap produk tekstil:</p>

<ul>
<li><strong>Uni Eropa — Regulasi REACH &amp; OEKO-TEX Standard 100:</strong> Larangan penggunaan zat pewarna Azo (<em>Azo dyes</em>) yang melepaskan amina karsinogenik, senyawa organotin, zat tahan api terlarang, serta senyawa fluorinated (PFAS). Eksportir wajib melampirkan sertifikat uji laboratorium yang membuktikan kepatuhan batas residu kimia.</li>
<li><strong>Amerika Serikat — U.S. Consumer Product Safety Commission (CPSC / CPSIA):</strong> Untuk pakaian anak-anak dan bayi, wajib memenuhi uji ketahanan api (<em>flammability test</em> 16 CFR Part 1610), batas kandungan timbal (<em>lead content</em>), dan uji bebas ftalat pada kancing atau sablon plastik.</li>
<li><strong>Ketertelusuran Rantai Pasok (Supply Chain Traceability):</strong> Kepatuhan terhadap larangan penggunaan bahan baku serat yang terkait dengan praktik kerja paksa (seperti regulasi UFLPA di AS). Eksportir wajib mendokumentasikan asal-usul pembelian kapas mentah hingga ke tingkat perkebunan/pabrik pemintalan.</li>
</ul>

<h2>Tata laksana kepabeanan ekspor (PMK 155/PMK.04/2022) &amp; mitigasi jalur merah</h2>

<p>Proses kepabeanan ekspor tekstil dilakukan secara otomasi melalui sistem CEISA 4.0:</p>

<ol>
<li><strong>Transmisi PEB BC 3.0:</strong> Eksportir mentransmisikan data PEB dengan mencantumkan nomor invoice, packing list, nomor fasilitas Kawasan Berikat/KITE jika ada, HS Code 8 digit, berat bersih, nilai FOB, dan nama kapal.</li>
<li><strong>Penetapan Respon Kepabeanan:</strong>
  <ul>
    <li><strong>Jalur Hijau:</strong> Sistem menerbitkan <em>Nota Pelayanan Ekspor (NPE)</em> secara instan tanpa pemeriksaan fisik kargo. Kontainer dapat langsung masuk ke terminal dermaga pelabuhan (CY Gate-In).</li>
    <li><strong>Jalur Merah:</strong> Terbit Pemberitahuan Pemeriksaan Barang (PPB). Petugas Bea Cukai melakukan pemeriksaan fisik kargo (uji sampling kemasan karton, pencocokan label, dan penghitungan jumlah fisik) di Tempat Penimbunan Pabean sebelum NPE diterbitkan.</li>
  </ul>
</li>
<li><strong>Mitigasi Risiko Pemeriksaan Jalur Merah:</strong>
  <ul>
    <li>Pastikan toleransi selisih berat antara packing list dan timbangan jembatan pelabuhan (VGM) tidak melebihi 3–5%.</li>
    <li>Pastikan deskripsi barang di PEB mencantumkan rincian spesifik (misalnya: *"100% Cotton Woven Men's Shirt"*, bukan hanya *"Garment"*).</li>
    <li>Siapkan surat tugas dan pendampingan petugas PPJK saat pemeriksaan fisik agar tidak terjadi penundaan jadwal pemuatan kapal.</li>
  </ul>
</li>
</ol>

