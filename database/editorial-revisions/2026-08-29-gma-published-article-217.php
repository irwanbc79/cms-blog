<h2>Checklist 6 langkah audit dokumen sebelum stuffing kontainer</h2>

<ol>
<li><strong>Audit Konsistensi Header Data:</strong> Pastikan nama legal Shipper, Consignee, Notify Party, dan alamat identik 100% pada Invoice, Packing List, PEB, dan Shipping Instruction B/L.</li>
<li><strong>Verifikasi Breakdown Rasio Ukuran &amp; Warna:</strong> Pastikan rincian karton packing list mencerminkan isi fisik sebenarnya untuk memudahkan verifikasi sampling jika terkena jalur merah.</li>
<li><strong>Validasi HS Code dan Uji Laboratorium Mutu:</strong> Pastikan sertifikat uji lab (OEKO-TEX / REACH) masih berlaku dan mencakup jenis kain yang diekspor.</li>
<li><strong>Transmisi Data e-SKA Tepat Waktu:</strong> Ajukan e-SKA ke IPSKA setelah kapal bertolak (ATD) dengan melampirkan salinan final B/L dan NPE.</li>
<li><strong>Rekonsiliasi Bahan Baku Kawasan Berikat (BC 2.7 / BC 4.0):</strong> Jika menggunakan fasilitas kepabeanan KB/KITE, pastikan konversi pemakaian bahan baku (BOM - Bill of Materials) telah disesuaikan di portal IT Inventory.</li>
<li><strong>Penyimpanan Berkas Pabean (Customs Archive):</strong> Simpan seluruh berkas asli PEB, NPE, Invoice, PL, B/L, dan e-SKA minimal selama 10 tahun sesuai ketentuan UU Kepabeanan RI untuk keperluan audit pasca-pelepasan (Post Clearance Audit).</li>
</ol>

