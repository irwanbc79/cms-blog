<h2>Regulatory snapshot yang digunakan</h2>

<p><a href="https://jdih.karantinaindonesia.go.id/document/cfc38412-4e04-4cd1-b861-9fa3f352280f/detail" target="_blank" rel="noopener noreferrer">Peraturan Badan Karantina Indonesia Nomor 14 Tahun 2024</a> berstatus berlaku dan mengatur tata cara tindakan karantina serta pengawasan terintegrasi. Untuk pengeluaran media pembawa OPTK, Pasal 302–309 mengatur sertifikat kesehatan tumbuhan, tempat pengeluaran, pelaporan dan penyerahan kepada pejabat karantina, serta dokumen lain sesuai persyaratan.</p>

<p>Peraturan tersebut menyebut dokumen atau keterangan pendukung dapat berupa informasi perlakuan, sertifikat perlakuan, hasil uji laboratorium, import permit negara tujuan, pernyataan bebas organisme tertentu, atau informasi fasilitas dan tempat produksi. Persyaratan teknis lain tetap mengikuti negara tujuan. Artinya, daftar dokumen tidak boleh disalin dari shipment lain tanpa destination check.</p>

<p><a href="https://karantinaindonesia.go.id/nusa-tenggara-timur/layanan-dan-prosedur-karantina-tumbuhan" target="_blank" rel="noopener noreferrer">Panduan layanan Karantina Tumbuhan Barantin</a> menjelaskan bahwa ekspor diperiksa untuk memastikan pemenuhan persyaratan karantina Indonesia dan negara tujuan sebelum diterbitkan Phytosanitary Certificate.</p>

<p>Secara internasional, <a href="https://ippc.int/en/publications/609/" target="_blank" rel="noopener noreferrer">ISPM 12</a> memberi persyaratan dan pedoman penyiapan serta penerbitan Phytosanitary Certificate untuk ekspor dan re-ekspor. Untuk fumigasi, <a href="https://ippc.int/en/publications/87183/" target="_blank" rel="noopener noreferrer">ISPM 43</a> memberi panduan teknis kepada NPPO tentang aplikasi fumigasi dan otorisasi penyedia perlakuan; standar ini tidak menetapkan satu fumigan atau satu jadwal untuk seluruh komoditas.</p>

<p>Untuk kemasan kayu, gunakan <a href="https://www.ippc.int/en/work-area-publications/92080/" target="_blank" rel="noopener noreferrer">panduan implementasi ISPM 15 IPPC</a>. Panduan itu membahas pilihan perlakuan yang disetujui, penerapan tanda, produksi, perbaikan, penggunaan kembali, pemeriksaan impor, dan tindakan atas ketidakpatuhan kemasan kayu.</p>

<h2>Gate 1: tentukan apakah barang masuk lingkup karantina tumbuhan</h2>

<p>Mulai dari identitas barang, bukan nama pemasaran. Product dossier minimum memuat nama umum, botanical name bila relevan, bagian tumbuhan, bentuk segar atau kering, tingkat pengolahan, intended use, negara asal bahan, proses produksi, kadar air bila relevan, kemasan, foto, dan HS working code.</p>

<p>Bedakan komoditas dari pembungkusnya. Biji kopi, rempah, bungkil, kayu olahan, dan produk tumbuhan lain memiliki profil risiko berbeda. Pallet kayu yang membawa barang nonpertanian juga dapat menjadi objek kontrol ISPM 15. Satu kesimpulan untuk isi barang tidak boleh otomatis diterapkan pada pallet.</p>

<h2>Gate 2: bangun destination requirement dossier</h2>

<p>Persyaratan negara tujuan adalah sumber keputusan. Simpan bukti dari NPPO negara tujuan, import permit, protokol bilateral, phytosanitary import requirement, additional declaration, daftar organisme sasaran, treatment schedule yang diakui, ketentuan tempat produksi atau fasilitas, serta masa berlaku dokumen.</p>

