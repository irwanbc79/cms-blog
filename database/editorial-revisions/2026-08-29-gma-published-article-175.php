<h2>Alur operasional satu shipment</h2>

<ol>
<li>Eksportir menerima purchase order dan destination requirement yang dapat diverifikasi.</li>
<li>Compliance mengunci commodity dossier, pest target, treatment dan document matrix.</li>
<li>Tim mengajukan permohonan tindakan karantina sesuai kanal dan lokasi layanan.</li>
<li>Provider memeriksa kesiapan lot, enclosure, kemasan, alat ukur, dan treatment order.</li>
<li>Perlakuan dilaksanakan serta direkam menurut schedule dan pengawasan yang berlaku.</li>
<li>Lot diproteksi dari pencampuran dan reinfestasi setelah perlakuan.</li>
<li>Karantina melakukan tindakan yang diperlukan dan menilai pemenuhan persyaratan tujuan.</li>
<li>Data treatment certificate, PC, invoice, packing list, booking dan container direkonsiliasi.</li>
<li>Dokumen final dikirim hanya setelah four-eyes review dan version lock.</li>
<li>Shipment ditutup setelah departure evidence, arsip, biaya, dan exception selesai.</li>
</ol>

<h2>Simulasi kontrol lot</h2>

<p>Contoh hipotetis: eksportir menyiapkan 20 bag produk tumbuhan kering dari Lot A dan 30 bag dari Lot B untuk satu kontainer. Negara tujuan meminta treatment dan additional declaration tertentu. Kedua lot hanya boleh digabung dalam satu treatment record jika identitas, kondisi, schedule, dan cakupannya disetujui.</p>

<p>Setelah perlakuan, final tally menemukan satu bag Lot B rusak dan diganti dengan bag dari Lot C yang belum tercakup. Tim tidak boleh mempertahankan sertifikat untuk total 50 bag seolah tidak terjadi perubahan. Pilihannya harus diputuskan melalui exception control: keluarkan pengganti, perlakukan lot tambahan, ubah quantity, atau lakukan tindakan lain sesuai arahan provider dan karantina.</p>

<h2>Biaya yang perlu dimasukkan ke quotation</h2>

<p>Quotation harus memisahkan survey kesiapan, mobilisasi, fumigan, enclosure, monitoring, aerasi, pengawasan, sertifikat perlakuan, handling, storage, re-bagging, transport, overtime, re-treatment, dan biaya pihak berwenang bila relevan. Tulis dasar satuan, mata uang, pajak, validity, included, excluded, serta trigger biaya kontingensi.</p>

<p>Harga terendah belum tentu menghasilkan biaya shipment terendah. Nilai provider dari kemampuan membuktikan schedule, menjaga keselamatan, merekonsiliasi data, melindungi lot setelah treatment, dan menangani deviation tanpa mengubah bukti secara informal.</p>

<h2>Red flags sebelum pemuatan</h2>

<ul>
<li>Fumigasi dipesan tanpa import permit atau bukti requirement negara tujuan.</li>
<li>Satu schedule dipakai untuk semua komoditas dan semua negara.</li>
<li>Provider tidak dapat menunjukkan status, personel, kalibrasi, atau treatment record.</li>
<li>Lot pada sertifikat berbeda dengan barang yang masuk kontainer.</li>
<li>Commodity treatment dan ISPM 15 untuk pallet dianggap proses yang sama.</li>
<li>Container atau seal diubah setelah treatment tanpa exception record.</li>
<li>Treatment certificate dianggap pengganti Phytosanitary Certificate.</li>
<li>Additional declaration disalin dari shipment lama tanpa verifikasi.</li>
<li>Tim menjanjikan penerbitan sertifikat atau penerimaan negara tujuan pada waktu tertentu.</li>
</ul>

<h2>Checklist sebelum shipment release</h2>

<ol>
<li>Commodity dossier dan status media pembawa telah dikonfirmasi.</li>
<li>Persyaratan NPPO tujuan, import permit, protokol, dan buyer terdokumentasi terpisah.</li>
<li>Treatment decision menyebut pest target dan schedule yang diterima.</li>
<li>Provider, lokasi, personel, peralatan, dan status kewenangan telah diverifikasi.</li>
<li>Lot register cocok dengan barang fisik, packing list, dan treatment order.</li>
<li>Barang pascaperlakuan terlindung dari pencampuran serta reinfestasi.</li>
<li>Fumigation certificate dan hasil pengawasan telah direview.</li>
<li>Phytosanitary application, additional declaration, serta dokumen lain konsisten.</li>
<li>ISPM 15 pada kemasan kayu diperiksa sebagai kontrol tersendiri.</li>
<li>Container, seal, quantity, weight, tanggal, dan lokasi cocok pada dokumen final.</li>
</ol>

<h2>Kesimpulan</h2>

<p>Fumigasi ekspor yang terkendali dimulai dari persyaratan tujuan, bukan dari pemesanan vendor. Pisahkan objek komoditas dan kemasan kayu, pilih treatment schedule yang diakui, kunci lot, lindungi barang setelah perlakuan, lalu rekonsiliasi treatment certificate dengan Phytosanitary Certificate dan dokumen shipment.</p>

