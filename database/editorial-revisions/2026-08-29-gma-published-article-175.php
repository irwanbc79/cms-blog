<p>Permintaan buyer perlu dicatat, tetapi tidak selalu identik dengan ketentuan NPPO. Jika buyer meminta metode yang berbeda dari protokol resmi, hentikan konfirmasi jadwal dan minta klarifikasi tertulis. Perlakuan yang tidak diakui dapat merusak barang tanpa menyelesaikan persyaratan fitosanitari.</p>

<h2>Gate 3: putuskan perlakuan berdasarkan schedule, bukan kebiasaan</h2>

<p>Fumigasi adalah aplikasi bahan kimia yang mencapai komoditas terutama dalam bentuk gas. Efektivitas bergantung pada kombinasi parameter, bukan hanya nama fumigan. Treatment order harus merujuk pada schedule yang diterima dan mencatat sekurang-kurangnya komoditas, target pest, fumigan, dosis awal, temperatur, waktu paparan, konsentrasi pada titik serta interval yang ditentukan, enclosure, loading factor, kondisi kemasan, aerasi, dan acceptance criteria.</p>

<p>Artikel ini tidak memberikan dosis atau instruksi penggunaan fumigan. Bahan fumigasi memiliki risiko keselamatan, lingkungan, residu, dan kerusakan komoditas. Perlakuan harus dilakukan oleh pihak yang memiliki kewenangan dan kompetensi, menggunakan schedule serta pengawasan yang sesuai.</p>

<p>Gunakan <a href="https://ft.karantinaindonesia.go.id/" target="_blank" rel="noopener noreferrer">FUMI TRUST Barantin</a> sesuai arahan UPT untuk pemberitahuan, pengawasan, pelaporan, dokumentasi, dan penelusuran tindakan fumigasi. Verifikasi status penyedia serta cakupan perlakuannya untuk metode dan wilayah kerja aktual.</p>

<h2>Gate 4: kunci identitas lot sebelum perlakuan</h2>

<p>Buat treatment lot register sebelum provider mulai bekerja. Setiap lot harus terhubung dengan purchase order, invoice, packing list, warehouse location, quantity, net dan gross weight, packaging, container jika sudah tersedia, serta foto atau seal control.</p>

<p>Jangan mencampur barang yang belum diberi perlakuan dengan barang yang telah diperlakukan. Setelah fumigasi, tetapkan zona, label status, akses personel, dan batas waktu stuffing. Bila lot dipecah, digabung, dikemas ulang, terkena air, terbuka, atau berpindah lokasi, buat deviation record dan minta penilaian apakah bukti perlakuan masih dapat dipakai.</p>

