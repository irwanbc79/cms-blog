<h2>Prosedur pengeringan matahari, destoning, dan pemisahan debu</h2>

<p>Tahapan pascapanen presisi untuk menjaga warna merah kecokelatan mengkilap dan mempertahankan senyawa eugenol:</p>

<ul>
<li><strong>Perontokan Bunga dari Tangkai:</strong> Dilakukan maksimal 24 jam setelah pemetikan buah matang petik (saat kepala bunga berwarna semburat merah muda kekuningan) agar bunga tidak mengalami fermentasi busuk.</li>
<li><strong>Penjemuran Bertahap di Atas Para-Para (Sun Drying):</strong> Menggunakan alas terpal food-grade atau rak para-para bambu dengan sirkulasi udara bawah selama 3–4 hari hingga kadar air stabil di kisaran 10%–11%.</li>
<li><strong>Pembersihan Mekanis Destoner &amp; Blower:</strong> Memisahkan debu tanah, kerikil, daun kering, dan serpihan tangkai menggunakan mesin pembersih getar dan tiupan udara siklon.</li>
<li><strong>Sortasi Manual Bunga Patah &amp; Tanpa Kepala:</strong> Tenaga sortasi terlatih memisahkan bunga cengkeh patah (<em>mother cloves</em>) untuk menghasilkan grade super AB6 yang bernilai jual tinggi di pasar bumbu Timur Tengah.</li>
</ul>

<h2>Sertifikasi fitosanitari Barantin &amp; protokol pasar ekspor India (Spices Board)</h2>

<p>Kepatuhan regulasi karantina tumbuhan internasional sebelum stuffing kontainer:</p>

<ul>
<li><strong>Pemeriksaan Karantina Tumbuhan Barantin (PPK Online):</strong> Petugas fungsional karantina memeriksa kebersihan fisik dan mengambil sampel representatif untuk uji laboratorium mikrobiologi dan serangga gudang.</li>
<li><strong>Fumigasi Gas Fosfin (Phospine PH3 120 Jam):</strong> Kargo cengkeh wajib difumigasi standar AFAS dengan dosis 2–3 g/m³ selama 5 hari untuk membunuh kumbang rempah (<em>Stegobium paniceum</em>), dibuktikan dengan <em>Fumigation Certificate</em> resmi.</li>
<li><strong>Penerbitan Phytosanitary Certificate (KT-1):</strong> Dokumen kesehatan tumbuhan resmi yang menjamin komoditas bebas dari Organisme Pengganggu Tumbuhan Karantina (OPTK).</li>
<li><strong>Ketentuan Pungutan &amp; Standar FSSAI India:</strong> Pengiriman cengkeh ke Pelabuhan Nhava Sheva atau Chennai India wajib melampirkan SKA e-Form AIFTA (ASEAN-India FTA) untuk menikmati tarif preferensi, serta memenuhi batas residu pestisida sesuai regulasi <em>Food Safety and Standards Authority of India (FSSAI)</em>.</li>
</ul>

<h2>Peluang hilirisasi: Ekspor minyak daun cengkeh &amp; eugenol murni</h2>

<p>Pengembangan produk turunan bernilai tambah tinggi dari biomassa tanaman cengkeh:</p>

<ul>
<li><strong>Minyak Daun Cengkeh (Clove Leaf Oil):</strong> Hasil penyulingan uap daun gugur cengkeh yang mengandung kadar total eugenol 75%–85%, diklasifikasikan pada pos tarif HS Code 3301.29.10 untuk industri farmasi sintetis vanilin di Eropa.</li>
<li><strong>Minyak Gagang Cengkeh (Clove Stem Oil):</strong> Memiliki aroma sangat murni dan tajam dengan kadar eugenol mencapai 85%–92%, dikemas dalam drum baja berlapis epoxy berstandar ekspor internasional.</li>
<li><strong>Pengujian Mikrobiologi Bebas Salmonella:</strong> Buyer rempah di Amerika Serikat dan Eropa mensyaratkan kepatuhan baku mutu bebas bakteri patogen (<em>Salmonella negative in 25g</em> dan <em>E. coli < 10 CFU/g</em>) yang dibuktikan melalui Certificate of Analysis laboratorium KAN.</li>
<li><strong>Standar Paletisasi Kayu ISPM 15:</strong> Penataan karung cengkeh di atas palet kayu yang telah diberi perlakuan panas (<em>Heat Treatment / HT</em>) atau fumigasi dan dibubuhi cap stempel gandum resmi IPPC untuk mempermudah handling muatan pabean.</li>
</ul>

