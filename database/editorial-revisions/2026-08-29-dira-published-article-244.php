<h2>Checklist 5 langkah audit kesiapan ekspor cengkeh bagi pelaku usaha</h2>

<ol>
<li><strong>Verifikasi Kadar Air &amp; Eugenol Lot Produksi:</strong> Memastikan hasil uji distilasi menunjukkan kadar air di bawah 11% dan kadar minyak atsiri eugenol di atas 18%.</li>
<li><strong>Pembersihan Benda Asing &amp; Sortasi Kepala Bunga:</strong> Menggunakan mesin destoner untuk mengeliminasi batu dan debu serta membatasi bunga tanpa kepala di bawah batas toleransi buyer.</li>
<li><strong>Pengajuan Permohonan Pemeriksaan Karantina (PPK Online):</strong> Mendaftarkan kargo ke sistem Barantin untuk proses sampling laboratorium dan penerbitan sertifikat KT-1.</li>
<li><strong>Deklarasi Pabean PEB BC 3.0 CEISA 4.0:</strong> Memproses penyusunan dan pengiriman PEB melalui PPJK berlisensi resmi DJBC hingga terbit Nota Pelayanan Ekspor (NPE).</li>
<li><strong>Penerbitan Surat Keterangan Asal Elektronik (e-SKA):</strong> Mengajukan Form AIFTA (India), Form D (ASEAN), atau Form B (Timur Tengah) pada portal e-SKA Kementerian Perdagangan RI.</li>
</ol>

