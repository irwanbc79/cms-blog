<h2>Aspek legalitas &amp; perpajakan: Mengapa LIFO dilarang di Indonesia?</h2>

<p>Berdasarkan <a href="https://iaiglobal.or.id" target="_blank" rel="noopener noreferrer">PSAK 14 (IAS 2)</a> dan <a href="https://pajak.go.id" target="_blank" rel="noopener noreferrer">Undang-Undang No. 36 Tahun 2008 tentang Pajak Penghasilan Pasal 10 ayat (6)</a>, penilaian persediaan di Indonesia hanya diperbolehkan menggunakan metode:</p>

<ol>
<li><strong>Metode Masuk Pertama Keluar Pertama (FIFO):</strong> Mengasumsikan persediaan yang dibeli lebih awal akan dijual lebih dulu, sehingga nilai persediaan akhir mencerminkan harga pasar terkini.</li>
<li><strong>Metode Rata-Rata Tertimbang (Weighted Average Cost / WAC):</strong> Menghitung biaya persediaan berdasarkan rata-rata tertimbang harga perolehan seluruh unit sejenis selama periode akuntansi.</li>
</ol>

<p>Metode <strong>LIFO dilarang secara mutlak</strong> karena dalam kondisi tren inflasi ekonomi, LIFO membebankan barang berharga tinggi (yang dibeli terakhir) ke HPP, sehingga mengecilkan laba bersih kena pajak secara artifisial dan menyajikan saldo nilai persediaan akhir di neraca dengan harga historis yang jauh di bawah nilai wajar pasar.</p>

<h2>Gate FEFO: regulasi BPOM &amp; pelabelan barcode GS1-128</h2>

<p>Bagi industri farmasi dan makanan berizin edar BPOM (<a href="https://www.pom.go.id" target="_blank" rel="noopener noreferrer">Perka BPOM CDPOB &amp; CPPOB</a>), gudang wajib mengunci sistem alokasi barang menggunakan parameter <strong>FEFO</strong>:</p>

<ul>
<li><strong>Aturan Remaining Shelf Life (RSL):</strong> Distributor modern dan ritel jaringan umumnya mensyaratkan batas sisa umur simpan produk minimal 75% s.d. 85% saat penerimaan di gudang distribution center (DC). Produk dengan RSL di bawah 60% wajib dialokasikan ke jalur promosi khusus atau retur pabrik.</li>
<li><strong>Area Karantina &amp; Status Hold (Quarantine Zone):</strong> Batch produk yang mendekati masa kedaluwarsa kritis (&lt;30 hari) secara otomatis diblokir sistem WMS (status <em>System Lock / On-Hold</em>) dan dipindahkan ke area karantina fisik berpagar khusus guna mencegah ketidaksengajaan terambil saat proses order picking.</li>
<li><strong>Integrasi Barcode GS1-128 &amp; 2D DataMatrix:</strong> Label barcode pada karton master wajib menyematkan <em>Application Identifier</em> (AI) terstandarisasi: <strong>AI (10)</strong> untuk Nomor Batch/Lot dan <strong>AI (17)</strong> untuk Tanggal Kedaluwarsa format YYMMDD. Saat operator memindai barcode, WMS secara otomatis menolak rilis barang jika ada batch lain yang memiliki tanggal kedaluwarsa lebih dini.</li>
</ul>

<h2>Desain infrastruktur fisik: sistem racking pendukung rotasi stok</h2>

<p>Efisiensi perputaran barang membutuhkan dukungan struktur rak (<em>racking system</em>) yang tepat:</p>

<ul>
<li><strong>Pallet Flow Racking (FIFO Murni):</strong> Rak berposisi miring dengan rel roda rol gravitasi (<em>gravity roller bed</em>). Pallet dimuat dari sisi belakang (infeed) dan meluncur otomatis ke sisi depan (picking face). Jalur muat dan ambil terpisah total 100%.</li>
<li><strong>Push-Back Racking (LIFO Fleksibel):</strong> Menggunakan sistem kereta geser bertingkat (<em>nested carts</em>). Pallet baru mendorong pallet sebelumnya ke belakang. Pemuatan dan pengambilan dilakukan dari satu sisi yang sama (<em>single aisle access</em>), ideal untuk SKU dengan volume tinggi tanpa tanggal kedaluwarsa.</li>
<li><strong>Selective Pallet Racking:</strong> Desain rak konvensional dengan akses langsung 100% ke setiap pallet, sangat fleksibel untuk menerapkan FEFO dinamis berbantuan sistem WMS scanner.</li>
<li><strong>Drive-In vs Drive-Through Racking:</strong> Drive-In memiliki satu akses masuk-keluar untuk LIFO densitas tinggi, sedangkan Drive-Through memiliki dua sisi terbuka yang memungkinkan alur FIFO pallet besar.</li>
</ul>

<h2>Manajemen logistik balik (Reverse Logistics) &amp; barang retur</h2>

<p>Penerapan FIFO dan FEFO sering kali diuji saat gudang menerima barang retur dari pelanggan (<em>Reverse Logistics</em>):</p>

<ol>
<li><strong>Inspeksi Kualitas &amp; Verifikasi Batch Asal:</strong> Barang retur tidak boleh langsung dimasukkan kembali ke rak picking aktif. Petugas QC wajib memindai barcode untuk memeriksa nomor lot batch dan tanggal kedaluwarsa aslinya guna memverifikasi integritas fisik kemasan dan masa simpan.</li>
<li><strong>Pemisahan Barang Rusak Kemasan:</strong> Jika kemasan luar rusak namun produk utuh, lakukan pelabelan ulang (re-tagging) barcode GS1 dan masukkan ke alur FEFO dengan prioritas pengeluaran tercepat. Jika produk telah terpapar suhu atau terkontaminasi, barang dipindahkan ke zona pemusnahan (scrap disposal) dengan berita acara resmi.</li>
<li><strong>Cycle Counting Berkala Berbasis Risiko:</strong> Laksanakan penghitungan stok berkala harian (Cycle Count) untuk SKU kategori fast-moving dan produk rentan kedaluwarsa guna menjamin akurasi data sistem dengan fisik di atas rak mencapai 99,8%.</li>
</ol>

