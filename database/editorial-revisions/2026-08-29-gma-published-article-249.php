<h2>Checklist 5 langkah audit perputaran stok gudang</h2>

<ol>
<li><strong>Sinkronisasi Master Data SKU:</strong> Pastikan seluruh produk sensitif waktu telah diaktifkan atribut wajib tanggal kedaluwarsa (expiry tracking flag) di sistem database WMS/ERP.</li>
<li><strong>Audit Pelabelan Barcode GS1 di Area Inbound:</strong> Periksa keterbacaan kode barcode AI (10) lot number dan AI (17) expiry date sebelum pallet dimasukkan ke lokasi rak penyimpanan.</li>
<li><strong>Verifikasi Rekonsiliasi Fiskal Pajak:</strong> Pastikan departemen akuntansi tidak menggunakan metode LIFO dalam perhitungan SPT Tahunan Badan.</li>
<li><strong>Inspeksi Fisik Jalur Gravitasi Pallet Flow:</strong> Bersihkan rel roda rol dan pastikan rem kecepatan (speed controller rollers) bekerja optimal agar pallet tidak bertabrakan saat meluncur.</li>
<li><strong>Lakukan Pemantauan Stock Aging Mingguan:</strong> Terbitkan laporan usia stok (<em>Inventory Aging Report</em>) untuk mengidentifikasi batch barang yang mendekati batas RSL 75%.</li>
</ol>

