<h2>Checklist 5 langkah audit efisiensi bongkar muat barang</h2>

<ol>
<li><strong>Sinkronisasi Dokumen Inward/Outward BC 1.1:</strong> Pastikan pos nomor manifes pabean telah cocok dengan data Bill of Lading dan PEB/PIB sebelum kapal tiba di pelabuhan.</li>
<li><strong>Verifikasi Kesiapan RKBM dan Alat Berat:</strong> Pastikan PBM telah mengonfirmasi ketersediaan crane, sasis terminal, dan tim lashing TKBM sebelum kapal menyelesaikan penambatan.</li>
<li><strong>Pemeriksaan Fisik Kargo dan Segel Kontainer (Tally &amp; Damage Report):</strong> Lakukan pencatatan kondisi fisik peti kemas saat berpindah dari kapal ke dermaga untuk melindungi hak klaim asuransi maritim jika terjadi benturan muatan.</li>
<li><strong>Penyelesaian D/O dan SPPB Sebelum Free Time Berakhir:</strong> Ambil Delivery Order dari pelayaran dan selesaikan clearance pabean secepatnya untuk menghindari denda storage lapangan penumpukan TPS.</li>
<li><strong>Kepatuhan Standar K3 Maritim:</strong> Wajibkan seluruh personel di dermaga mengenakan Alat Pelindung Diri (APD lengkap: helm keselamatan, rompi reflektif, sepatu keselamatan baja, dan harness saat bekerja di atas palka).</li>
</ol>

<h2>Kesimpulan</h2>

<p>Kelancaran <strong>prosedur bongkar muat ekspor impor</strong> bertumpu pada kedisiplinan koordinasi antara Perusahaan Bongkar Muat (PBM), kepatuhan penyampaian manifes pabean Inward/Outward BC 1.1 di CEISA 4.0, integrasi dokumen kerja di sistem Inaportnet Kementerian Perhubungan, serta penerapan standar keselamatan kerja maritim (K3) yang ketat di dermaga pelabuhan.</p>

<p>GMA World menyediakan layanan keagenan kapal, logistik maritim, dan pendampingan kepelabuhanan terpercaya: koordinasi izin sandar dan bongkar muat kapal, manajemen dokumen kepabeanan ekspor-impor, penanganan kargo curah, peti kemas, dan kargo proyek (heavy lift), serta optimalisasi pergerakan kargo keluar pelabuhan. Seluruh operasional pembongkaran muatan dan izin kepabeanan tunduk pada regulasi resmi Kementerian Perhubungan RI dan Direktorat Jenderal Bea dan Cukai.</p>

