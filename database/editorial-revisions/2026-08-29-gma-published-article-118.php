<h2>Gate 1: alur perizinan operasional kapal di Inaportnet Kemenhub</h2>

<p>Sebelum pembongkaran atau pemuatan barang dimulai, agen pelayaran dan PBM wajib menyelesaikan administrasi kepelabuhanan melalui sistem elektronik terpadu Inaportnet:</p>

<ol>
<li><strong>Warta Kedatangan Kapal (Pemberitahuan Kedatangan Kapal / PKK):</strong> Agen kapal menyampaikan manifes muatan, rencana rute pelayaran, dan perkiraan waktu tiba (<em>Estimated Time of Arrival / ETA</em>) minimal 24 jam sebelum kapal memasuki perairan pelabuhan.</li>
<li><strong>Rencana Penetapan Penambatan Kapal (RPK / PPK):</strong> Kantor Otoritas Pelabuhan (KSOP) dan Badan Usaha Pelabuhan (BUP / Pelindo) menerbitkan alokasi tambatan dermaga sesuai draf kedalaman kapal dan kesiapan crane.</li>
<li><strong>Rencana Kerja Bongkar Muat (RKBM):</strong> PBM mengajukan dokumen RKBM yang merinci daftar palka kapal, volume kargo yang dibongkar/dimuat, jenis alat berat yang digunakan, serta jumlah regu kerja TKBM yang ditugaskan per giliran kerja (<em>shift</em>).</li>
<li><strong>Penerbitan Surat Persetujuan Olah Gerak (SPOG) &amp; Izin Mulai Bongkar:</strong> Syahbandar menerbitkan izin resmi setelah seluruh dokumen keselamatan kapal dan kelaiklautan dinyatakan lengkap.</li>
</ol>

<h2>Gate 2: pengawasan kepabeanan &amp; rekonsiliasi Manifes BC 1.1</h2>

<p>Seluruh muatan ekspor dan impor yang melintasi kawasan pabean pelabuhan wajib terdaftar dalam sistem manifes Direktorat Jenderal Bea dan Cukai (DJBC):</p>

<ul>
<li><strong>Inward Manifest Impor (Inward BC 1.1):</strong> Pengangkut wajib mentransmisikan data Inward Manifest ke sistem CEISA 4.0 maksimal 24 jam sebelum kedatangan kapal untuk rute laut internasional jarak jauh, atau sebelum kapal tiba untuk pelayaran pendek. Pembongkaran kargo hanya boleh dilakukan atas barang yang tercantum dalam pos Inward BC 1.1 yang valid.</li>
<li><strong>Outward Manifest Ekspor (Outward BC 1.1):</strong> Sebelum kapal bertolak meninggalkan pelabuhan muat, pengangkut menyampaikan Outward Manifest yang berisi daftar seluruh peti kemas dan kargo ekspor yang telah dimuat di atas kapal berdasarkan Nota Pelayanan Ekspor (NPE PEB BC 3.0).</li>
<li><strong>Penimbunan di Tempat Penimbunan Sementara (TPS):</strong> Kargo impor yang dibongkar wajib langsung ditimbun di area TPS lini 1 pelabuhan yang telah terintegrasi dengan sistem IT Inventory pabean sebelum diterbitkan Surat Persetujuan Pengeluaran Barang (SPPB PIB BC 2.0).</li>
</ul>

<h2>Gate 3: prosedur pembongkaran langsung (Truck Lossing)</h2>

<p>Untuk komoditas tertentu yang memiliki sifat fisik khusus, pabean memberikan izin fasilitas pembongkaran langsung ke atas truk pengangkut tanpa ditimbun terlebih dahulu di lapangan penumpukan pelabuhan (<em>Truck Lossing</em>):</p>

<ul>
<li><strong>Kategori Komoditas yang Diizinkan:</strong>
  <ol>
    <li>Barang berbahaya dan beracun (<em>Hazardous Cargo / IMDG Code</em>) seperti bahan kimia mudah meledak atau gas bertekanan;</li>
    <li>Kargo berukuran raksasa atau berat abnormal (<em>Over Dimension Over Weight / Project Cargo</em>);</li>
    <li>Komoditas curah cair (minyak nabati, bahan kimia cair via marine pipeline);</li>
    <li>Komoditas curah kering pangan strategis (seperti gandum, kedelai, jagung yang langsung dibongkar ke dump truck via grab hopper);</li>
    <li>Kargo perishable yang memerlukan penanganan suhu segera.</li>
  </ol>
</li>
<li><strong>Syarat Administrasi:</strong> Importir wajib mengajukan surat permohonan pembongkaran langsung dan mengantongi izin tertulis dari Kepala Kantor Pabean sebelum kapal bersandar di dermaga.</li>
</ul>

