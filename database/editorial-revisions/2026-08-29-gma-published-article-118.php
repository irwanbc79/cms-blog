<h2>3 tahapan utama operasi bongkar muat pelabuhan (PBM)</h2>

<p>Berdasarkan Peraturan Pemerintah No. 31 Tahun 2021, kegiatan usaha bongkar muat barang dari dan ke kapal dilakukan oleh Perusahaan Bongkar Muat (PBM) berizin yang terbagi dalam tiga tahapan operasional berkesinambungan:</p>

