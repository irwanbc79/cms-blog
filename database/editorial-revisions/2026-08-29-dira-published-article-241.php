<h2>Standar pengujian mutu laboratorium ASTA &amp; kendali coumarin</h2>

<p>Kepatuhan spesifikasi kimia dan kebersihan pangan sebelum pengapalan internasional:</p>

<ul>
<li><strong>Kadar Minyak Atsiri (Volatile Oil / VO):</strong> Diuji menggunakan metode distilasi uap Clevenger (SNI 01-3714). Nilai minimal 2,0%–3,5% menjamin kekuatan aroma dan rasa pedas-manis khas cinnamaldehyde.</li>
<li><strong>Batas Cemaran Coumarin:</strong> Kayu manis jenis cassia mengandung senyawa coumarin alami. Laboratorium independen (seperti Sucofindo atau Saraswanti) melakukan uji HPLC untuk memastikan kargo memenuhi spesifikasi kontrak buyer pangan Eropa.</li>
<li><strong>Kebersihan Fisik Standar ASTA (Filth Test):</strong> Bebas dari serangga mati, bulu hewan pengerat, kotoran tanah, dan benda asing (kadar kotoran maksimal 0,50%).</li>
<li><strong>Batas Logam Berat &amp; Residu Pestisida:</strong> Timbal (Pb) &lt; 2,0 mg/kg, Kadmium (Cd) &lt; 0,2 mg/kg, dan bebas dari residu fumigasi kimia terlarang.</li>
</ul>

<h2>Sertifikasi organik internasional, penanganan kapal, dan proteksi kelembaban</h2>

<p>Perlakuan fisik dan pengemasan untuk menjamin kayu manis tetap renyah dan aromatik selama pelayaran 30–45 hari:</p>

<ul>
<li><strong>Sertifikasi Rempah Organik (USDA Organic &amp; EU Organic Regulation 2018/848):</strong> Kayu manis yang dibudidayakan tanpa pupuk sintetis atau pestisida kimia di lereng Kerinci berhak memperoleh sertifikat organik internasional dengan premi harga hingga 30%–40% di pasar Eropa dan Amerika Serikat.</li>
<li><strong>Kemasan Master Carton 5-ply untuk Stick AA:</strong> Stik kayu manis diikat per bundel 1 kg menggunakan tali rafia food-grade, kemudian dimasukkan ke dalam karton bergelombang tebal (double wall 5-ply) berkapasitas 10 kg atau 25 kg.</li>
<li><strong>Kemasan Karung Goni Ganda / PP Woven untuk Broken KB:</strong> Karet dan serpihan kayu manis dikemas dalam karung goni laminasi rapat berbobot bersih 25 kg atau 50 kg dengan jahitan mesin ganda.</li>
<li><strong>Fumigasi Gas Fosfin (Phospine PH3 Standar AFAS):</strong> Dilakukan oleh perusahaan fumigasi bersertifikasi Badan Karantina Indonesia dengan dosis 2–3 g/m³ selama 120 jam pemaparan guna mengeliminasi seluruh stadia hama kutu gudang (<em>Lasioderma serricorne</em>).</li>
<li><strong>Penataan Muatan Palka Kapal (Under Deck Stowage):</strong> Kontainer rempah kayu manis wajib ditempatkan di palka bawah kapal (<em>under deck</em>) dan dijauhkan dari dinding ruang mesin/ketel uap (<em>away from boiler room</em>) guna mencegah pemanasan berlebih yang merusak minyak atsiri.</li>
<li><strong>Ventilasi Kontainer Kargo Kering:</strong> Menggunakan kontainer berventilasi (<em>passive ventilated container</em>) dengan sirkulasi udara stabil guna menjaga agar kadar air kayu manis tetap seimbang dan terhindar dari pertumbuhan jamur aflatoksin selama transit di laut lepas.</li>
</ul>

