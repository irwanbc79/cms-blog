<h2>Checklist 5 langkah audit kesiapan ekspor kayu manis cassia</h2>

<ol>
<li><strong>Verifikasi Grading &amp; Kadar Air Lot Produksi:</strong> Memastikan seluruh stik kayu manis memiliki kadar air di bawah 12% dan ukuran seragam sesuai sales contract.</li>
<li><strong>Pengujian Laboratorium Bebas Logam Berat &amp; Pestisida:</strong> Mengantongi Certificate of Analysis (CoA) parameter kimia dan mikrobiologi dari laboratorium terakreditasi KAN.</li>
<li><strong>Pengajuan Permohonan Pemeriksaan Karantina (PPK Online):</strong> Mengunggah dokumen pengapalan ke portal Barantin untuk penjadwalan inspeksi fisik dan sampling.</li>
<li><strong>Deklarasi Pabean PEB BC 3.0 CEISA 4.0:</strong> Memproses customs clearance ekspor melalui PPJK berlisensi resmi DJBC hingga terbit Nota Pelayanan Ekspor (NPE).</li>
<li><strong>Penerbitan Surat Keterangan Asal (e-SKA):</strong> Mengajukan Form B (Eropa/AS) atau Form D (ASEAN) pada portal e-SKA Kementerian Perdagangan RI.</li>
</ol>

