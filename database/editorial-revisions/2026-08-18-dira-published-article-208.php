<li>Akta serta perubahan terakhir.</li>
<li>NPWP dan alamat.</li>
<li>Penanggung jawab serta kewenangannya.</li>
<li>KBLI dan kegiatan usaha aktual.</li>
<li>Lokasi proyek, kantor, gudang, dan fasilitas bila relevan.</li>
<li>Email, telepon, serta akun yang dikelola perusahaan.</li>
