<p>Gunakan akun korporasi dan aktifkan kontrol akses yang tersedia. Jangan menyerahkan email utama, OTP, atau kredensial OSS kepada banyak penyedia jasa. Buat register pengguna, role, tanggal pemberian akses, dan pencabutan akses setelah pekerjaan selesai.</p>

<h2>Gate 2: terbitkan atau perbarui NIB secara benar</h2>

<p>Ikuti panduan OSS yang sesuai dengan kategori usaha dan kondisi data perusahaan. Jangan menyalin tutorial lama bila tampilan atau rezim perizinannya sudah berubah. Simpan versi dokumen yang diterbitkan, tanggal, data proyek, KBLI, serta perubahan yang dilakukan.</p>

<p>NIB adalah identitas usaha, tetapi bukan pengganti seluruh izin. Pastikan status NIB serta API yang tercermin sesuai tujuan impor. Bila hendak mengubah API-U menjadi API-P atau melakukan perubahan data lain, periksa syarat pada regulasi terakhir dan pastikan tidak ada realisasi atau perizinan yang membuat perubahan tidak dapat dilakukan pada saat itu.</p>

