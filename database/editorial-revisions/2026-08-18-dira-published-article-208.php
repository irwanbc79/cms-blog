<h2>Gate 6: kesiapan transaksi dan landed cost</h2>

<p>Sebelum purchase order final, hitung harga barang, freight, insurance, bea masuk, pajak impor, trade remedies bila ada, izin, surveyor, pemeriksaan, handling, storage, transportasi lokal, jasa profesional, dan buffer keterlambatan. Setiap tarif harus memiliki HS Code, sumber, tanggal, dan asumsi.</p>

<p>Pastikan kontrak supplier mengatur spesifikasi, dokumen, origin, perubahan model, keterlambatan, non-conformity, serta hak menahan pembayaran. API-U yang benar tidak memperbaiki invoice yang salah atau barang yang tidak sesuai izin.</p>

<h2>Bangun transaction dossier sebelum booking</h2>

<p>Satu shipment sebaiknya memiliki satu folder kendali yang dapat ditelusuri. Isinya minimal profil produk, korespondensi klasifikasi, hasil pemeriksaan lartas, salinan izin, purchase order, proforma atau commercial invoice, packing list, kontrak pengangkutan, dokumen asal bila digunakan, perhitungan landed cost, dan daftar keputusan. Beri nama versi dan tanggal pada setiap dokumen; file tanpa versi mudah tertukar ketika supplier melakukan revisi.</p>

<p>Lakukan rekonsiliasi silang sebelum booking: uraian barang pada invoice harus dapat dipetakan ke dossier dan izin; jumlah serta satuan harus selaras; nama importir, consignee, supplier, dan manufacturer tidak boleh berubah tanpa penjelasan; model atau part number pada dokumen harus sama dengan barang. Bila izin memakai batas kuota, pelabuhan tertentu, negara asal, masa berlaku, atau kewajiban survey, catat sisa dan tenggatnya.</p>

<p>Buat keputusan <em>go</em>, <em>hold</em>, atau <em>stop</em> secara tertulis. Status <em>go</em> hanya diberikan ketika pemilik keputusan menerima bukti bahwa identitas importir, API, akses kepabeanan, HS, lartas, izin, dokumen, dan biaya sudah konsisten. <em>Hold</em> dipakai bila bukti belum lengkap; <em>stop</em> dipakai bila struktur transaksi atau barang tidak dapat dipenuhi secara sah. Ini menghindari tekanan biaya demurrage dijadikan alasan untuk menerima risiko yang belum dihitung.</p>

<h2>Uji satu transaksi sebelum meningkatkan volume</h2>

<p>Importir baru sebaiknya tidak langsung menggandakan SKU dan volume hanya karena NIB telah aktif. Pilih transaksi awal yang dokumentasinya paling jelas, lalu catat waktu proses, koreksi dokumen, biaya aktual, temuan pemeriksaan, dan selisih landed cost. Hasil transaksi pertama menjadi dasar memperbaiki SOP, master produk, klausul supplier, serta matriks otorisasi sebelum skala dinaikkan. Keputusan ini bukan jaminan jalur pemeriksaan atau waktu pelepasan, tetapi membatasi dampak bila asumsi awal ternyata salah.</p>

