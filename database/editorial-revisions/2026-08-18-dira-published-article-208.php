<h2>Kesalahan yang sering tidak terlihat</h2>

<ul>
<li>Memakai NIB perusahaan lain atau struktur undername tanpa kontrak dan pembagian tanggung jawab yang jelas.</li>
<li>Memilih API-U padahal barang dipakai sendiri untuk produksi, atau sebaliknya.</li>
<li>KBLI dan kegiatan aktual tidak konsisten.</li>
<li>Akun OSS atau kepabeanan dikuasai mantan konsultan.</li>
<li>Menganggap API-U menghapus kebutuhan PI, LS, karantina, BPOM, SNI, atau lartas lain.</li>
<li>HS Code supplier dipakai tanpa dossier produk.</li>
<li>Invoice, izin, dan PIB memakai uraian, quantity, atau pihak yang berbeda.</li>
<li>Barang dikapalkan sebelum status izin dan kesiapan akses dinyatakan go.</li>
