<h2>Regulasi persetujuan lingkungan: AMDAL vs RKL-RPL Rinci (PP 22/2021)</h2>

<p>Kepatuhan hukum lingkungan hidup menentukan kelancaran operasional pabrik guna memitigasi potensi sanksi penyegelan:</p>

<ul>
<li><strong>Fasilitas di Dalam Kawasan Industri Terpadu (Kawasan AMDAL):</strong> Berdasarkan PP 22/2021, pabrik manufaktur yang berlokasi di dalam kawasan industri resmi yang telah memiliki AMDAL Kawasan tidak perlu menyusun dokumen AMDAL tersendiri. Perusahaan cukup menyusun dokumen <em>Rencana Pengelolaan dan Pemantauan Lingkungan Hidup (RKL-RPL Rinci)</em> yang diverifikasi oleh pengelola kawasan industri dan Dinas Lingkungan Hidup.</li>
<li><strong>Fasilitas Berdiri Sendiri (Stand-Alone Non-Kawasan):</strong> Wajib menyusun dokumen AMDAL penuh atau UKL-UPL mandiri, melalui sidang komisi penilai AMDAL, serta memperoleh Persetujuan Lingkungan dari Kementerian LHK sebelum PBG dapat diterbitkan.</li>
<li><strong>Kajian Pengelolaan Limbah B3 dan IPAL:</strong> Rincian sistem penampungan limbah beracun sementara (TPS B3) dan baku mutu pengolahan air limbah wajib dilampirkan secara utuh dalam dokumen studi kelayakan.</li>
<li><strong>Penilaian Aspek Sosial &amp; Pemberdayaan Masyarakat Sekitar:</strong> Analisis penyerapan tenaga kerja lokal dan program tanggung jawab sosial lingkungan (TJSL/CSR) untuk menjaga hubungan harmonis dengan masyarakat sekitar tapak proyek.</li>
</ul>

<h2>Checklist 5 tahapan pelaksanaan studi kelayakan proyek pabrik</h2>

<ol>
<li><strong>Tahap 1: Kajian Awal &amp; Pengumpulan Data Lapangan:</strong> Analisis pasar, survei calon lokasi lahan, uji laboratorium geoteknik tanah (N-SPT), dan pengecekan zonasi tata ruang (KKPR).</li>
<li><strong>Tahap 2: Konseptual Engineering &amp; Pemilihan Teknologi Mesin:</strong> Perancangan alur proses manufaktur, penentuan kapasitas mesin optimal, dan penyusunan anggaran rinci CAPEX &amp; OPEX.</li>
<li><strong>Tahap 3: Pemodelan Arus Kas Finansial &amp; Uji Sensitivitas:</strong> Perhitungan metrik investasi NPV, IRR, Payback Period, dan analisis skenario krisis kenaikan biaya.</li>
<li><strong>Tahap 4: Penyusunan Dokumen Lingkungan &amp; Pra-Perizinan:</strong> Penyusunan draf RKL-RPL Rinci / UKL-UPL, izin pembuangan air limbah, dan persetujuan Andalalin.</li>
<li><strong>Tahap 5: Finalisasi Feasibility Report &amp; Pengajuan Pembiayaan Bank:</strong> Penerbitan buku laporan studi kelayakan final berstandar <em>Bankable Report</em> untuk persetujuan dewan direksi dan komite kredit perbankan.</li>
</ol>

