<h2>Penyelidikan tanah geoteknik (N-SPT) &amp; keandalan pasokan utilitas energi</h2>

<p>Kajian teknis lokasi tapak pabrik wajib memastikan fondasi gedung kokoh dan infrastruktur utilitas tersedia tanpa hambatan:</p>

<ul>
<li><strong>Uji Penetrasi Standar (Standard Penetration Test / N-SPT):</strong> Pengeboran inti tanah (soil boring) di titik-titik kritis kolom utama hingga kedalaman tanah keras (N-SPT &gt; 50) untuk menentukan tipe fondasi terpilih: apakah cukup fondasi dangkal (footplate) atau wajib tiang pancang spun pile berdiameter 40–60 cm.</li>
<li><strong>Analisis Kebutuhan Daya Listrik PLN Tegangan Menengah (TM 20 kV):</strong> Menghitung total beban puncak mesin (kVA) dan merancang gardu trafo internal guna mengantisipasi biaya penambahan daya listrik industri.</li>
<li><strong>Pasokan Air Bersih Industri &amp; Pipa Gas Alam:</strong> Memastikan ketersediaan debit air baku (m³/hari) untuk cooling tower dan pipa jaringan transmisi gas bumi PGN bila pabrik membutuhkan energi pemanas boiler temperatur tinggi.</li>
<li><strong>Aksesibilitas Lalu Lintas Angkutan Berat (Andalalin):</strong> Melakukan Analisis Dampak Lalu Lintas (Andalalin) Kementerian Perhubungan untuk menjamin pergerakan truk trailer 40ft tidak mengganggu arus jalan raya umum di luar gerbang pabrik.</li>
</ul>

<h2>Pemodelan finansial: Discounted Cash Flow (DCF), NPV, IRR, dan Analisis Sensitivitas</h2>

<p>Kelayakan investasi diukur menggunakan metode Discounted Cash Flow (DCF) dengan tingkat suku bunga diskonto tertimbang (<em>Weighted Average Cost of Capital / WACC</em>):</p>

<ul>
<li><strong>Net Present Value (NPV):</strong> Nilai sekarang dari seluruh arus kas bersih di masa depan dikurangi total belanja modal awal (CAPEX). Proyek layak jika NPV bernilai positif.</li>
<li><strong>Internal Rate of Return (IRR):</strong> Tingkat suku bunga pengembalian internal yang menghasilkan NPV = 0. Proyek layak jika IRR melampaui batas minimum pengembalian (<em>Hurdle Rate / WACC</em>).</li>
<li><strong>Payback Period (PBP):</strong> Jangka waktu yang dibutuhkan oleh laba operasional bersih untuk menutup seluruh modal investasi awal yang dikeluarkan.</li>
<li><strong>Debt Service Coverage Ratio (DSCR):</strong> Rasio kemampuan laba operasional bersih (EBITDA) dalam melunasi pokok dan bunga pinjaman bank per tahun (target minimal DSCR &ge; 1,30x).</li>
<li><strong>Uji Sensitivitas Finansial (Sensitivity Stress Testing):</strong> Simulasi ketahanan proyek terhadap 3 skenario krisis: (1) Kenaikan biaya konstruksi CAPEX +15%, (2) Kenaikan harga bahan baku +10%, dan (3) Penurunan volume penjualan produk -15%.</li>
</ul>

