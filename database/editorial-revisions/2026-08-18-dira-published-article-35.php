<h2>Gate 4: periksa persyaratan produk di luar organik</h2>

<p>Sertifikasi organik tidak menggantikan ketentuan ekspor umum atau persyaratan komoditas. Kopi, rempah, beras, buah segar, bahan olahan, dan produk kelapa memiliki karakter risiko berbeda. Periksa klasifikasi, keamanan pangan, residu, kontaminan, label, registrasi fasilitas, karantina tumbuhan, perlakuan, fumigasi, kemasan kayu, dan persyaratan buyer sesuai produk serta negara tujuan.</p>

<p>Untuk komoditas tumbuhan, konfirmasikan persyaratan phytosanitary negara tujuan dan prosesnya dengan <a href="https://karantinaindonesia.go.id/" rel="noopener noreferrer" target="_blank">Badan Karantina Indonesia</a> sebelum booking. Sertifikat organik dan phytosanitary certificate memiliki tujuan berbeda; salah satunya tidak menggantikan yang lain.</p>

<h3>Pisahkan empat lapisan kepatuhan</h3>

<p>Tim sering memasukkan seluruh kebutuhan ke dalam satu kolom “sertifikat”. Padahal ada empat lapisan yang perlu pemilik dan approver berbeda. Pertama, organic integrity mencakup produksi, handling, traceability, serta klaim organik. Kedua, market access mencakup izin masuk, registrasi fasilitas, dan ketentuan importir. Ketiga, product conformity mencakup mutu, residu, kontaminan, komposisi, dan label. Keempat, shipment compliance mencakup dokumen ekspor, karantina, dokumen angkut, serta sertifikat yang harus melekat pada lot tertentu.</p>

<p>Buat register dengan kolom persyaratan, dasar atau permintaan buyer, penerbit, pemegang, produk, lokasi, masa berlaku, lead time, biaya, dan bukti pemenuhan. Hubungkan setiap baris dengan milestone purchase order, produksi, stuffing, cut-off dokumen, keberangkatan, dan arrival. Dengan pemisahan ini, sertifikat tahunan tidak keliru dianggap cukup untuk release setiap shipment.</p>

<h3>Uji satu lot sebelum skala komersial</h3>

<p>Untuk rantai pasok baru, jalankan pilot lot yang dapat ditelusuri dari kebun sampai dokumen penjualan. Rekonsiliasi kuantitas, uji prosedur segregasi, selesaikan artwork, dan lakukan document simulation bersama buyer serta certifier. Pilot bukan alasan untuk mengabaikan aturan; tujuannya menemukan gap pada volume dan risiko yang masih terkendali sebelum kontrak besar dibuat.</p>

<h2>Gate 5: release dokumen per shipment</h2>

<ol>
<li>Cocokkan lot, kuantitas, produk, exporter, consignee, dan negara tujuan dengan scope certificate.</li>
<li>Pastikan invoice, packing list, dokumen angkut, health atau phytosanitary document, dan sertifikat mutu menggunakan data yang konsisten.</li>
<li>Koordinasikan permintaan e-COI atau NOP Import Certificate sesuai lead time certifier.</li>
<li>Periksa draft label dan organic claim sebelum dicetak massal.</li>
<li>Jangan mengubah supplier, processor, warehouse, lot, atau route tanpa change review.</li>
<li>Berikan final document pack kepada buyer dan pihak clearance sebelum cut-off.</li>
<li>Simpan bukti release, sertifikat, komunikasi, dan rekonsiliasi lot sesuai retention policy.</li>
</ol>

<h2>Keputusan komersial sebelum mengeluarkan biaya</h2>

<p>Harga premium tidak boleh dijadikan asumsi. Minta buyer memberikan spesifikasi, formula harga, volume minimum, rejection criteria, jadwal order, dan pembagian biaya secara tertulis. Buat simulasi untuk skenario normal, volume turun, sertifikasi terlambat, corrective action, hasil laboratorium tidak sesuai, dan shipment ditunda.</p>

<p>Hitung biaya sertifikasi, inspection, audit tambahan, pengujian, segregasi gudang, perubahan kemasan, sertifikat per shipment, sample, freight, serta modal kerja. Proyek layak dilanjutkan bila margin dan demand yang terverifikasi mampu menanggung seluruh sistem kontrol, bukan hanya biaya sertifikat pertama.</p>

<h2>Checklist go, hold, atau stop</h2>

<ul>
<li><strong>Go:</strong> buyer, pasar, scope, certifier, traceability, label, dokumen shipment, dan economics sudah tervalidasi.</li>
<li><strong>Hold:</strong> buyer ada tetapi peran importir, scope certificate, atau certificate workflow belum tertulis.</li>
<li><strong>Redesign:</strong> produk menarik tetapi rantai pasok belum dapat menjaga segregasi dan mass balance.</li>
<li><strong>Stop:</strong> pihak meminta klaim organik tanpa sertifikasi yang berlaku, menggunakan sertifikat entitas lain, atau mengubah data untuk melewati kontrol.</li>
</ul>

