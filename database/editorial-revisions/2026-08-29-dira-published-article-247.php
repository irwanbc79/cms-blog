<h2>Prosedur pengupasan semi-husked, anti-jamur, dan sortasi</h2>

<p>Tahapan penanganan pascapanen untuk menjamin daya simpan kelapa hingga 45–60 hari masa transit pelayaran:</p>

<ul>
<li><strong>Teknik Pengupasan Sabut Semi-Husked:</strong> Mengupas sabut menggunakan parang lengkung atau mesin deshelling dengan menyisakan sedikit sabut (ketebalan 1–2 cm) melingkar di sekeliling mata kelapa untuk mencegah benturan tempurung.</li>
<li><strong>Pencucian &amp; Perlakuan Anti-Jamur Organik:</strong> Kelapa dibersihkan dari debu sabut lalu disemprot larutan asam sitrat food-grade atau ekstrak alami anti-kapang pada area mata kelapa guna mencegah pertumbuhan jamur selama perjalanan laut.</li>
<li><strong>Uji Kocok Slosh Test (Sortasi Total):</strong> Seluruh butir kelapa dikocok secara manual oleh tenaga ahli; kelapa yang tidak bersuara air (air bocor/kosong atau retak) langsung diafkir.</li>
<li><strong>Pengemasan Karung Jaring (PP Mesh Bag):</strong> Kelapa ditata rapi dalam karung jaring berpori (kapasitas 20 s.d. 25 butir per karung / berat sekitar 25 kg per karung) yang memungkinkan sirkulasi udara bebas.</li>
</ul>

<h2>Pengaturan temperatur kontainer reefer &amp; hilirisasi produk turunan sabut</h2>

<p>Manajemen logistik rantai dingin dan utilisasi produk samping kelapa:</p>

<ul>
<li><strong>Pengaturan Kontainer Reefer (Reefer Temperature Settings):</strong> Pengapalan jarak jauh di atas 14 hari pelayaran sangat direkomendasikan menggunakan kontainer berpendingin dengan suhu set point 10°C–12°C dan kelembaban relatif 70%–80% untuk menghentikan pertumbuhan tunas (germination) dan menjaga kesegaran daging buah.</li>
<li><strong>Pemanfaatan Serat Sabut (Coco Fiber HS 5305.00):</strong> Sabut hasil pengupasan diproses menggunakan mesin pemecah serat untuk menghasilkan serat sabut kelapa yang diekspor ke pabrik matras dan jok mobil di China.</li>
<li><strong>Pemanfaatan Serbuk Sabut (Cocopeat HS 2703.00):</strong> Dicuci (washed cocopeat dengan Electrical Conductivity / EC &lt; 0,5 mS/cm) lalu dipadatkan menjadi balok blok 5 kg untuk diekspor ke pembeli hortikultura rumah kaca di Korea Selatan dan Jepang.</li>
<li><strong>Penataan Sirkulasi Udara Stuffing Kontainer:</strong> Penataan karung jaring di dalam kontainer wajib memberikan celah ventilasi (chimney stacking) di bagian tengah dan atas guna memastikan panas respirasi buah dapat dibuang keluar selama pelayaran di perairan tropis.</li>
</ul>

<h2>Sertifikasi karantina Barantin &amp; protokol impor GACC China</h2>

<p>Kepatuhan regulasi karantina fitosanitari tumbuhan internasional:</p>

<ul>
<li><strong>Pemeriksaan Fisik Karantina Barantin (PPK Online):</strong> Petugas fungsional karantina memeriksa sampel kelapa untuk menjamin bebas dari kumbang moncong kelapa (<em>Rhynchophorus ferrugineus</em>) dan serangga pabean lainnya.</li>
<li><strong>Fumigasi Gas Fosfin (Phospine PH3 Standar AFAS):</strong> Kargo kelapa difumigasi selama 120 jam sebelum pemuatan untuk memenuhi protokol impor karantina GACC China dan Spices Board.</li>
<li><strong>Penerbitan Phytosanitary Certificate (KT-1):</strong> Sertifikat karantina tumbuhan resmi dari Badan Karantina Indonesia yang menyertai pengapalan.</li>
<li><strong>Fasilitas Pembebasan Bea Masuk ACFTA Form E:</strong> Penggunaan e-Form E memberikan pembebasan tarif bea masuk (0%) bagi importir kelapa di pelabuhan China.</li>
</ul>

