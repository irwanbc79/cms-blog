<h2>Checklist 6 langkah audit ekspor barang ke Timur Tengah</h2>

<ol>
<li><strong>Verifikasi Pos Tarif &amp; Registrasi SABER:</strong> Pastikan dokumen PCoC dan SCoC telah terbit di akun SABER importir sebelum kontainer dimuat di pelabuhan asal.</li>
<li><strong>Audit Pelabelan Dwibahasa (Arab-Inggris):</strong> Periksa kesesuaian label nama produk, negara asal (*Made in Indonesia*), dan tanda G-Mark pada kemasan.</li>
<li><strong>Pemeriksaan Fisik Dokumen V-Legal / Karantina:</strong> Pastikan sertifikat V-Legal dan stempel ISPM 15 telah terverifikasi di portal INSW.</li>
<li><strong>Penerbitan e-SKA Form IUAE-CEPA / Form B:</strong> Ajukan SKA segera setelah final Bill of Lading terbit agar berkas dapat diakses importir sebelum kapal sandar di pelabuhan Teluk.</li>
<li><strong>Transmisi PEB BC 3.0 di CEISA 4.0:</strong> Deklarasikan data nilai transaksi, berat kargo, dan nomor dokumen perizinan secara presisi untuk menghindari pemeriksaan fisik jalur merah.</li>
<li><strong>Manajemen Pengarsipan Pabean:</strong> Simpan seluruh berkas asli ekspor (PEB, NPE, SABER, SCoC, B/L) minimal 10 tahun untuk keperluan audit kepabeanan.</li>
</ol>

