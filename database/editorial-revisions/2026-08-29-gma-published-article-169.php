<h2>Gate 1: kepatuhan platform SABER SASO untuk pasar Arab Saudi</h2>

<p>Untuk mengekspor produk manufaktur non-pangan ke Arab Saudi, eksportir Indonesia wajib melalui alur sertifikasi digital pada portal SABER:</p>

<ol>
<li><strong>Klasifikasi Risiko Produk di SABER (HS Code Verification):</strong> Produk dikategorikan ke dalam Regulated Products (produk terikat regulasi teknis) atau Non-Regulated Products.</li>
<li><strong>Penerbitan Product Certificate of Conformity (PCoC):</strong> Untuk produk terikat regulasi (seperti furnitur, tekstil, deterjen, atau bahan bangunan), eksportir wajib menunjuk Badan Sertifikasi Terakreditasi SASO (<em>Notified Certification Body</em> seperti TUV, Intertek, SGS, Bureau Veritas) untuk menguji sampel produk di laboratorium terakreditasi ISO 17025. PCoC berlaku selama 1 tahun.</li>
<li><strong>Penerbitan Shipment Certificate of Conformity (SCoC):</strong> Setiap kali pengapalan kontainer akan diberangkatkan, importir/eksportir menerbitkan SCoC di portal SABER yang terikat langsung dengan nomor invoice dan packing list pengapalan tersebut. Dokumen SCoC diverifikasi otomatis oleh Bea Cukai Arab Saudi (ZATCA) melalui sistem Fasah.</li>
</ol>

<h2>Gate 2: sertifikasi G-Mark regional GCC untuk produk listrik dan mainan</h2>

<p>Berdasarkan Peraturan Teknis GSO, produk mainan anak (BD-131704-01) dan peralatan listrik tegangan rendah (BD-142004-05)—seperti kipas angin, blender, setrika, adaptor listrik, dan soket—wajib memiliki tanda kesesuaian <strong>G-Mark</strong>:</p>

<ul>
<li><strong>Uji Kesesuaian Standar Keselamatan &amp; EMC:</strong> Produk diuji terhadap standar keselamatan listrik IEC/GSO dan kompatibilitas elektromagnetik (EMC).</li>
<li><strong>Penandaan Label G-Mark &amp; QR Code:</strong> Setiap unit produk dan kemasan master box wajib mencantumkan simbol G-Mark beserta kode QR unik yang terhubung ke basis data sertifikasi GSO. Kargo tanpa tanda G-Mark sah akan langsung ditolak masuk di seluruh pelabuhan GCC.</li>
<li><strong>Bahasa Pelabelan:</strong> Buku petunjuk manual dan label peringatan keselamatan wajib tersedia dalam Bahasa Arab dan Bahasa Inggris.</li>
</ul>

<h2>Gate 3: pemanfaatan fasilitas tarif preferensi 0% IUAE-CEPA</h2>

<p>Perjanjian kemitraan ekonomi bilateral <a href="https://ditjenpki.kemendag.go.id" target="_blank" rel="noopener noreferrer">IUAE-CEPA</a> membuka akses pasar bebas Bea Masuk ke Uni Emirat Arab:</p>

<ul>
<li><strong>Penghapusan Tarif Bea Masuk:</strong> Lebih dari 90% pos tarif produk manufaktur Indonesia (termasuk tekstil, perhiasan, minyak nabati, kertas, furnitur, alas kaki) mendapatkan pembebasan Bea Masuk 0% di pelabuhan UEA (seperti Jebel Ali Dubai dan Khalifa Port Abu Dhabi).</li>
<li><strong>Penerbitan e-SKA Form IUAE-CEPA:</strong> Eksportir mengajukan Surat Keterangan Asal elektronik melalui portal e-SKA Kementerian Perdagangan RI dengan melampirkan final Invoice, Packing List, PEB, dan B/L.</li>
<li><strong>Aturan Pengapalan Langsung:</strong> Kargo wajib dikapalkan langsung dari Indonesia ke pelabuhan Uni Emirat Arab atau dilengkapi dokumen pengawasan pabean transit jika terjadi alih-kapal di hub perantara.</li>
</ul>

<h2>Gate 4: tata laksana kepabeanan ekspor (PMK 155/PMK.04/2022)</h2>

<p>Seluruh proses kepabeanan ekspor diselesaikan secara terpadu melalui sistem CEISA 4.0 Ekspor:</p>

<ol>
<li><strong>Transmisi PEB BC 3.0:</strong> Eksportir menginput rincian kargo, HS Code 8 digit, berat kotor/bersih, nilai FOB/CIF, nama kapal, dan nomor dokumen pelengkap ke sistem pabean.</li>
<li><strong>Penerbitan Nota Pelayanan Ekspor (NPE):</strong> Setelah validasi sistem pabean (Jalur Hijau) atau pemeriksaan fisik selesai (Jalur Merah), NPE terbit sebagai izin sah pemuatan peti kemas ke kapal pengangkut.</li>
<li><strong>Kepatuhan Regulasi Ekspor Kayu (V-Legal):</strong> Untuk ekspor furnitur dan produk olahan kayu, eksportir wajib melampirkan Dokumen V-Legal (Sistem Verifikasi Kelestarian Hasil Hutan / SVLK) yang terintegrasi di portal INSW.</li>
</ol>

