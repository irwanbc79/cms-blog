<h2>Alur kepabeanan ekspor: dari NIB hingga terbit Nota Pelayanan Ekspor (NPE)</h2>

<ol>
<li><strong>Tahap 1: Registrasi Hak Akses Kepabeanan Ekspor (NIB OSS RBA):</strong> Pelaku usaha wajib memastikan NIB aktif dengan hak akses kepabeanan ekspor yang terintegrasi pada sistem Single Submission CEISA 4.0 DJBC.</li>
<li><strong>Tahap 2: Verifikasi Ketentuan Lartas pada Portal INSW:</strong> Memeriksa apakah HS Code komoditas memerlukan dokumen persetujuan kementerian teknis (seperti ET Kemendag, Rekomendasi Kementan, atau V-Legal KLHK).</li>
<li><strong>Tahap 3: Pemeriksaan Karantina Komoditas (Barantin PPK Online):</strong> Komoditas pertanian, perikanan, dan kehutanan wajib diajukan permohonan pemeriksaan karantina untuk penerbitan Phytosanitary Certificate (PC) atau Health Certificate (HC).</li>
<li><strong>Tahap 4: Pengisian &amp; Transmisi PEB BC 3.0:</strong> PPJK resmi mengisi data eksportir, nomor invoice, packing list, jenis sarana pengangkut, pelabuhan muat/tujuan, pos tarif HS Code, dan nilai FOB pada sistem CEISA 4.0.</li>
<li><strong>Tahap 5: Analisis Profil Risiko &amp; Penerbitan NPE:</strong> Sistem otomasi DJBC menerbitkan respon kepabeanan:
<ul>
<li><strong>Jalur Hijau:</strong> Dokumen dinyatakan lengkap dan langsung terbit <em>Nota Pelayanan Ekspor (NPE)</em> tanpa pemeriksaan fisik barang.</li>
<li><strong>Jalur Merah:</strong> Terbit Pemberitahuan Pemeriksaan Fisik (PPF) untuk verifikasi kesesuaian jenis dan jumlah barang sebelum NPE diterbitkan.</li>
</ul>
</li>
<li><strong>Tahap 6: Pemasukan Kargo ke Kawasan Pabean (Customs Yard):</strong> Peti kemas masuk ke terminal pelabuhan menggunakan dokumen NPE untuk proses pemuatan (loading) ke kapal kargo internasional.</li>
</ol>

<h2>Fasilitas kepabeanan KITE &amp; kewajiban Devisa Hasil Ekspor (DHE SDA)</h2>

<p>Pemerintah menyediakan insentif fiskal sekaligus regulasi devisa untuk memperkuat daya saing industri ekspor nasional:</p>

<ul>
<li><strong>Kemudahan Impor Tujuan Ekspor (KITE Pembebasan / Pengembalian PMK 145/2022):</strong> Pembebasan bea masuk dan PPN tidak dipungut atas impor bahan baku yang diolah, dirakit, atau dipasang pada barang yang hasilnya 100% diekspor ke luar negeri.</li>
<li><strong>Kewajiban Devisa Hasil Ekspor Sumber Daya Alam (DHE SDA PP 36/2023):</strong> Eksportir komoditas sektor pertambangan, perkebunan, kehutanan, dan perikanan dengan nilai PEB minimal US$ 250.000 wajib menempatkan sedikitnya 30% devisa hasil ekspor di dalam sistem keuangan Indonesia (Rekening Khusus DHE SDA) selama paling singkat 3 bulan.</li>
<li><strong>Layanan Jalur Prioritas Mitra Utama Kepabeanan (MITA Ekspor):</strong> Fasilitas percepatan proses kepabeanan pabean bagi eksportir bereputasi tinggi yang memangkas waktu dwell time di pelabuhan.</li>
</ul>

<h2>Pemanfaatan Surat Keterangan Asal (SKA) &amp; penghematan bea masuk negara tujuan</h2>

<p>Penggunaan dokumen Surat Keterangan Asal (Certificate of Origin) memberikan keunggulan kompetitif bagi eksportir nasional:</p>

<ul>
<li><strong>SKA Preferensi (Form D, Form E, Form AK, Form IJEPA, Form RCEP):</strong> Memberikan fasilitas tarif bea masuk 0% atau tarif khusus di negara importir berdasarkan perjanjian perdagangan bebas (FTA), dibuktikan dengan pemenuhan <em>Rules of Origin (ROO)</em> kandungan lokal.</li>
<li><strong>SKA Non-Preferensi (Form B):</strong> Berfungsi sebagai bukti otentik negara asal barang murni Indonesia untuk memenuhi ketentuan kuota atau kebijakan perdagangan negara non-mitra FTA.</li>
<li><strong>Transmisi Elektronik e-COO:</strong> Diajukan melalui portal e-SKA Kementerian Perdagangan RI dan terhubung secara otomatis ke sistem bea cukai negara mitra via <em>ASEAN Single Window (ASW)</em>.</li>
</ul>

