<h2>Standar pengolahan higienis nira aren, pengeringan oven, dan pengayakan</h2>

<p>Tahapan pengolahan pascapanen bebas bahan kimia sintetis untuk menjamin kualitas butiran renyah:</p>

<ul>
<li><strong>Pengawetan Alami Nira di Pohon (Non-Sulfite Preservative):</strong> Perajin menggunakan kulit kayu manggis, serbuk kayu nangka, atau getah raru alami pada tabung bambu penderesan guna mencegah fermentasi asam nira tanpa menggunakan bahan kimia sintetis.</li>
<li><strong>Pemasakan &amp; Kristalisasi Nira:</strong> Nira aren disaring bertahap lalu dimasak dalam wajan stainless steel hingga mengental pekat, kemudian diaduk cepat saat pendinginan hingga membentuk kristal pasir renyah.</li>
<li><strong>Pengeringan Lanjutan Oven Konveksi:</strong> Kristal gula aren dikeringkan dalam oven bersuhu terkontrol 60°C–70°C selama 4–6 jam hingga kadar air mencapai titik aman di bawah 2,0% guna mencegah pertumbuhan mikroba.</li>
<li><strong>Pengayakan Saringan Getar Stainless Steel (Mesh 18):</strong> Memastikan seluruh butiran memiliki ukuran seragam, renyah, dan bebas dari butiran kasar yang belum mengkristal sempurna.</li>
</ul>

<h2>Sertifikasi organik internasional (USDA Organic, EU, JAS) &amp; kemasan barrier tinggi</h2>

<p>Kepatuhan sertifikasi dan integritas pengemasan pelayaran lintas samudra:</p>

<ul>
<li><strong>Sertifikasi Kelompok Tani Organik (ICS - Internal Control System):</strong> Kebun aren di kawasan hutan rakyat disertifikasi oleh lembaga sertifikasi organik internasional (seperti Control Union, Ceres, atau Eko-Sert) dengan ketertelusuran rantai pasok dari petani mitra hingga fasilitas packing house.</li>
<li><strong>Penerbitan Transaction Certificate (TC):</strong> Dokumen sertifikasi transaksi resmi yang diterbitkan per lot pengapalan untuk membuktikan keaslian produk organik kepada pembeli luar negeri.</li>
<li><strong>Kemasan Kedap Udara High-Barrier:</strong> Gula aren semut dikemas dalam inner bag aluminium foil tebal (atau plastik vacuum food-grade 100 micron) berkapasitas 5 kg atau 25 kg, kemudian dimasukkan ke dalam master carton tebal (double wall 5-ply) untuk mencegah higroskopisitas uap air laut.</li>
<li><strong>Sertifikasi Keamanan Pangan HACCP &amp; Halal BPJPH:</strong> Fasilitas pengolahan menerapkan prinsip Hazard Analysis and Critical Control Point (HACCP) dan mengantongi sertifikat Halal resmi BPJPH Kementerian Agama RI.</li>
<li><strong>Pengujian Mikrobiologi Bebas Cemaran Jamur:</strong> Laboratorium uji terakreditasi KAN memverifikasi bahwa total ragi dan kapang (<em>Yeast &amp; Molds</em>) berada di bawah 100 CFU/g serta bebas dari bakteri <em>Coliforms</em> dan <em>Salmonella</em>.</li>
<li><strong>Pelabelan Kemasan Ritel Internasional:</strong> Memenuhi ketentuan pelabelan informasi nilai gizi (<em>Nutrition Facts</em>), nomor registrasi sertifikasi organik, klaim indeks glikemik rendah, dan identitas negara asal Indonesia sesuai regulasi US FDA dan EU Food Information for Consumers (FIC).</li>
<li><strong>Proteksi Kelembaban Kontainer Kargo:</strong> Pemasangan silica gel food-grade dan kantong desiccant CaCl2 di sekeliling dinding kontainer guna menjaga kelembaban relatif udara palka tetap berada di bawah 65% selama transit laut menuju pelabuhan Eropa.</li>
</ul>

