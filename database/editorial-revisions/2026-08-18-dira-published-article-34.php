<h2>5. Kapasitas dan mutu: ukur kemampuan repeat</h2>

<p>Buyer tidak membeli kapasitas pada brosur. Ukur output mingguan, yield, rejection, supplier lead time, downtime, bottleneck, dan batch consistency. Pisahkan kapasitas teoritis dari kapasitas yang dapat dikirim tepat waktu dengan standar mutu yang disetujui.</p>

<p>Buat approved specification, incoming inspection, in-process control, final release, lot code, retain sample, complaint log, dan corrective action. Bila produk dibuat oleh beberapa UMKM, agregator harus menentukan satu standard, sistem lot, dan pihak yang berwenang menolak produk.</p>

<h2>6. Dokumen dan logistik: desain sebelum purchase order</h2>

<p>Tentukan incoterm setelah memahami biaya dan titik perpindahan risiko. Petakan siapa membuat invoice, packing list, PEB, origin document, certificate, shipping instruction, serta siapa memeriksa draft bill of lading. Gunakan master shipment data agar deskripsi, quantity, weight, marks, buyer, consignee, origin, dan nilai konsisten.</p>

<p>Bandingkan air, LCL, FCL, courier, atau consolidation berdasarkan sifat barang, ukuran, urgency, damage risk, customs route, dan economics. PPJK atau forwarder membantu sesuai kontrak, tetapi tidak menggantikan tanggung jawab pemilik data dan izin.</p>

<h2>7. Pembayaran: lindungi kas sebelum mengejar pertumbuhan</h2>

<p>Tentukan deposit, balance, open account, collection, letter of credit, atau instrumen lain berdasarkan nilai, buyer risk, negara, tenor, dokumen, dan kemampuan operasional. Periksa nama pemilik rekening, perubahan payment instruction, serta otorisasi internal sebelum refund atau transfer.</p>

<p>LPEI atau Indonesia Eximbank menyediakan produk pembiayaan, penjaminan, asuransi, dan jasa konsultasi sebagaimana tercantum pada <a href="https://www.indonesiaeximbank.go.id/product-services" rel="noopener noreferrer" target="_blank">Produk dan Jasa LPEI</a>. Ketersediaan program tidak berarti setiap UMKM otomatis memenuhi syarat; ajukan berdasarkan kebutuhan, cash-conversion cycle, dan kemampuan membayar.</p>

<h2>Rencana validasi 90 hari</h2>

<ol>
<li><strong>Hari 1–15:</strong> pilih satu SKU dan satu pasar, lengkapi scorecard, product dossier, compliance map, dan unit economics.</li>
<li><strong>Hari 16–30:</strong> bangun daftar 30 target account, verifikasi kontak, siapkan buyer pack, dan tetapkan qualification criteria.</li>
<li><strong>Hari 31–45:</strong> lakukan outreach terukur, catat respons, kebutuhan, objection, serta qualified opportunity.</li>
<li><strong>Hari 46–60:</strong> kirim sample hanya kepada buyer yang lolos, gunakan feedback form, dan hitung biaya akuisisi.</li>
<li><strong>Hari 61–75:</strong> negosiasikan specification, MOQ, harga, incoterm, payment, claim, dan dokumen.</li>
<li><strong>Hari 76–90:</strong> jalankan pilot bila seluruh gate kritis terpenuhi, lalu lakukan post-shipment review.</li>
</ol>

