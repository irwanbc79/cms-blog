<h2>1. Buyer dan demand: bedakan lead dari pembeli</h2>

<p>Nama di WhatsApp, inquiry marketplace, atau kartu nama pameran belum menjadi buyer. Buat buyer qualification record berisi legal entity, domain perusahaan, alamat, business registration, negara release, jenis usaha, PIC, decision maker, produk yang dibutuhkan, volume, target price, payment term, dan reference bila relevan.</p>

<p>Minta calon buyer mengonfirmasi spesifikasi, packaging, label, incoterm, port, forecast, sample process, dan acceptance criteria. Waspadai pergantian rekening, permintaan dokumen identitas di luar konteks, biaya registrasi tidak wajar, email yang meniru domain, serta tekanan mengirim barang sebelum term disepakati.</p>

<p><a href="https://www.inaexport.id/about" rel="noopener noreferrer" target="_blank">Inaexport</a> adalah direktori B2B resmi Ditjen Pengembangan Ekspor Nasional yang menghubungkan supplier Indonesia dengan buyer dan perwakilan perdagangan. Gunakan sebagai kanal lead generation, bukan sebagai pengganti due diligence.</p>

<h2>2. Product-market fit: uji acceptance, bukan selera internal</h2>

<p>“Unik”, “premium”, dan “khas Indonesia” bukan bukti buyer akan membayar. Buat comparison sheet terhadap tiga sampai lima produk yang benar-benar dijual di target market. Bandingkan format, bahan, ukuran, shelf life, certification, label, retail price reference, wholesale structure, minimum order, serta review pelanggan bila tersedia.</p>

<p>Gunakan sample dengan nomor versi dan form feedback. Catat siapa yang menguji, tanggal, attribute yang dinilai, pass-fail criteria, perubahan yang diminta, dan dampak biaya. Sample gratis tanpa decision process mudah menjadi aktivitas sibuk yang tidak menghasilkan purchase order.</p>

<h2>3. Compliance: petakan per SKU dan pasar</h2>

<p>Tidak ada daftar sertifikasi universal untuk semua UMKM. Halal, organic, food-safety management, test report, phytosanitary, standard produk, label, atau registrasi fasilitas berlaku sesuai produk, claim, pasar, dan pelaku rantai pasok. Sertifikat yang tidak diminta pasar atau tidak mencakup produk hanya menambah biaya.</p>

<p>Buat compliance matrix per SKU: HS Code kandidat, larangan atau pembatasan Indonesia, persyaratan negara tujuan, issuing agency, applicant, scope, biaya, lead time, masa berlaku, dan document timing. Direktorat Jenderal Bea dan Cukai menyediakan <a href="https://www.beacukai.go.id/klinik-ekspor" rel="noopener noreferrer" target="_blank">Klinik Ekspor</a> untuk konsultasi prosedur dan fasilitas kepabeanan UMKM. Keputusan produk tetap harus diverifikasi kepada instansi berwenang.</p>

<h2>4. Unit economics: hitung contribution margin per shipment</h2>

<p>Harga FOB atau CIF tidak sama dengan laba. Hitung revenue dikurangi produk, packaging export, testing, certification allocation, inland transport, stuffing, handling, document, forwarder, freight atau insurance sesuai incoterm, bank fee, marketplace fee, commission, FX buffer, claim reserve, dan financing cost.</p>

