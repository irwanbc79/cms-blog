<h2>Post-shipment review: putuskan scale, repair, atau exit</h2>

<p>Maksimal tujuh hari setelah delivery atau buyer acceptance, lakukan review bersama sales, produksi, finance, dan logistik. Bandingkan rencana dengan realisasi untuk quantity, lead time, biaya, margin, document amendment, damage, claim, payment, dan respons buyer. Jangan menutup pilot hanya dengan status “barang sudah sampai”.</p>

<p>Klasifikasikan akar masalah menjadi demand, product, process, supplier, compliance, logistics, atau buyer behavior. Setiap temuan harus memiliki corrective action, owner, due date, dan bukti closure. Perubahan harga atau MOQ tidak boleh diputuskan tanpa memperbarui unit economics dan buyer discussion.</p>

